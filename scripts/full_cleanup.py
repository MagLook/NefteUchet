"""Полная чистка тестовой базы от документов и записей TradeLedger."""
import win32com.client

BASE = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"

com = win32com.client.Dispatch("V83.COMConnector")
conn = com.Connect(f'File="{BASE}";Usr="{USER}";Pwd="{PWD}";')

print("=== Полная чистка тестовой базы от документов TradeLedger ===")
print()

# 1. Удалить все документы с комментарием TL|*
типы = ["ПриходныйКассовыйОрдер", "КомплектацияНоменклатуры",
        "ПеремещениеТоваров", "ОтчетОРозничныхПродажах"]
всего_удалено = 0
ошибок = 0

for тип in типы:
    Q = conn.NewObject("Запрос")
    Q.Текст = f'''ВЫБРАТЬ Ссылка ИЗ Документ.{тип}
    ГДЕ ВЫРАЗИТЬ(Комментарий КАК СТРОКА(200)) ПОДОБНО "TL|%"'''
    Sel = Q.Выполнить().Выбрать()
    n_тип = 0
    while Sel.Следующий():
        try:
            obj = Sel.Ссылка.ПолучитьОбъект()
            if obj.Проведен:
                obj.Записать()  # распровести
            obj.Удалить()
            n_тип += 1
        except Exception as e:
            ошибок += 1
            print(f"  Ошибка удаления {тип}: {e}")
    print(f"  {тип:30}: удалено {n_тип}")
    всего_удалено += n_тип

print(f"\nВсего документов удалено: {всего_удалено}, ошибок: {ошибок}")

# 2. Очистить регистр TL_СтатусыЗагрузки
print()
print("=== Очистка регистра TL_СтатусыЗагрузки ===")
try:
    НаборЗаписей = conn.РегистрыСведений.TL_СтатусыЗагрузки.СоздатьНаборЗаписей()
    НаборЗаписей.Записать()  # пустой набор без отбора = очистить всё? нет — нужен Прочитать всё
    # Альтернативно через цикл
    Q = conn.NewObject("Запрос")
    Q.Текст = "ВЫБРАТЬ КлючЗагрузки ИЗ РегистрСведений.TL_СтатусыЗагрузки"
    Sel = Q.Выполнить().Выбрать()
    n_рег = 0
    while Sel.Следующий():
        try:
            М = conn.РегистрыСведений.TL_СтатусыЗагрузки.СоздатьМенеджерЗаписи()
            М.КлючЗагрузки = str(Sel.КлючЗагрузки)
            М.Прочитать()
            М.Удалить()
            n_рег += 1
        except Exception as e:
            print(f"  Ошибка удаления записи: {e}")
    print(f"Удалено записей: {n_рег}")
except Exception as e:
    print(f"Ошибка чистки регистра: {e}")

