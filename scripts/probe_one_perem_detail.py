# -*- coding: utf-8 -*-
"""Подробно одно корпоративное перемещение (voucher или cards): что в ТЧ
и какие проводки реально создались."""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return ""


def fmt(n):
    return f"{n:,.2f}".replace(",", " ")


# Возьмём 2 свежих корпоративных перемещения (voucher и cards)
для_проверки = []
for суф in ["|voucher", "|cards"]:
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("М", "%" + суф)
    q.Текст = """
    ВЫБРАТЬ ПЕРВЫЕ 1
        Док.Ссылка КАК С, Док.Номер КАК Н,
        Док.Дата КАК Д, Док.Комментарий КАК К
    ИЗ Документ.ПеремещениеТоваров КАК Док
    ГДЕ Док.Дата >= ДАТАВРЕМЯ(2026,5,1,0,0,0)
      И Док.Дата <= ДАТАВРЕМЯ(2026,5,15,23,59,59)
      И ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО &М
      И Док.Проведен И НЕ Док.ПометкаУдаления
    УПОРЯДОЧИТЬ ПО Док.Дата УБЫВ
    """
    в = q.Выполнить().Выбрать()
    if в.Следующий():
        для_проверки.append((в.С, s(в.Н), s(в.К)))

for ссылка, ном, ком in для_проверки:
    print(f"\n{'='*90}")
    print(f"Перемещение №{ном.strip()}  Ком: {ком}")
    print('='*90)

    # Шапка
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("С", ссылка)
    q.Текст = """
    ВЫБРАТЬ
        Док.Дата КАК Д,
        Док.СкладОтправитель.Наименование КАК СО,
        Док.СкладПолучатель.Наименование КАК СП
    ИЗ Документ.ПеремещениеТоваров КАК Док
    ГДЕ Док.Ссылка = &С
    """
    в = q.Выполнить().Выбрать(); в.Следующий()
    print(f"  Дата: {в.Д}")
    print(f"  Отправитель: {s(в.СО)}  → Получатель: {s(в.СП)}")

    # ТЧ Товары
    q2 = conn.NewObject("Запрос")
    q2.УстановитьПараметр("С", ссылка)
    q2.Текст = """
    ВЫБРАТЬ
        ТЧ.Номенклатура.Наименование КАК Ном,
        ТЧ.Количество КАК Кол,
        ТЧ.СчетУчета.Код КАК СУ
    ИЗ Документ.ПеремещениеТоваров.Товары КАК ТЧ
    ГДЕ ТЧ.Ссылка = &С
    """
    print(f"  ТЧ Товары:")
    в2 = q2.Выполнить().Выбрать()
    while в2.Следующий():
        print(f"    {s(в2.Ном):<30}  {float(в2.Кол):>8.2f}  СчётУчёта={s(в2.СУ)}")

    # Проводки в Хозрасчетном
    q3 = conn.NewObject("Запрос")
    q3.УстановитьПараметр("С", ссылка)
    q3.Текст = """
    ВЫБРАТЬ
        Прв.СчетДт.Код КАК Дт, Прв.СчетКт.Код КАК Кт,
        Прв.Сумма КАК Σ, Прв.КоличествоДт КАК КолДт, Прв.КоличествоКт КАК КолКт
    ИЗ РегистрБухгалтерии.Хозрасчетный КАК Прв
    ГДЕ Прв.Регистратор = &С
    """
    в3 = q3.Выполнить().Выбрать()
    print(f"  Проводки:")
    есть = False
    while в3.Следующий():
        есть = True
        print(f"    Дт {s(в3.Дт):<10} Кт {s(в3.Кт):<10}  Σ={fmt(в3.Σ or 0):>14} ₽  КолДт={float(в3.КолДт or 0):.2f} КолКт={float(в3.КолКт or 0):.2f}")
    if not есть:
        print(f"    ⚠ нет проводок")
