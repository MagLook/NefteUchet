# -*- coding: utf-8 -*-
"""Проверить 6 ТТН-ключей со скриншота: есть ли документы в БД."""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return ""


КЛЮЧИ = [
    "TL|ТТН|15|210|7839348306|5",
    "TL|ТТН|15|8|156|3",
    "TL|ТТН|15|208|3830|2",
    "TL|ТТН|15|210|7839348306|5",  # повтор?
    "TL|ТТН|15|210|4012|2",
    "TL|ТТН|15|208|4384|2",
]

for ключ in КЛЮЧИ:
    print(f"\n=== {ключ} ===")

    # 1. Все записи в TL_СтатусыЗагрузки
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("К", ключ)
    q.УстановитьПараметр("М", ключ + "|%")
    q.Текст = """
    ВЫБРАТЬ КлючЗагрузки, Статус, ДатаЗагрузки, ТипДокумента
    ИЗ РегистрСведений.TL_СтатусыЗагрузки
    ГДЕ КлючЗагрузки = &К ИЛИ КлючЗагрузки ПОДОБНО &М
    """
    в = q.Выполнить().Выбрать()
    есть_в_рег = False
    while в.Следующий():
        есть_в_рег = True
        try: вр = в.ДатаЗагрузки.strftime("%d.%m %H:%M")
        except: вр = s(в.ДатаЗагрузки)
        print(f"  [регистр] {s(в.КлючЗагрузки):<42} {s(в.Статус):<12} {вр}  {s(в.ТипДокумента)}")
    if not есть_в_рег:
        print(f"  [регистр] нет записей")

    # 2. Документы в БД
    нашли = False
    for менеджер, краткое in [
        ("Документ.ПеремещениеТоваров", "Перемещ"),
        ("Документ.КомплектацияНоменклатуры", "Компл"),
    ]:
        q2 = conn.NewObject("Запрос")
        q2.УстановитьПараметр("М", ключ + "%")
        q2.Текст = f"""
        ВЫБРАТЬ Док.Номер, Док.Дата, Док.Проведен, Док.ПометкаУдаления, Док.Комментарий
        ИЗ {менеджер} КАК Док
        ГДЕ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО &М
        """
        в2 = q2.Выполнить().Выбрать()
        while в2.Следующий():
            нашли = True
            try: дт = в2.Дата.strftime("%d.%m")
            except: дт = s(в2.Дата)
            пр = "✓" if в2.Проведен else "○"
            пу = " ✗ПОМЕЧЕН" if в2.ПометкаУдаления else " (активен)"
            print(f"  [{краткое}]  {пр} №{s(в2.Номер).strip():<14} {дт}{пу}  ком: {s(в2.Комментарий)[:60]}")
    if not нашли:
        print(f"  [БД] документов нет")
