# -*- coding: utf-8 -*-
"""Probe 4 ТТН с скриншота: 5864, 6525, 6898, 6970 — что с ними в БД ГИГ."""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return ""


# Ищем по комментарию (ключ TL|ТТН|...) и по номеру в описании
ТТН_список = [
    ("5864", 208, "02.05"),
    ("6525", 210, "10.05"),
    ("6898", 208, "15.05"),
    ("6970", 208, "08.05"),
]

print("=" * 100)
print("Probe 4 ТТН с скриншота")
print("=" * 100)

# 1. Проверка TL_СтатусыЗагрузки
print("\n[1] Записи в TL_СтатусыЗагрузки")
print("-" * 100)
for номер, азс, дата in ТТН_список:
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Маска", f"TL|ТТН|15|{азс}|{номер}%")
    q.Текст = """
    ВЫБРАТЬ Рег.КлючЗагрузки, Рег.ДатаЗагрузки, Рег.Статус, Рег.ТипДокумента
    ИЗ РегистрСведений.TL_СтатусыЗагрузки КАК Рег
    ГДЕ Рег.КлючЗагрузки ПОДОБНО &Маска
    УПОРЯДОЧИТЬ ПО Рег.ДатаЗагрузки УБЫВ
    """
    в = q.Выполнить().Выбрать()
    print(f"\nТТН №{номер} АЗС {азс} ({дата}):")
    есть = False
    while в.Следующий():
        есть = True
        try: вр = в.ДатаЗагрузки.strftime("%d.%m %H:%M")
        except: вр = s(в.ДатаЗагрузки)
        print(f"  • {s(в.КлючЗагрузки):<40} {вр}  Статус={s(в.Статус)} тип={s(в.ТипДокумента)}")
    if not есть:
        print(f"  (нет записей в регистре)")

# 2. Документы по типам
print(f"\n\n[2] Документы по типам (поиск по КлючЗагрузки в комментарии)")
print("-" * 100)
ТИПЫ_ДОК = [
    ("Документ.ПоступлениеТоваровУслуг",     "ПТУ"),
    ("Документ.ПеремещениеТоваров",          "Перемещ"),
    ("Документ.КомплектацияНоменклатуры",    "Компл"),
]

for номер, азс, дата in ТТН_список:
    print(f"\nТТН №{номер} АЗС {азс} ({дата}) — документы в БП:")
    нашли = False
    for менеджер, краткое in ТИПЫ_ДОК:
        q = conn.NewObject("Запрос")
        q.УстановитьПараметр("Маска1", f"TL|ТТН|15|{азс}|{номер}%")
        q.УстановитьПараметр("Маска2", f"%TL|ТТН|15|{азс}|{номер}%")
        q.Текст = f"""
        ВЫБРАТЬ Док.Номер, Док.Дата, Док.Проведен, Док.ПометкаУдаления, Док.Комментарий
        ИЗ {менеджер} КАК Док
        ГДЕ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО &Маска1
           ИЛИ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО &Маска2
        """
        в = q.Выполнить().Выбрать()
        while в.Следующий():
            нашли = True
            ном = s(в.Номер).strip()
            try: дт = в.Дата.strftime("%d.%m.%Y")
            except: дт = s(в.Дата)
            пом = " [ПОМЕЧЕН]" if в.ПометкаУдаления else ""
            пр = "✓ ПРОВЕДЁН" if в.Проведен else "○ не проведён"
            print(f"  [{краткое}] №{ном:<14} {дт} {пр}{пом}")
            print(f"           ком: {s(в.Комментарий)[:90]}")
    if not нашли:
        print(f"  ⚠ НИ ОДНОГО документа не найдено")

# 3. TL_ОшибкиЗагрузки (свежие — после моего фикса cdd4512 / 81b71fe)
