# -*- coding: utf-8 -*-
"""Simple balance check via Остатки. Run: py -3.13-32 scripts/check_bu4.py"""
import pythoncom, io
pythoncom.CoInitialize()
import win32com.client

conn = win32com.client.Dispatch("V83.COMConnector")
ib = conn.Connect(r'File="D:\Users\magsp\GIG Base2";Usr="Гайворонская Татьяна";Pwd="12345"')

out = io.open(r"D:\Users\magsp\ELSYPLUS\NefteUchet\build\bu_check4.txt", "w", encoding="utf-8")

# Простые остатки - без виртуальной таблицы
# Через оборотно-сальдовую ведомость (движения по журналу)
out.write("=== Движения по 41.02 (последние 20) ===\n")
try:
    q = ib.NewObject("Query")
    q.Text = """ВЫБРАТЬ ПЕРВЫЕ 20
        Период, Регистратор, СуммаДт, КоличествоДт, СуммаКт, КоличествоКт,
        Субконто1.Наименование КАК Субконто1,
        Субконто2.Наименование КАК Субконто2
    ИЗ РегистрБухгалтерии.Хозрасчетный.ДвиженияССубконто(
        Период >= &Дата,
        СчетДт = &Счет ИЛИ СчетКт = &Счет,,,)
    УПОРЯДОЧИТЬ ПО Период УБЫВ"""
    q.УстановитьПараметр("Счет", ib.ПланыСчетов.Хозрасчетный.НайтиПоКоду("41.02"))
    from datetime import datetime
    q.УстановитьПараметр("Дата", datetime(2026, 3, 1))
    r = q.Выполнить().Выбрать()
    while r.Следующий():
        out.write(f"  {r.Период} [{r.Субконто1}] [{r.Субконто2}] Дт:{r.КоличествоДт}/{r.СуммаДт} Кт:{r.КоличествоКт}/{r.СуммаКт}\n")
except Exception as e:
    out.write(f"  Ошибка: {e}\n")

# Другой подход — прямые проводки
out.write("\n=== Проводки с 41.02 (последние 20) ===\n")
try:
    q2 = ib.NewObject("Query")
    q2.Text = """ВЫБРАТЬ ПЕРВЫЕ 20
        Период, СчетДт.Код КАК Дебет, СчетКт.Код КАК Кредит,
        Сумма, Количество, Регистратор.Представление КАК Документ
    ИЗ РегистрБухгалтерии.Хозрасчетный
    ГДЕ (СчетДт = &Счет ИЛИ СчетКт = &Счет) И Период >= &Дата
    УПОРЯДОЧИТЬ ПО Период УБЫВ"""
    q2.УстановитьПараметр("Счет", ib.ПланыСчетов.Хозрасчетный.НайтиПоКоду("41.02"))
    q2.УстановитьПараметр("Дата", datetime(2026, 3, 1))
    r2 = q2.Выполнить().Выбрать()
    while r2.Следующий():
        out.write(f"  {r2.Период} Дт:{r2.Дебет} Кт:{r2.Кредит} сумма:{r2.Сумма} кол:{r2.Количество} [{r2.Документ}]\n")
except Exception as e:
    out.write(f"  Ошибка: {e}\n")

out.close()
print("Saved to build/bu_check4.txt")
