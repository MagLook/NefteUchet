# -*- coding: utf-8 -*-
"""Одноразовая правка регистра TL_Настройки: полный маппинг 1..6 service_code → Номенклатура.
Удаляет ошибочный Топливо_100_*, добавляет 1, 4, 6."""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def установить(key, value, описание=""):
    мз = conn.NewObject("РегистрСведенийМенеджерЗаписи.TL_Настройки")
    мз.Ключ = key
    мз.Значение = value
    if описание:
        мз.Описание = описание
    мз.Записать(True)
    print(f"  ✓ {key:<32} = {value}")


def удалить(key):
    мз = conn.NewObject("РегистрСведенийМенеджерЗаписи.TL_Настройки")
    мз.Ключ = key
    мз.Прочитать()
    if мз.Выбран():
        мз.Удалить()
        print(f"  ✗ удалён {key}")


print("Удаление ошибочных Топливо_100_* (АИ-100 имеет service_code=1, не 100):")
для_удаления = ["Топливо_100_Литры", "Топливо_100_Тонны", "Топливо_100_Плотность"]
for k in для_удаления:
    удалить(k)

print("\nДобавление полного маппинга по справочнику STS:")

# service_code=1 — АИ-100
установить("Топливо_1_Литры", "АИ-100(л)", "АИ-100 (литры) по справочнику STS service_code=1")
установить("Топливо_1_Тонны", "АИ-100(т)", "АИ-100 (тонны)")
установить("Топливо_1_Плотность", "0.7600", "АИ-100 эталонная плотность (для проверки)")

# service_code=4 — АИ-98
установить("Топливо_4_Литры", "АИ-98(л)", "АИ-98 (литры) по справочнику STS service_code=4")
установить("Топливо_4_Тонны", "АИ-98(т)", "АИ-98 (тонны)")
установить("Топливо_4_Плотность", "0.7550", "АИ-98 эталонная плотность")

# service_code=6 — ДТ зимний
установить("Топливо_6_Литры", "Дизельное топливо ЗИМА (л)",
           "ДТ зимний (литры) по справочнику STS service_code=6")
установить("Топливо_6_Тонны", "Дизельное топливо ЗИМА (т)", "ДТ зимний (тонны)")
установить("Топливо_6_Плотность", "0.8400", "ДТ зимний эталонная плотность")

# service_code=7 — СУГ. В БП ГИГ нет номенклатуры — создаём через COM
# с шаблоном по образцу АИ-92(л)/АИ-92(т) (тот же НомГруппа, ВидНоменклатуры,
# единицы и т.п.)

def найти_образец(имя):
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Н", имя)
    q.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Номенклатура ГДЕ Наименование = &Н И НЕ ПометкаУдаления"
    в = q.Выполнить().Выбрать()
    return в.Ссылка if в.Следующий() else None

def создать_номенклатуру(имя_новой, образец_ссылка):
    # Проверим что её ещё нет
    есть = найти_образец(имя_новой)
    if есть is not None:
        print(f"  • {имя_новой:<30} уже есть, пропускаем создание")
        return есть
    объ = conn.Справочники.Номенклатура.СоздатьЭлемент()
    обр = образец_ссылка.ПолучитьОбъект()
    объ.Наименование = имя_новой
    # Копируем ключевые реквизиты по шаблону
    for реквизит in ["НоменклатурнаяГруппа", "ВидНоменклатуры", "СтавкаНДС",
                     "БазоваяЕдиницаИзмерения", "ЕдиницаИзмеренияМест",
                     "ЕдиницаДляОтчетов", "ИспользоватьХарактеристики",
                     "ИспользоватьСерии"]:
        try:
            setattr(объ, реквизит, getattr(обр, реквизит))
        except Exception:
            pass
    объ.Записать()
    print(f"  ✓ создано: {имя_новой}")
    return объ.Ссылка

print("\nСоздание СУГ в БП ГИГ:")
образец_л = найти_образец("АИ-92 (л)")
образец_т = найти_образец("АИ-92(т)")
if образец_л is None or образец_т is None:
    print("  ⚠ образец АИ-92 не найден — пропускаем создание СУГ")
else:
    создать_номенклатуру("СУГ (л)", образец_л)
    создать_номенклатуру("СУГ (т)", образец_т)

установить("Топливо_7_Литры", "СУГ (л)",
           "СУГ (литры) по справочнику STS service_code=7")
установить("Топливо_7_Тонны", "СУГ (т)", "СУГ (тонны)")
установить("Топливо_7_Плотность", "0.5500", "СУГ эталонная плотность (пропан-бутан)")

print("\nГотово. Проверка через запрос:")
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Ключ, Значение
ИЗ РегистрСведений.TL_Настройки
ГДЕ Ключ ПОДОБНО "Топливо_%"
УПОРЯДОЧИТЬ ПО Ключ
"""
в = q.Выполнить().Выбрать()
while в.Следующий():
    print(f"  {str(в.Ключ):<30} = {в.Значение}")
