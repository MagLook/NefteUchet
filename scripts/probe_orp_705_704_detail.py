# -*- coding: utf-8 -*-
"""Детально по ОРП ГИ0Г-000705 (20.05, смена 209/3880) и ГИ0Г-000704
(21.05, смена 209/3881): ТЧ Оплата, ошибки загрузки, статус.
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def fmt(num):
    return f"{num:,.2f}".replace(",", " ")


print("=" * 100)
print("Детальный probe ОРП ГИ0Г-000705 (смена 209/3880) и ГИ0Г-000704 (смена 209/3881)")
print("=" * 100)

q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    Док.Ссылка КАК Ссылка,
    Док.Номер  КАК Номер,
    Док.Дата   КАК Дата,
    Док.Проведен КАК Проведен,
    Док.СуммаДокумента КАК Сумма,
    Док.Комментарий КАК Ком,
    Док.Организация КАК Орг,
    Док.Склад КАК Склад
ИЗ Документ.ОтчетОРозничныхПродажах КАК Док
ГДЕ Док.Дата >= ДАТАВРЕМЯ(2026,5,20,0,0,0)
  И Док.Дата <= ДАТАВРЕМЯ(2026,5,22,23,59,59)
"""
в = q.Выполнить().Выбрать()
орп = []
while в.Следующий():
    орп.append({
        "ссылка": в.Ссылка,
        "ном": str(в.Номер).strip(),
        "дата": в.Дата,
        "пров": bool(в.Проведен),
        "сум": float(в.Сумма or 0),
        "ком": str(в.Ком or ""),
        "орг": str(в.Орг or "—"),
        "скл": str(в.Склад or "—"),
    })

for о in орп:
    зн = "✓ ПРОВЕДЁН" if о["пров"] else "○ НЕ ПРОВЕДЁН"
    print(f"\n{'═'*100}")
    print(f"  {зн}  ОРП №{о['ном']}  от {о['дата']}  СуммаДок={fmt(о['сум'])} ₽")
    print(f"  Организация: {о['орг']}")
    print(f"  Склад:       {о['скл']}")
    print(f"  Комментарий: {о['ком']}")
    print("─" * 100)

    # ТЧ Оплата
    q1 = conn.NewObject("Запрос")
    q1.УстановитьПараметр("Док", о["ссылка"])
    q1.Текст = """
    ВЫБРАТЬ ТЧ.ВидОплаты КАК Вид, ТЧ.СуммаОплаты КАК Сумма
    ИЗ Документ.ОтчетОРозничныхПродажах.Оплата КАК ТЧ
    ГДЕ ТЧ.Ссылка = &Док
    """
    в1 = q1.Выполнить().Выбрать()
    print("  ТЧ Оплата:")
    итог_опл = 0
    б_оплат = False
    while в1.Следующий():
        б_оплат = True
        вид = str(в1.Вид or "—")
        сум = float(в1.Сумма or 0)
        итог_опл += сум
        print(f"    {вид:<35}  {fmt(сум):>14} ₽")
    if not б_оплат:
        print("    (пусто)")
    print(f"    {'ИТОГО оплат':<35}  {fmt(итог_опл):>14} ₽")
    нал = о["сум"] - итог_опл
    if abs(нал) > 0.01:
        print(f"    {'Наличные (СуммаДок − Σ оплат)':<35}  {fmt(нал):>14} ₽")

    # ТЧ Товары — короткая сводка, сгруппировано по СтавкеНДС
    q2 = conn.NewObject("Запрос")
    q2.УстановитьПараметр("Док", о["ссылка"])
    q2.Текст = """
    ВЫБРАТЬ
        ТЧ.Номенклатура.Наименование КАК Ном,
        ТЧ.Количество КАК Кол,
        ТЧ.Сумма КАК Сум,
        ТЧ.СтавкаНДС КАК НДС
    ИЗ Документ.ОтчетОРозничныхПродажах.Товары КАК ТЧ
    ГДЕ ТЧ.Ссылка = &Док
    УПОРЯДОЧИТЬ ПО ТЧ.Сумма УБЫВ
    """
    в2 = q2.Выполнить().Выбрать()
    тов = []
    while в2.Следующий():
        тов.append((str(в2.Ном)[:40], float(в2.Кол or 0), float(в2.Сум or 0), str(в2.НДС or "—")))
    if тов:
        print(f"  ТЧ Товары ({len(тов)} строк):")
        for ном, кол, сум, ндс in тов[:8]:
            print(f"    {ном:<42}  {кол:>8.2f}  {fmt(сум):>12} ₽  НДС={ндс}")
        if len(тов) > 8:
            print(f"    ... ещё {len(тов)-8} строк")

# ───────────────────────────────────────────────────────────────────────
# Регистр TL_СтатусыЗагрузки за период
