# -*- coding: utf-8 -*-
"""Diagnose VAT mismatch in ОРП on GIG Base2 stand.

Контекст: аудит 22.05.2026 показал, что 178/178 проведённых ОРП дают
Σ(Кт 90.01.1 + Кт 90.03) ≈ СуммаДокумента × 1.18 (22% сверху, а не выделение).
Цель — установить корневую причину, выбрав вариант фикса (A/B/C) для
TL_СозданиеДокументов.bsl:ОбработатьСмену.

Запуск:
    py -3.13-32 scripts/probe_orp_vat_diagnosis.py [--doc ГИ0Г-001477]

Что делает:
  1) перечисляет реквизиты шапки Документ.ОтчетОРозничныхПродажах
     (есть ли СуммаВключаетНДС, какие розничные поля доступны);
  2) перечисляет реквизиты ТЧ Товары;
  3) для конкретного ОРП печатает шапку (СуммаВключаетНДС, ВидОперации,
     Склад, СуммаДокумента) и ТЧ Товары (Цена, Сумма, СтавкаНДС, СуммаНДС,
     ЦенаВРознице, СуммаВРознице, СтавкаНДСВРознице, СуммаНДСВРознице);
  4) читает проводки этого ОРП из РегистрБухгалтерии.Хозрасчетный и
     группирует по Дт/Кт;
  5) сводит «СуммаДокумента vs Σ проводок (90.01.1 + 90.03)» и печатает диагноз.
"""
import argparse, io, sys, pythoncom
sys.path.insert(0, __file__.rsplit("\\", 1)[0] if "\\" in __file__ else ".")
import _tl_config as cfg

pythoncom.CoInitialize()
import win32com.client

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

def _val(obj, name):
    """Получить значение поля COM-выборки/объекта 1С.
    pywin32 для полей типа Variant возвращает bound-method — нужно вызвать."""
    v = getattr(obj, name)
    try:
        return v() if callable(v) and not hasattr(v, "_oleobj_") else v
    except TypeError:
        return v

def num(obj, name, default=0.0):
    v = _val(obj, name)
    try:
        return float(v or default)
    except Exception:
        return float(default)

def s(obj, name, default=""):
    v = _val(obj, name)
    return str(v) if v is not None else default

ap = argparse.ArgumentParser()
ap.add_argument("--doc", default="ГИ0Г-001477",
                help="Номер ОРП для разбора (default: ГИ0Г-001477)")
ap.add_argument("--all", action="store_true",
                help="Прогнать сверку Σ проводок по всем ОРП периода 01-15.05")
args = ap.parse_args()

conn = win32com.client.Dispatch("V83.COMConnector")
ib = cfg.connect(conn)

print(f"=== Подключено к {cfg.BASE_PATH} ===\n")

# ---------- 1. Реквизиты ШАПКИ ----------
print("== 1. Реквизиты ШАПКИ Документ.ОтчетОРозничныхПродажах ==")
mdDoc = ib.Метаданные.Документы.Найти("ОтчетОРозничныхПродажах")
if mdDoc is None:
    print("  !! не найден")
else:
    has_sum_includes_vat = False
    has_vat_rate = False
    for rq in mdDoc.Реквизиты:
        flag = ""
        if rq.Имя == "СуммаВключаетНДС":
            has_sum_includes_vat = True
            flag = "  ⭐ КРИТИЧНО"
        if rq.Имя == "СтавкаНДС":
            has_vat_rate = True
            flag = "  ⭐"
        print(f"  - {rq.Имя} : {rq.Тип}{flag}")
    print(f"\n  Итог: СуммаВключаетНДС {'есть' if has_sum_includes_vat else 'НЕТ'},"
          f" СтавкаНДС в шапке {'есть' if has_vat_rate else 'НЕТ'}")

# ---------- 2. Реквизиты ТЧ Товары ----------
print("\n== 2. Реквизиты ТЧ Товары ==")
tcTovary = None
for tc in mdDoc.ТабличныеЧасти:
    if tc.Имя == "Товары":
        tcTovary = tc
        break
if tcTovary is None:
    print("  !! ТЧ Товары не найдена")
else:
    interesting = {"Цена", "Сумма", "СтавкаНДС", "СуммаНДС",
                   "ЦенаВРознице", "СуммаВРознице",
                   "СтавкаНДСВРознице", "СуммаНДСВРознице",
                   "СчетУчета", "СчетДоходов", "СчетРасходов",
                   "СчетУчетаНДСПоРеализации"}
    found = set()
    for rq in tcTovary.Реквизиты:
        if rq.Имя in interesting:
            found.add(rq.Имя)
            print(f"  - {rq.Имя}")
    print(f"  Не найдено в ТЧ: {sorted(interesting - found)}")
ROZN_FIELDS_EXIST = bool(found & {"ЦенаВРознице", "СуммаВРознице"})

# ---------- 3. Шапка конкретного ОРП ----------
# Серии номеров переиспользуются — берём ОРП с TL-комментарием за май 2026.
print(f"\n== 3. Шапка ОРП №{args.doc} (TL за май 2026, последний по дате) ==")
q = ib.NewObject("Query")
q.Text = """ВЫБРАТЬ ПЕРВЫЕ 1
    Д.Ссылка КАК Ссылка, Д.Номер, Д.Дата,
    Д.СуммаДокумента, Д.ВидОперации, Д.Склад,
    Д.Комментарий
ИЗ Документ.ОтчетОРозничныхПродажах КАК Д
ГДЕ Д.Номер = &Н И Д.Проведен И Д.Комментарий ПОДОБНО "TL|%"
УПОРЯДОЧИТЬ ПО Д.Дата УБЫВ"""
q.УстановитьПараметр("Н", args.doc)
r = q.Выполнить().Выбрать()
if not r.Следующий():
    # fallback: ищем любой TL-ОРП за май 2026
    print(f"  ! ОРП {args.doc} с TL-комментарием не найден, ищу любой TL-ОРП за май 2026...")
    q.Text = """ВЫБРАТЬ ПЕРВЫЕ 1
        Д.Ссылка КАК Ссылка, Д.Номер, Д.Дата,
        Д.СуммаДокумента, Д.ВидОперации, Д.Склад,
        Д.Комментарий
    ИЗ Документ.ОтчетОРозничныхПродажах КАК Д
    ГДЕ Д.Проведен И Д.Комментарий ПОДОБНО "TL|%"
        И Д.Дата >= ДАТАВРЕМЯ(2026, 5, 1)
        И Д.Дата <  ДАТАВРЕМЯ(2026, 5, 16)
    УПОРЯДОЧИТЬ ПО Д.Дата УБЫВ"""
    r = q.Выполнить().Выбрать()
    if not r.Следующий():
        print("  !! TL-ОРП за май 2026 не найден в этой базе")
        sys.exit(1)
ssylka = r.Ссылка
print(f"  Номер          : {s(r, 'Номер')}")
print(f"  Дата           : {s(r, 'Дата')}")
print(f"  СуммаДокумента : {num(r, 'СуммаДокумента'):.2f}")
print(f"  ВидОперации    : {s(r, 'ВидОперации')}")
print(f"  Склад          : {s(r, 'Склад')}")
print(f"  Комментарий    : {s(r, 'Комментарий')}")

# вычитать СуммаВключаетНДС и др. свойства напрямую через объект
obj = ssylka.ПолучитьОбъект()
for attr in ["СуммаВключаетНДС", "СтавкаНДС", "ВалютаДокумента",
             "СуммаВключаетНДСВРознице"]:
    try:
        val = getattr(obj, attr)
        print(f"  {attr:<25}: {val}")
    except Exception as e:
        print(f"  {attr:<25}: [реквизита нет / {e}]")

# ---------- 4. Строки ТЧ Товары ----------
print(f"\n== 4. ТЧ Товары ==")
q2 = ib.NewObject("Query")
q2.Text = """ВЫБРАТЬ
    Т.Номенклатура.Наименование КАК Ном,
    Т.Количество, Т.Цена, Т.Сумма,
    Т.СтавкаНДС, Т.СуммаНДС,
    Т.СчетУчета.Код КАК СчУч,
    Т.СчетДоходов.Код КАК СчДох,
    Т.СчетРасходов.Код КАК СчРас
ИЗ Документ.ОтчетОРозничныхПродажах.Товары КАК Т
ГДЕ Т.Ссылка = &С
УПОРЯДОЧИТЬ ПО Т.НомерСтроки"""
q2.УстановитьПараметр("С", ssylka)
rr = q2.Выполнить().Выбрать()
sum_tch = 0.0
sum_nds_tch = 0.0
print(f"  {'Номенклатура':<30} {'Кол':>10} {'Цена':>10} {'Сумма':>12} "
      f"{'СтНДС':>10} {'СумНДС':>10} {'СчУч':>6} {'СчДох':>7}")
while rr.Следующий():
    nom = s(rr, "Ном")[:30]
    kol = num(rr, "Количество"); cena = num(rr, "Цена")
    summ = num(rr, "Сумма"); snds = num(rr, "СуммаНДС")
    stnds = s(rr, "СтавкаНДС")[:10]; sch_uch = s(rr, "СчУч"); sch_doh = s(rr, "СчДох")
    print(f"  {nom:<30} {kol:>10.2f} {cena:>10.2f} {summ:>12.2f} "
          f"{stnds:>10} {snds:>10.2f} {sch_uch:>6} {sch_doh:>7}")
    sum_tch += summ
    sum_nds_tch += snds
print(f"\n  Σ ТЧ Сумма  = {sum_tch:.2f}")
print(f"  Σ ТЧ СумНДС = {sum_nds_tch:.2f}")

# ---------- 5. Проводки ----------
print(f"\n== 5. Проводки по ОРП №{args.doc} (РегистрБухгалтерии.Хозрасчетный) ==")
q3 = ib.NewObject("Query")
q3.Text = """ВЫБРАТЬ
    ЕСТЬNULL(Прв.СчетДт.Код, "") КАК ДтКод,
    ЕСТЬNULL(Прв.СчетКт.Код, "") КАК КтКод,
    Прв.Сумма КАК Сумма
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Прв
ГДЕ Прв.Регистратор = &С"""
q3.УстановитьПараметр("С", ssylka)
r3 = q3.Выполнить().Выбрать()
sum_9001 = 0.0
sum_9003 = 0.0
print(f"  {'Дт':>10} {'Кт':>10} {'Сумма':>14}")
while r3.Следующий():
    dt = s(r3, "ДтКод"); kt = s(r3, "КтКод"); sm = num(r3, "Сумма")
    print(f"  {dt:>10} {kt:>10} {sm:>14.2f}")
    if kt == "90.01.1":
        sum_9001 += sm
    if kt == "68.02":
        sum_9003 += sm
print(f"\n  Σ Кт 90.01.1 = {sum_9001:.2f}")
print(f"  Σ Кт 68.02   = {sum_9003:.2f} (= 90.03)")
print(f"  Σ обоих      = {sum_9001 + sum_9003:.2f}")

# ---------- 6. Диагноз ----------
print(f"\n== 6. ДИАГНОЗ ==")
sum_doc = num(r, "СуммаДокумента")
total = sum_9001 + sum_9003
diff = total - sum_doc
print(f"  СуммаДокумента : {sum_doc:.2f}")
print(f"  Σ(90.01.1+90.03): {total:.2f}")
print(f"  Расхождение    : {diff:+.2f} ({diff/sum_doc*100:+.2f}% от СуммаДок)")

if abs(diff) < 0.05:
    print("\n  ✅ Суммы сходятся — НДС посчитан правильно (выделение).")
elif 17 < diff/sum_doc*100 < 19:
    print("\n  ❌ Систематика 22/(100+22)=18.03% подтверждена → НДС начислен СВЕРХУ.")
    print("\n  Анализ:")
    siv = None
    try:
        siv = obj.СуммаВключаетНДС
    except Exception:
        pass
    print(f"    СуммаВключаетНДС шапки = {siv}")
    if siv:
        print("    → Реквизит шапки ИСТИНА, но проводки всё равно НДС сверху.")
        print("    → Гипотеза D: типовая ОбработкаПроведения для розничного режима")
        print("      берёт НДС не из ТЧ СуммаНДС, а считает сама от Цены × Количества")
        print("      по СтавкаНДС из карточки Номенклатуры. Проверить ВидСтавкиНДС")
        print("      в Catalog.Номенклатура для топлива (АИ-95 и т.п.) на боевой —")
        print("      если 'Общая' и СтавкаНДСПоУмолчанию=20, реальная ставка станет 22%")
        print("      по правилам перехода 2026, и НДС добавится сверху Сумма-без-НДС.")
    else:
        print("    → Реквизит шапки ЛОЖЬ. Если СуммаВключаетНДС в шапке есть в метаданных,")
        print("      нужно использовать прямое присваивание (УстановитьРеквизитБезопасно")
        print("      молчаливо проглотил) — заменить на Док.СуммаВключаетНДС = Истина.")
else:
    print(f"\n  ⚠ Расхождение нетипичное ({diff/sum_doc*100:+.2f}%). Требует ручного разбора.")

# ---------- 7. Опционально: пройти по всем 178 ОРП ----------
if args.all:
    print("\n\n== 7. Сверка по всем ОРП периода 01-15.05.2026 ==")
    q4 = ib.NewObject("Query")
    q4.Text = """ВЫБРАТЬ
        Д.Номер КАК Номер, Д.Дата, Д.СуммаДокумента,
        СУММА(ВЫБОР КОГДА Прв.СчетКт.Код = "90.01.1" ТОГДА Прв.Сумма ИНАЧЕ 0 КОНЕЦ) КАК С9001,
        СУММА(ВЫБОР КОГДА Прв.СчетКт.Код = "68.02"   ТОГДА Прв.Сумма ИНАЧЕ 0 КОНЕЦ) КАК С9003
    ИЗ Документ.ОтчетОРозничныхПродажах КАК Д
        ЛЕВОЕ СОЕДИНЕНИЕ РегистрБухгалтерии.Хозрасчетный КАК Прв
            ПО Прв.Регистратор = Д.Ссылка
    ГДЕ Д.Проведен И Д.Дата МЕЖДУ &НД И &КД
        И Д.Комментарий ПОДОБНО "TL|СМЕНА%"
    СГРУППИРОВАТЬ ПО Д.Номер, Д.Дата, Д.СуммаДокумента
    УПОРЯДОЧИТЬ ПО Д.Дата"""
    q4.УстановитьПараметр("НД", ib.XMLЗначение(__import__("datetime").datetime(2026, 5, 1)))
    q4.УстановитьПараметр("КД", ib.XMLЗначение(__import__("datetime").datetime(2026, 5, 15, 23, 59)))
    r4 = q4.Выполнить().Выбрать()
    cnt_ok = cnt_18 = cnt_other = 0
    while r4.Следующий():
        sd = float(r4.СуммаДокумента or 0)
        ssum = float(r4.С9001 or 0) + float(r4.С9003 or 0)
        if sd == 0:
            continue
        pct = (ssum - sd) / sd * 100
        if abs(pct) < 0.01:
            cnt_ok += 1
        elif 17 < pct < 19:
            cnt_18 += 1
        else:
            cnt_other += 1
            print(f"  ⚠ {r4.Номер} {r4.Дата:%d.%m}: СуммаДок {sd:.2f}, Σ {ssum:.2f}, {pct:+.2f}%")
    print(f"\n  Сошлось (±0.01%): {cnt_ok}")
    print(f"  Расхождение 18%:  {cnt_18}")
    print(f"  Иное:             {cnt_other}")
