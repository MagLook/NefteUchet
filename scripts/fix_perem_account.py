# -*- coding: utf-8 -*-
"""Одноразовая правка: поменять НовыйСчетУчета=41.01 → 41.02 во всех
канальных Перемещениях за 01-15.05 (voucher/cards/online/ledger).
Распровести → правка → провести заново."""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return ""


# 41.02 счёт
сч4102 = conn.NewObject("Запрос")
сч4102.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ ПланСчетов.Хозрасчетный ГДЕ Код = "41.02"'
вс = сч4102.Выполнить().Выбрать(); вс.Следующий()
СЧЁТ_4102 = вс.Ссылка
print(f"Счёт 41.02: {СЧЁТ_4102}")

# Список перемещений канальных
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Док.Ссылка КАК С, Док.Номер КАК Н, Док.Комментарий КАК К
ИЗ Документ.ПеремещениеТоваров КАК Док
ГДЕ Док.Дата >= ДАТАВРЕМЯ(2026,5,1,0,0,0)
  И Док.Дата <= ДАТАВРЕМЯ(2026,5,15,23,59,59)
  И Док.Проведен И НЕ Док.ПометкаУдаления
  И (ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО "%|voucher"
     ИЛИ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО "%|cards"
     ИЛИ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО "%|online"
     ИЛИ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО "%|ledger")
"""
в = q.Выполнить().Выбрать()
ссылки = []
while в.Следующий():
    ссылки.append((в.С, s(в.Н).strip(), s(в.К)))

print(f"Найдено канальных Перемещений к переправке: {len(ссылки)}")

исправлено = 0
ошибок = 0
для_правки = 0
без_правки = 0

for i, (ссылка, ном, ком) in enumerate(ссылки):
    if i % 25 == 0:
        print(f"  ... обработано {i}/{len(ссылки)}  (исправлено {исправлено}, ошибок {ошибок})")
    try:
        объ = ссылка.ПолучитьОбъект()
        # Проверим — есть ли строки с НовыйСчетУчета != 41.02
        нужна_правка = False
        for j in range(объ.Товары.Количество()):
            стр = объ.Товары.Получить(j)
            try:
                if стр.НовыйСчетУчета != СЧЁТ_4102:
                    нужна_правка = True
                    break
            except Exception:
                pass
        if not нужна_правка:
            без_правки += 1
            continue
        для_правки += 1
        # Распровести
        if объ.Проведен:
            объ.Записать(conn.РежимЗаписиДокумента.ОтменаПроведения)
            объ = ссылка.ПолучитьОбъект()
        # Поправить ТЧ
        for j in range(объ.Товары.Количество()):
            стр = объ.Товары.Получить(j)
            try: стр.НовыйСчетУчета = СЧЁТ_4102
            except Exception: pass
        # Провести
        объ.Записать(conn.РежимЗаписиДокумента.Проведение)
        исправлено += 1
    except Exception as e:
        ошибок += 1
        if ошибок <= 5:
            print(f"  ✗ {ном} ({ком}): {e}")

print()
print(f"Итого:")
print(f"  Обработано:    {len(ссылки)}")
print(f"  Уже было ОК:   {без_правки}")
print(f"  Требовало:     {для_правки}")
print(f"  Исправлено:    {исправлено}")
print(f"  Ошибок:        {ошибок}")
