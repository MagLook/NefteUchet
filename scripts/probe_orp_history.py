# 1. ОРП за март-апрель по всем АЗС: дата, склад, сумма, комментарий, кто создал
hr("1) Все ОРП за март-апрель 2026 — кто, когда, какая сумма, есть ли наш ключ TL|СМЕНА")
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    ОРП.Дата,
    ОРП.Номер,
    ОРП.Склад.Наименование КАК Склад,
    ОРП.СуммаДокумента,
    ОРП.Комментарий,
    ОРП.Ответственный.Наименование КАК Ответственный,
    ОРП.Проведен
ИЗ Документ.ОтчетОРозничныхПродажах КАК ОРП
ГДЕ ОРП.Дата МЕЖДУ &Н1 И &Н2
УПОРЯДОЧИТЬ ПО ОРП.Дата
"""
q.УстановитьПараметр("Н1", datetime.datetime(2026,3,1,0,0,0))
q.УстановитьПараметр("Н2", datetime.datetime(2026,5,1,0,0,0))
sel = q.Выполнить().Выбрать()

by_warehouse_march = {}
by_warehouse_april = {}
tl_count = 0
manual_count = 0
while sel.Следующий():
    d = sel.Дата
    sklad = str(sel.Склад)
    sum_ = float(sel.СуммаДокумента or 0)
    com_ = str(sel.Комментарий or "")
    is_tl = "TL|СМЕНА" in com_ or "TL|CMEHA" in com_
    if is_tl: tl_count += 1
    else: manual_count += 1
    bucket = by_warehouse_march if d.month == 3 else by_warehouse_april
    a = bucket.setdefault(sklad, {"cnt":0, "sum":0.0, "tl":0, "manual":0})
    a["cnt"] += 1
    a["sum"] += sum_
    if is_tl: a["tl"] += 1
    else: a["manual"] += 1

print(f"\nВсего ОРП за период: TL-канал={tl_count}, ручные={manual_count}")
print("\nМарт 2026 по складам:")
print(f"  {'Склад':25} {'ОРП':>4} {'TL':>4} {'Ручн':>4} {'Σ ₽':>16}")
for s, a in sorted(by_warehouse_march.items()):
    print(f"  {s:25} {a['cnt']:>4} {a['tl']:>4} {a['manual']:>4} {a['sum']:>16.2f}")
print("\nАпрель 2026 по складам:")
print(f"  {'Склад':25} {'ОРП':>4} {'TL':>4} {'Ручн':>4} {'Σ ₽':>16}")
for s, a in sorted(by_warehouse_april.items()):
    print(f"  {s:25} {a['cnt']:>4} {a['tl']:>4} {a['manual']:>4} {a['sum']:>16.2f}")

