def main():
    парсер = argparse.ArgumentParser()
    парсер.add_argument("--only-json", action="store_true",
                        help="Только сформировать JSON, не загружать в БП ГИГ")
    парсер.add_argument("--номер", default=ETALON_NOMER)
    args = парсер.parse_args()

    print("=" * 76)
    print(f"  СРЕЗ 3: kind=production_release + ingredients_writeoff на эталоне {args.номер}")
    print("=" * 76)

    # [1] Чтение ВыпускПродукции
    print(f"\n[1/5] Чтение ВыпускПродукции {args.номер} из ЦБ ЭЛСИ.АЗК...")
    шапка, товары, ингредиенты = прочитать_выпуск_из_цб(args.номер)
    print(f"  Дата:        {шапка['Дата']}")
    print(f"  Сумма:       {шапка['СуммаДокумента']:,.2f}")
    print(f"  Продукция:   {len(товары)}")
    print(f"  Ингредиенты: {len(ингредиенты)}")

    if abs(шапка["СуммаДокумента"] - EXPECTED_SUM) > 0.01:
        print(f"  [WARN] Сумма не совпадает с эталоном {EXPECTED_SUM}")
    if len(товары) != EXPECTED_PRODUCTS:
        print(f"  [WARN] Продукции {len(товары)} ≠ эталон {EXPECTED_PRODUCTS}")
    if len(ингредиенты) != EXPECTED_INGREDIENTS:
        print(f"  [INFO] Ингредиентов {len(ингредиенты)} (эталон 51, может отличаться из-за временного разрыва — это OK, см. project_obshepit_51_42_resolved)")

    # Связи продукция↔ингредиенты через ИдентификаторПродукция
    связи = {}
    for инг in ингредиенты:
        ип = инг["ИдентификаторПродукция"]
        связи[ип] = связи.get(ип, 0) + 1
    print(f"  Связей продукция→ингредиенты: {len(связи)} уникальных ID")

    # [2] Формирование JSON
    print("\n[2/5] Формирование JSON-пакета...")
    пакет, package_id, док_хеш = сформировать_пакет(шапка, товары, ингредиенты)
    print(f"  ИдентификаторПакета: {package_id}")
    print(f"  ХешДокумента:       {док_хеш[:16]}...")
    print(f"  НСИ-объектов:       {len(пакет['НСИ'])}")

    # [3] Сохранение
    print("\n[3/5] Сохранение пакета...")
    путь = сохранить_пакет(пакет, package_id)
    print(f"  {путь}")

    if args.only_json:
        print("\n[STOP] --only-json: загрузка в БП ГИГ пропущена")
        return 0

    # [4] Загрузка
    print("\n[4/5] Загрузка в БП ГИГ...")
    результат = загрузить_в_бп_гиг(путь)
    if результат is None:
        print("\n[5/5] Проверка пропущена — kind production_release ещё не реализован")
        return 1

    print("\n[5/5] TODO: проверка ОтчетПроизводстваЗаСмену в БП ГИГ + проводки 41.02/44.01")
    return 0


if __name__ == "__main__":
    sys.exit(main())
