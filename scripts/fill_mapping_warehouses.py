# -*- coding: utf-8 -*-
"""Дозаливка складов в существующие записи TL_МаппингОплат:
для канала cards/online/ledger/voucher проставляем склад из настроек канала."""
import sys, io, win32com.client
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

BASE_PATH = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"; PWD = "12345"

com = win32com.client.Dispatch("V83.COMConnector")
conn = com.Connect(f'File="{BASE_PATH}";Usr="{USER}";Pwd="{PWD}";')

# 1) Подтянуть имена складов канала из настроек
q = conn.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ Ключ, Значение ИЗ РегистрСведений.TL_Настройки ГДЕ Ключ ПОДОБНО &Шаб"
q.УстановитьПараметр("Шаб", "Оплата_%_Склад")
sel = q.Выполнить().Выбрать()
канал_имя_склада = {}
while sel.Следующий():
    k = str(sel.Ключ)  # "Оплата_cards_Склад"
    канал = k.replace("Оплата_", "").replace("_Склад", "")
    имя = str(sel.Значение)
    канал_имя_склада[канал] = имя

print("Склады каналов из настроек:")
for канал, имя in канал_имя_склада.items():
    print(f"  {канал}: {имя!r}")

def найти_склад(имя):
    if not имя:
        return None
    ссылка = conn.Справочники.Склады.НайтиПоНаименованию(имя, True)
    return ссылка if str(ссылка) else None

канал_склад_ссылка = {канал: найти_склад(имя) for канал, имя in канал_имя_склада.items()}

# 2) Пройти по всем записям TL_МаппингОплат и проставить склад если пуст
print("\nДозаливка складов в маппинг:")
q = conn.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ ОбразецИмени, КаналОплаты, Склад ИЗ РегистрСведений.TL_МаппингОплат УПОРЯДОЧИТЬ ПО Приоритет"
sel = q.Выполнить().Выбрать()
обновлено = 0
while sel.Следующий():
    канал = str(sel.КаналОплаты)
    if канал in ("", "retail_cash", "retail_card"):
        # склад не нужен
        continue
    if str(sel.Склад) and sel.Склад is not None:
        try:
            пуст = bool(sel.Склад.Пустая())
        except Exception:
            пуст = False
        if not пуст:
            print(f"  УЖЕ: {sel.ОбразецИмени:14} → {канал:12} → {sel.Склад}")
            continue
    целевой = канал_склад_ссылка.get(канал)
    if not целевой:
        print(f"  НЕТ СКЛАДА для канала {канал} (образец {sel.ОбразецИмени})")
        continue
    мн = conn.РегистрыСведений.TL_МаппингОплат.СоздатьМенеджерЗаписи()
    мн.ОбразецИмени = sel.ОбразецИмени
    мн.Прочитать()
    if not мн.Выбран():
        continue
    мн.Склад = целевой
    мн.Записать()
    обновлено += 1
    print(f"  ОБНОВЛЕНО: {sel.ОбразецИмени:14} → {канал:12} → {целевой}")

print(f"\nИтого обновлено записей: {обновлено}")
