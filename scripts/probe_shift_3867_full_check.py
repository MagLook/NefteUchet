# -*- coding: utf-8 -*-
"""Полный probe смены 209/3867 от 07.05.2026 — особенно канал Прочие
(writeoff_fuel → СписаниеТоваров).
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return "—"
    try: return str(v)
    except Exception: return repr(v)


def fmt(n):
    return f"{n:,.2f}".replace(",", " ")


def fmt_date(d):
    try: return d.strftime("%d.%m.%Y %H:%M")
    except Exception: return str(d)


print("=" * 100)
print("Probe смены 209/3867 от 07.05.2026 (Прочие должны быть)")
print("=" * 100)

# 1. TL_СтатусыЗагрузки по этой смене
print("\n[1] TL_СтатусыЗагрузки для 3867")
print("-" * 100)
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    Рег.КлючЗагрузки КАК Ключ,
    Рег.ДатаЗагрузки КАК ДатаЗ,
    Рег.Статус       КАК Статус,
    Рег.ТипДокумента КАК ТипДок
ИЗ РегистрСведений.TL_СтатусыЗагрузки КАК Рег
ГДЕ Рег.КлючЗагрузки ПОДОБНО "%3867%"
УПОРЯДОЧИТЬ ПО Рег.ДатаЗагрузки УБЫВ
"""
в = q.Выполнить().Выбрать()
н = 0
while в.Следующий():
    н += 1
    print(f"  [{н}] {fmt_date(в.ДатаЗ):<22}  Статус={s(в.Статус):<12}  ТипДок={s(в.ТипДок):<15}  Ключ={s(в.Ключ)}")
if н == 0:
    print("  (записей нет)")

# 2. Все документы по смене 3867
print("\n\n[2] Все документы со смены 3867 (по комментарию)")
print("-" * 100)

ТИПЫ = [
    ("Документ.ОтчетОРозничныхПродажах", "ОРП"),
    ("Документ.ПеремещениеТоваров",      "Перемещ."),
    ("Документ.СписаниеТоваров",         "Списание"),
    ("Документ.ПриходныйКассовыйОрдер",  "ПКО"),
]

по_типам = {}
for менеджер, краткое in ТИПЫ:
    q = conn.NewObject("Запрос")
    q.Текст = f"""
    ВЫБРАТЬ
        Док.Ссылка     КАК Ссылка,
        Док.Номер      КАК Ном,
        Док.Дата       КАК Дата,
        Док.Проведен   КАК Пров,
        Док.Комментарий КАК Ком
    ИЗ {менеджер} КАК Док
    ГДЕ Док.Комментарий ПОДОБНО "%3867%"
    УПОРЯДОЧИТЬ ПО Док.Дата
    """
    в = q.Выполнить().Выбрать()
    строки = []
    while в.Следующий():
        строки.append({
            "ссылка": в.Ссылка, "ном": s(в.Ном).strip(),
            "дата": fmt_date(в.Дата), "пров": bool(в.Пров), "ком": s(в.Ком),
        })
    if строки:
        по_типам[краткое] = строки
        print(f"\n  === {краткое}: {len(строки)} ===")
        for ст in строки:
            зн = "✓ ПРОВЕДЁН" if ст["пров"] else "○ НЕ проведён"
            print(f"    {зн}  №{ст['ном']:<14}  {ст['дата']}")
            print(f"       Комментарий: {ст['ком']}")

# 3. Детально СписаниеТоваров для Прочих
print("\n\n[3] Детальный анализ СписаниеТоваров (канал writeoff_fuel)")
print("=" * 100)

if "Списание" not in по_типам:
    print("  ⚠ СписаниеТоваров для смены 3867 НЕ найдено")
else:
    for доку in по_типам["Списание"]:
        print(f"\n  СписаниеТоваров №{доку['ном']} ({доку['дата']})")
        print(f"  Проведён: {'ДА' if доку['пров'] else 'НЕТ'}")
        print(f"  Комментарий: {доку['ком']}")

        # Шапка
        qx = conn.NewObject("Запрос")
        qx.УстановитьПараметр("Док", доку["ссылка"])
        qx.Текст = """
        ВЫБРАТЬ
            Док.Организация.Наименование КАК Орг,
            Док.Склад.Наименование       КАК Скл,
            Док.ВидОперации              КАК ВО,
            Док.Ответственный.Наименование КАК Отв
        ИЗ Документ.СписаниеТоваров КАК Док
        ГДЕ Док.Ссылка = &Док
        """
        в = qx.Выполнить().Выбрать()
        в.Следующий()
        print(f"  Организация:  {s(в.Орг)}")
        print(f"  Склад:        {s(в.Скл)}")
        print(f"  ВидОперации:  {s(в.ВО)}")
        print(f"  Ответственный: {s(в.Отв)}")

        # Попытка провести этот документ
        if not доку["пров"]:
            print(f"\n  >>> Попытка провести вручную:")
            try:
                объ = доку["ссылка"].ПолучитьОбъект()
                объ.Записать(conn.РежимЗаписиДокумента.Проведение)
                print(f"  ✓ ПРОВЕДЕНО успешно")
                # Перечитаем доку как проведённый
                доку["пров"] = True
            except Exception as e:
                print(f"  ✗ ОШИБКА проведения: {e}")

        # ТЧ Товары
        q2 = conn.NewObject("Запрос")
        q2.УстановитьПараметр("Док", доку["ссылка"])
        q2.Текст = """
        ВЫБРАТЬ
            ТЧ.Номенклатура.Наименование КАК Ном,
            ТЧ.Количество КАК Кол,
            ТЧ.Сумма КАК Сум,
            ТЧ.СчетУчета.Код КАК Счёт
        ИЗ Документ.СписаниеТоваров.Товары КАК ТЧ
        ГДЕ ТЧ.Ссылка = &Док
        """
        в2 = q2.Выполнить().Выбрать()
        print(f"  ТЧ Товары:")
        итог_л = 0
        итог_сум = 0
        н_строк = 0
        while в2.Следующий():
            н_строк += 1
            кол = float(в2.Кол or 0)
            сум = float(в2.Сум or 0)
            итог_л += кол
            итог_сум += сум
            print(f"    • {s(в2.Ном):<35}  {кол:>10.2f} л   {fmt(сум):>14} ₽   счёт {s(в2.Счёт)}")
        if н_строк > 0:
            print(f"    ─────────────────────────────────────────────────────────────────────")
            print(f"    ИТОГО: {итог_л:.2f} л / {fmt(итог_сум)} ₽")

        # Проводки
        q3 = conn.NewObject("Запрос")
        q3.УстановитьПараметр("Док", доку["ссылка"])
        q3.Текст = """
        ВЫБРАТЬ
            Прв.СчетДт.Код КАК Дт,
            Прв.СчетКт.Код КАК Кт,
            Прв.Сумма КАК Сумма,
            Прв.Содержание КАК Сод,
            Прв.КоличествоДт КАК КолДт,
            Прв.КоличествоКт КАК КолКт
        ИЗ РегистрБухгалтерии.Хозрасчетный КАК Прв
        ГДЕ Прв.Регистратор = &Док
        """
        в3 = q3.Выполнить().Выбрать()
        провод = []
        while в3.Следующий():
            провод.append((s(в3.Дт), s(в3.Кт), float(в3.Сумма or 0),
                          float(в3.КолДт or 0), float(в3.КолКт or 0), s(в3.Сод)))
        print(f"  Проводки ({len(провод)}):")
        if not провод:
            if доку["пров"]:
                print(f"    ⚠ Проведён, но проводок в РегистрБухгалтерии.Хозрасчетный нет (учётная политика стенда?)")
            else:
                print(f"    (документ не проведён → проводок нет)")
        else:
            for дт, кт, сум, кд, кк, сод in провод:
                кол_инф = ""
                if кд > 0: кол_инф = f"   КолДт={кд:.2f}"
                elif кк > 0: кол_инф = f"   КолКт={кк:.2f}"
                print(f"    Дт {дт:<8} Кт {кт:<8} {fmt(сум):>14} ₽{кол_инф}   {сод[:50]}")

        # Регистры накопления
        for имя_рег in ["ТоварыНаСкладах", "ТоварыОрганизаций"]:
            qr = conn.NewObject("Запрос")
            qr.УстановитьПараметр("Док", доку["ссылка"])
            qr.Текст = f"""
            ВЫБРАТЬ
                Рег.ВидДвижения КАК ВД,
                Рег.Номенклатура.Наименование КАК Ном,
                Рег.Склад.Наименование КАК Скл,
                Рег.Количество КАК Кол
            ИЗ РегистрНакопления.{имя_рег} КАК Рег
            ГДЕ Рег.Регистратор = &Док
            """
            try:
                вр = qr.Выполнить().Выбрать()
                строки_р = []
                while вр.Следующий():
                    строки_р.append((s(вр.ВД), s(вр.Ном), s(вр.Скл), float(вр.Кол or 0)))
                if строки_р:
                    print(f"  Регистр {имя_рег} ({len(строки_р)}):")
                    for вд, ном, скл, кол in строки_р:
                        print(f"    {вд:<8}  {ном:<25}  {скл:<30}  {кол:>8.2f}")
            except Exception:
                pass

# 4. Сводка по перемещениям этой смены
if "Перемещ." in по_типам:
    print("\n\n[4] Перемещения смены 3867 — куда, литры")
    print("-" * 100)
    for доку in по_типам["Перемещ."]:
        qm = conn.NewObject("Запрос")
        qm.УстановитьПараметр("Док", доку["ссылка"])
        qm.Текст = """
        ВЫБРАТЬ
            Док.СкладОтправитель.Наименование КАК Отпр,
            Док.СкладПолучатель.Наименование КАК Полу
        ИЗ Документ.ПеремещениеТоваров КАК Док
        ГДЕ Док.Ссылка = &Док
        """
        вм = qm.Выполнить().Выбрать()
        вм.Следующий()
        qt = conn.NewObject("Запрос")
        qt.УстановитьПараметр("Док", доку["ссылка"])
        qt.Текст = """
        ВЫБРАТЬ ТЧ.Номенклатура.Наименование КАК Ном, ТЧ.Количество КАК Кол
        ИЗ Документ.ПеремещениеТоваров.Товары КАК ТЧ
        ГДЕ ТЧ.Ссылка = &Док
        """
        вт = qt.Выполнить().Выбрать()
        итог = 0
        строки_т = []
        while вт.Следующий():
            кол = float(вт.Кол or 0)
            строки_т.append((s(вт.Ном), кол))
            итог += кол
        зн = "✓" if доку["пров"] else "○"
        print(f"  {зн} №{доку['ном']}  {s(вм.Отпр)} → {s(вм.Полу)}   Σ={итог:.2f} л")
        for ном, кол in строки_т:
            print(f"     • {ном:<35}  {кол:>8.2f} л")

print("\n" + "=" * 100)
