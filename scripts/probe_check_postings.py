# -*- coding: utf-8 -*-
"""Проверка проводок: каждый активный документ за 01-15.05 имеет корректные движения
в РегистрБухгалтерии.Хозрасчетный. Корреспонденции счетов соответствуют типу документа."""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return ""


def fmt(n):
    return f"{n:,.2f}".replace(",", " ")


ПЕРИОД = ("Док.Дата >= ДАТАВРЕМЯ(2026,5,1,0,0,0) "
          "И Док.Дата <= ДАТАВРЕМЯ(2026,5,15,23,59,59)")
УСЛ_TL = ('(ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО "TL|%" '
          'ИЛИ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО "% | TL|%")')

print("=" * 90)
print("Проверка проводок документов TradeLedger 01-15.05.2026")
print("=" * 90)

ТИПЫ = [
    ("Документ.ОтчетОРозничныхПродажах",    "ОРП"),
    ("Документ.ПриходныйКассовыйОрдер",     "ПКО"),
    ("Документ.ПеремещениеТоваров",         "Перемещение"),
    ("Документ.КомплектацияНоменклатуры",   "Комплектация"),
    ("Документ.СписаниеТоваров",            "Списание"),
]

for менеджер, краткое in ТИПЫ:
    # Тип регистратора через ВЫРАЗИТЬ
    тип_ссылки = менеджер.replace("Документ.", "")  # ОтчетОРозничныхПродажах и т.п.

    # Корреспонденции счетов по типу документа за период
    q = conn.NewObject("Запрос")
    q.Текст = f"""
    ВЫБРАТЬ
        Прв.СчетДт.Код КАК Дт,
        Прв.СчетКт.Код КАК Кт,
        КОЛИЧЕСТВО(*) КАК Стр,
        СУММА(Прв.Сумма) КАК Σ
    ИЗ РегистрБухгалтерии.Хозрасчетный КАК Прв
    ГДЕ Прв.Период >= ДАТАВРЕМЯ(2026,5,1,0,0,0)
      И Прв.Период <= ДАТАВРЕМЯ(2026,5,15,23,59,59)
      И Прв.Регистратор ССЫЛКА Документ.{тип_ссылки}
      И ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.{тип_ссылки}).Проведен
      И НЕ ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.{тип_ссылки}).ПометкаУдаления
      И (ВЫРАЗИТЬ(ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.{тип_ссылки}).Комментарий КАК СТРОКА(300)) ПОДОБНО "TL|%"
         ИЛИ ВЫРАЗИТЬ(ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.{тип_ссылки}).Комментарий КАК СТРОКА(300)) ПОДОБНО "% | TL|%")
    СГРУППИРОВАТЬ ПО Прв.СчетДт.Код, Прв.СчетКт.Код
    УПОРЯДОЧИТЬ ПО Σ УБЫВ
    """
    # Кол-во документов всего
    q_кол = conn.NewObject("Запрос")
    q_кол.Текст = f"""
    ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К
    ИЗ {менеджер} КАК Док
    ГДЕ {ПЕРИОД} И {УСЛ_TL} И Док.Проведен И НЕ Док.ПометкаУдаления
    """
    в_к = q_кол.Выполнить().Выбрать(); в_к.Следующий()
    всего = int(в_к.К or 0)
    # Кол-во документов с проводками
    q_рег = conn.NewObject("Запрос")
    q_рег.Текст = f"""
    ВЫБРАТЬ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Прв.Регистратор) КАК Р
    ИЗ РегистрБухгалтерии.Хозрасчетный КАК Прв
    ГДЕ Прв.Период >= ДАТАВРЕМЯ(2026,5,1,0,0,0)
      И Прв.Период <= ДАТАВРЕМЯ(2026,5,15,23,59,59)
      И Прв.Регистратор ССЫЛКА Документ.{тип_ссылки}
    """
    в_р = q_рег.Выполнить().Выбрать(); в_р.Следующий()
    с_проводками = int(в_р.Р or 0)

    print(f"\n## {краткое}: {всего} активных документов")
    в2 = q.Выполнить().Выбрать()
    print(f"  Корреспонденции счетов:")
    итог_сумма = 0
    есть_проводки = False
    while в2.Следующий():
        есть_проводки = True
        Σ = float(в2.Σ or 0)
        итог_сумма += Σ
        print(f"    Дт {s(в2.Дт):<10} Кт {s(в2.Кт):<10}  {int(в2.Стр):>5} стр    {fmt(Σ):>16} ₽")
    if not есть_проводки:
        print(f"    ⚠ ПРОВОДОК НЕТ")
    else:
        print(f"    {'ИТОГО Σ движений':<32}                    {fmt(итог_сумма):>16} ₽")

    без_проводок = всего - с_проводками
    if без_проводок > 0:
        print(f"  ⚠ Документов БЕЗ проводок: {без_проводок} из {всего}")
    else:
        print(f"  ✓ Все {всего} имеют движения в регистре")

# ───────────────────────────────────────────────────────────────────────
# Проверка баланса: Дт сумма = Кт сумма по типу документа
# ───────────────────────────────────────────────────────────────────────
print(f"\n{'='*90}")
print("Контроль баланса (Дт сумма = Кт сумма) по типам документов")
print(f"{'='*90}")

q_bal = conn.NewObject("Запрос")
q_bal.Текст = """
ВЫБРАТЬ
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.ОтчетОРозничныхПродажах).Ссылка КАК ОРП,
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.ПриходныйКассовыйОрдер).Ссылка КАК ПКО,
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.ПеремещениеТоваров).Ссылка КАК Перем,
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.КомплектацияНоменклатуры).Ссылка КАК Компл,
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.СписаниеТоваров).Ссылка КАК Списан,
    СУММА(Прв.Сумма) КАК ΣДт
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Прв
ГДЕ Прв.Период >= ДАТАВРЕМЯ(2026,5,1,0,0,0)
  И Прв.Период <= ДАТАВРЕМЯ(2026,5,15,23,59,59)
СГРУППИРОВАТЬ ПО
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.ОтчетОРозничныхПродажах).Ссылка,
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.ПриходныйКассовыйОрдер).Ссылка,
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.ПеремещениеТоваров).Ссылка,
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.КомплектацияНоменклатуры).Ссылка,
    ВЫРАЗИТЬ(Прв.Регистратор КАК Документ.СписаниеТоваров).Ссылка
"""
в_bal = q_bal.Выполнить().Выбрать()
несхождений = 0
всего = 0
while в_bal.Следующий():
    Σ = float(в_bal.ΣДт or 0)
    всего += 1
    # Сумма движений = Дт сумма = Кт сумма (всегда одинаково по правилу 1С)
    # Несхождения быть не может в типовой БП — пропускаем
print(f"  ✓ Принцип 1С: Σ(Дт) = Σ(Кт) в каждой проводке по определению. Дисбалансов быть не может.")
print(f"  Всего регистраторов с движениями: {всего}")

# ───────────────────────────────────────────────────────────────────────
# Сравнение Σ ОРП по проводкам с СуммаДокумента
