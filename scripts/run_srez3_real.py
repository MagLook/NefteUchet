def предзагрузить_номенклатуру_в_бп(conn, пакет_dict, package_id):
    """Создать в БП ГИГ записи Catalog.Номенклатура + TL_СоответствиеИсточников для всех SKU."""
    import datetime as _dt
    nom_items = [n for n in пакет_dict["НСИ"] if n["Тип"] == "Номенклатура"]
    if not nom_items:
        return 0, 0
    ENUM = conn.Перечисления.TL_ТипОбъектаИсточника

    def find_one(text):
        q = conn.NewObject("Запрос"); q.Текст = text
        sel = q.Выполнить().Выбрать()
        return sel.Ссылка if sel.Следующий() else None

    вид_товар = find_one(
        "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.ВидыНоменклатуры "
        "ГДЕ Наименование = \"Товары\" И НЕ ПометкаУдаления"
    ) or find_one(
        "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.ВидыНоменклатуры ГДЕ НЕ ПометкаУдаления"
    )
    ed_sht = find_one(
        "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.КлассификаторЕдиницИзмерения ГДЕ Код = \"796\""
    )
    created = matched = 0
    for item in nom_items:
        uuid = item["ИсточникUUID"]
        if conn.TL_МаппингЦБ.НайтиСоответствие(ENUM.Номенклатура, uuid):
            matched += 1
            continue
        try:
            nm = conn.Справочники.Номенклатура.СоздатьЭлемент()
            nm.Наименование = (item.get("Наименование") or f"SKU_{uuid[:8]}")[:100]
            if item.get("Код"):
                try: nm.Артикул = str(item["Код"])[:25]
                except Exception: pass
            if ed_sht:
                try: nm.БазоваяЕдиницаИзмерения = ed_sht
                except Exception: pass
            if вид_товар:
                try: nm.ВидНоменклатуры = вид_товар
                except Exception: pass
            nm.Записать()
            мз = conn.РегистрыСведений.TL_СоответствиеИсточников.СоздатьМенеджерЗаписи()
            мз.Тип = ENUM.Номенклатура
            мз.ИсточникUUID = uuid
            мз.СсылкаОбъект = nm.Ссылка
            мз.ДатаПоследнейЗагрузки = _dt.datetime.now()
            мз.ИдентификаторПоследнегоПакета = package_id
            мз.Записать()
            created += 1
        except Exception:
            pass
    return created, matched


def загрузить_в_бп_гиг(путь_пакета, package_id):
    print(f"  Подключение к БП ГИГ: {BP_BASE}")
    connector = win32com.client.Dispatch("V83.COMConnector")
    cs = f'File="{BP_BASE}";Usr="{BP_USER}";Pwd="{BP_PWD}";'
    conn = connector.Connect(cs)
    print(f"  OK. Конфа {conn.Метаданные.Версия}")

    with open(путь_пакета, "r", encoding="utf-8-sig") as f:
        пакет_dict = json.load(f)

    print("  Предзагрузка SKU (Номенклатура + TL_СоответствиеИсточников)...")
    cr, mt = предзагрузить_номенклатуру_в_бп(conn, пакет_dict, package_id)
    print(f"    Создано: {cr}, уже сопоставлено: {mt}")

    try:
        read_result = conn.TL_HTTPКлиентЦБ.ПрочитатьПакетИзФайла(str(путь_пакета))
        if read_result.Ошибка:
            print(f"  FAIL чтения: {read_result.Ошибка}")
            return None
        результат = conn.TL_СопуткаСервис.ОбработатьПакет(read_result.Пакет, True)
        print(f"  Документов создано: {результат.Документы.Количество()}")
        print(f"  Ошибок: {результат.Ошибки.Количество()}")
        if результат.Ошибки.Количество() > 0:
            for i in range(результат.Ошибки.Количество()):
                print(f"    [{i+1}] {результат.Ошибки.Получить(i)}")
        return результат, conn
    except Exception as e:
        print(f"  [FAIL] {e}")
        return None


