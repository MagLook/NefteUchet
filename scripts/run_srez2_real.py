    путь = сохранить_пакет(пакет, package_id)
    print(f"  {путь}")

    if args.only_json:
        print("\n[STOP] --only-json: загрузка в БП ГИГ пропущена")
        return 0

    # [4] Загрузка в БП ГИГ
    print("\n[4/5] Загрузка в БП ГИГ...")
    результат = загрузить_в_бп_гиг(путь)
    if результат is None:
        print("\n[5/5] Проверка пропущена — загрузка не удалась")
        return 1
    res, conn = результат

    # [5] Проверка результата
    print("\n[5/5] Проверка созданного ОРП в БП ГИГ...")
    if res.Документы.Количество() == 0:
        print("  FAIL: документ не создан")
        return 1

    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.ОтчетОРозничныхПродажах "
        "ГДЕ ВЫРАЗИТЬ(Комментарий КАК СТРОКА(200)) ПОДОБНО &Ш"
    )
    q.УстановитьПараметр("Ш", f"TL|ЦБ|{package_id}|%")
    v = q.Выполнить().Выбрать()
    if not v.Следующий():
        print("  FAIL: ОРП не найден по комментарию")
        return 1
    орп = v.Ссылка
    о = орп.ПолучитьОбъект()
    print(f"  Найден:        {орп}")
    print(f"  Дата:          {о.Дата}")
    print(f"  Организация:   {о.Организация}")
    print(f"  Склад:         {о.Склад}")
    print(f"  Подразделение: {о.ПодразделениеОрганизации}")
    print(f"  ВидОперации:   {о.ВидОперации}")
    print(f"  СуммаДокумента: {о.СуммаДокумента}")
    print(f"  Проведен:      {о.Проведен}")
    print(f"  Строк Товаров: {о.Товары.Количество()}")
    print(f"  Строк Оплаты:  {о.Оплата.Количество()}")

    sum_delta = abs(float(о.СуммаДокумента) - EXPECTED_SUM)
    ok_sum = sum_delta < 0.01
    ok_lines = о.Товары.Количество() == EXPECTED_LINES
    print(f"  Совпадение суммы (ожидалось {EXPECTED_SUM}): {ok_sum} (Δ={sum_delta:.4f})")
    print(f"  Совпадение строк (ожидалось {EXPECTED_LINES}): {ok_lines}")

    # Распределение НДС в БП
    nds_bp = {}
    for i in range(о.Товары.Количество()):
        стр = о.Товары.Получить(i)
        имя = str(conn.XMLСтрока(стр.СтавкаНДС)) if стр.СтавкаНДС else "пусто"
        nds_bp[имя] = nds_bp.get(имя, 0) + 1
    print(f"  НДС-распределение БП: {nds_bp}")

    # Проводки
    print("\n  Проводки Хозрасчётный:")
    q2 = conn.NewObject("Запрос")
    q2.Текст = (
        "ВЫБРАТЬ СчетДт.Код КАК Дт, СчетКт.Код КАК Кт, СУММА(Сумма) КАК Сум, "
        "  КОЛИЧЕСТВО(*) КАК К "
        "ИЗ РегистрБухгалтерии.Хозрасчетный "
        "ГДЕ Регистратор = &Р "
        "СГРУППИРОВАТЬ ПО СчетДт.Код, СчетКт.Код"
    )
    q2.УстановитьПараметр("Р", орп)
    v = q2.Выполнить().Выбрать()
    while v.Следующий():
        print(f"    Дт {v.Дт} Кт {v.Кт}: {int(v.К)} строк, {float(v.Сум):.2f} ₽")

    print("\n" + "=" * 76)
    if ok_sum and ok_lines and res.Ошибки.Количество() == 0:
        print("  СРЕЗ 2 retail_sale_sidegoods: ✓ УСПЕХ")
    else:
        print("  СРЕЗ 2 retail_sale_sidegoods: ⚠ есть отклонения")
    print("=" * 76)
    return 0


