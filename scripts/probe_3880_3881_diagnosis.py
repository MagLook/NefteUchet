# -*- coding: utf-8 -*-
"""Диагностика смен 209/3880 (проведён) и 209/3881 (НЕ проведён):
  1. Записи TL_СтатусыЗагрузки/TL_ОшибкиЗагрузки по идентификаторам этих смен
  2. Попытка провести ОРП 704 с перехватом ошибки
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def fmt_date(d):
    try:
        return d.strftime("%d.%m %H:%M:%S")
    except Exception:
        return str(d)


def s(v):
    """Строковое представление чего угодно из COM (избегаем 'COMObject unknown')"""
    if v is None:
        return "—"
    try:
        return str(v)
    except Exception:
        return repr(v)


print("=" * 100)
print("Диагностика смен 209/3880 и 209/3881")
print("=" * 100)

# ───────────────────────────────────────────────────────────────────────
# 1. TL_СтатусыЗагрузки — записи по сменам 3880 и 3881
# ───────────────────────────────────────────────────────────────────────
print("\n[1] TL_СтатусыЗагрузки (записи с КлючЗагрузки содержащим '3880' или '3881')")
print("-" * 100)
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    Рег.КлючЗагрузки КАК Ключ,
    Рег.ДатаЗагрузки КАК ДатаЗ,
    Рег.Статус       КАК Статус,
    Рег.ТипДокумента КАК ТипДок
ИЗ РегистрСведений.TL_СтатусыЗагрузки КАК Рег
ГДЕ Рег.КлючЗагрузки ПОДОБНО "%3880%" ИЛИ Рег.КлючЗагрузки ПОДОБНО "%3881%"
УПОРЯДОЧИТЬ ПО Рег.ДатаЗагрузки УБЫВ
"""
в = q.Выполнить().Выбрать()
н = 0
while в.Следующий():
    н += 1
    print(f"\n  [{н}] {fmt_date(в.ДатаЗ)}  Статус={s(в.Статус)}")
    print(f"      Ключ:    {s(в.Ключ)}")
    print(f"      ТипДок:  {s(в.ТипДок)}")
if н == 0:
    print("  (записей нет — пакеты по этим сменам не отмечены в TL_СтатусыЗагрузки)")

# ───────────────────────────────────────────────────────────────────────
# 2. TL_ОшибкиЗагрузки — записи за 20-22.05
# ───────────────────────────────────────────────────────────────────────
print("\n\n[2] TL_ОшибкиЗагрузки (последние 50 записей за 20-22.05)")
print("-" * 100)
q2 = conn.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 50
    Рег.ИдентификаторПакета КАК Пакет,
    Рег.НомерЗаписи         КАК Н,
    Рег.КодОшибки           КАК Код,
    Рег.Поле                КАК Поле,
    Рег.ИсточникUUID        КАК UUID,
    Рег.ЗначениеИсточника   КАК Значение,
    Рег.СообщениеОшибки     КАК Сообщ,
    Рег.ВремяРегистрации    КАК Время,
    Рег.Документ            КАК Документ
ИЗ РегистрСведений.TL_ОшибкиЗагрузки КАК Рег
ГДЕ Рег.ВремяРегистрации >= ДАТАВРЕМЯ(2026,5,20,0,0,0)
  И Рег.ВремяРегистрации <= ДАТАВРЕМЯ(2026,5,22,23,59,59)
УПОРЯДОЧИТЬ ПО Рег.ВремяРегистрации УБЫВ
"""
в2 = q2.Выполнить().Выбрать()
н = 0
по_пакетам = {}
while в2.Следующий():
    н += 1
    пакет = s(в2.Пакет)[:60]
    по_пакетам.setdefault(пакет, []).append({
        "время": fmt_date(в2.Время),
        "код": s(в2.Код),
        "поле": s(в2.Поле),
        "uuid": s(в2.UUID)[:50],
        "значение": s(в2.Значение)[:60],
        "сообщ": s(в2.Сообщ)[:200],
    })

if н == 0:
    print("  (ошибок за период нет)")
else:
    for пакет, ошибки in по_пакетам.items():
        print(f"\n  Пакет: {пакет}  ({len(ошибки)} ошибок)")
        for о in ошибки[:10]:
            print(f"     [{о['время']}] {о['код']:<30}  поле={о['поле']}")
            if о["uuid"] not in ("—", ""):
                print(f"        UUID:    {о['uuid']}")
            if о["значение"] not in ("—", ""):
                print(f"        Значение: {о['значение']}")
            print(f"        Сообщ:    {о['сообщ']}")
        if len(ошибки) > 10:
            print(f"     ... ещё {len(ошибки)-10}")

# ───────────────────────────────────────────────────────────────────────
# 3. Попытка провести ОРП 704 (смена 3881) с перехватом ошибки
# ───────────────────────────────────────────────────────────────────────
print("\n\n[3] Попытка провести ОРП ГИ0Г-000704 (смена 3881)")
print("-" * 100)
q3 = conn.NewObject("Запрос")
q3.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 Док.Ссылка КАК С
ИЗ Документ.ОтчетОРозничныхПродажах КАК Док
ГДЕ Док.Комментарий ПОДОБНО "%3881%"
"""
в3 = q3.Выполнить().Выбрать()
в3.Следующий()
ссылка = в3.С
print(f"  Найден ОРП: {s(ссылка)}")

try:
    объ = ссылка.ПолучитьОбъект()
    print(f"  Записываем с режимом 'Проведение'...")
    try:
        объ.Записать(conn.РежимЗаписиДокумента.Проведение)
        print(f"  ✓ ПРОВЕДЕНО успешно")
    except Exception as e:
        print(f"  ✗ ОШИБКА проведения: {e}")
except Exception as e:
    print(f"  ✗ ОШИБКА получения объекта: {e}")

print("\n" + "=" * 100)
print("Готово")
