# -*- coding: utf-8 -*-
"""Найти и пометить на удаление дубли ОРП. Также пометить связанные дочерние."""
import win32com.client
import re

BASE = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"
OUT = open(r"D:\Users\magsp\ELSYPLUS\NefteUchet\scripts\_out_dedup.txt", "w", encoding="utf-8")
def p(*a): print(*a, file=OUT)

def s(v):
    if v is None: return ""
    sv = str(v)
    if "<COMObject" in sv or "unknown" in sv:
        for attr in ("Представление", "Номер", "Наименование"):
            try:
                a = getattr(v, attr)
                if a is None: continue
                a_s = str(a)
                if a_s and "<COMObject" not in a_s: return a_s
            except Exception: continue
        return ""
    return sv

com = win32com.client.Dispatch("V83.COMConnector")
conn = com.Connect(f'File="{BASE}";Usr="{USER}";Pwd="{PWD}";')

p("=" * 78)
p("Дубли ОРП (нормализованный ключ TL|СМЕНА|сеть|стн|номер)")
p("=" * 78)

Q = conn.NewObject("Запрос")
Q.Текст = '''ВЫБРАТЬ Ссылка, Номер, Дата, Комментарий, Проведен
ИЗ Документ.ОтчетОРозничныхПродажах
ГДЕ ВЫРАЗИТЬ(Комментарий КАК СТРОКА(200)) ПОДОБНО "TL|СМЕНА|%"
УПОРЯДОЧИТЬ ПО Дата'''
Sel = Q.Выполнить().Выбрать()

ключ_к_доку = {}
while Sel.Следующий():
    ком = str(Sel.Комментарий or '').strip()
    m = re.match(r'^(TL\|СМЕНА\|\d+\|\d+\|\d+)', ком)
    if m:
        к = m.group(1)
        ключ_к_доку.setdefault(к, []).append((Sel.Ссылка, str(Sel.Номер), Sel.Проведен, Sel.Дата))

дубли = {к: лст for к, лст in ключ_к_доку.items() if len(лст) > 1}
p(f"Уникальных ключей: {len(ключ_к_доку)}, с дублями: {len(дубли)}")
p()

для_удаления = []
для_сохранения = []
for к, лст in sorted(дубли.items()):
    # Сортируем: проведённые в конец (последним), и при равенстве — по дате (свежие в конец)
    лст.sort(key=lambda x: (1 if x[2] else 0, x[3]))
    оставляем = лст[-1]
    удаляем = лст[:-1]
    p(f"  {к}:")
    for ссыл, ном, провед, дата in лст:
        marker = "ОСТАВИТЬ" if (ссыл, ном, провед, дата) == оставляем else "удалить"
        p(f"    [{marker}] {ном} провед={провед} {дата}")
    для_сохранения.append(оставляем[0])
    for x in удаляем:
        для_удаления.append(x[0])

p()
p(f"Для пометки на удаление: {len(для_удаления)} ОРП")

p()
p("=" * 78)
p("Поиск дочерних документов (Перемещение/Комплектация/ПКО) на удаляемые ОРП")
p("=" * 78)

# Для каждого ключа лишних ОРП — находим связанные документы по тому же базовому ключу
# Базовый ключ дочернего = TL|СМЕНА|сеть|стн|номер|<суффикс>
# Удалить нужно дочерние созданные В ТОТ ЖЕ ДЕНЬ что и удаляемый ОРП
# (потому что регистр статусов может ссылаться на свежий ОРП и связанные с ним)

дочерние_к_удалению = []
for к, лст in sorted(дубли.items()):
    лст.sort(key=lambda x: (1 if x[2] else 0, x[3]))
    оставляем_дата = лст[-1][3]
    удаляем_даты = [x[3] for x in лст[:-1]]
    p(f"\n  {к}: оставляем дата {оставляем_дата}")
    # Для каждого дочернего типа проверяем связь
    for тип in ["ПеремещениеТоваров", "КомплектацияНоменклатуры", "ПриходныйКассовыйОрдер"]:
        Q2 = conn.NewObject("Запрос")
        Q2.УстановитьПараметр("Префикс", к + "%")
        Q2.Текст = f'''ВЫБРАТЬ Ссылка, Номер, Дата, Комментарий, МоментВремени
        ИЗ Документ.{тип}
        ГДЕ ВЫРАЗИТЬ(Комментарий КАК СТРОКА(200)) ПОДОБНО &Префикс
        УПОРЯДОЧИТЬ ПО МоментВремени'''
        Sel2 = Q2.Выполнить().Выбрать()
        дочерние_по_ключу = {}  # под-ключ → [(ссылка, дата)]
        while Sel2.Следующий():
            ком = str(Sel2.Комментарий or '').strip()
            m = re.match(r'^(TL\|СМЕНА\|\d+\|\d+\|\d+\|[^ ]+)', ком)
            if m:
                подключ = m.group(1)
            else:
                подключ = ком
            дочерние_по_ключу.setdefault(подключ, []).append((Sel2.Ссылка, str(Sel2.Номер), Sel2.Дата))

        для_удаления_типа = 0
        for подключ, элты in дочерние_по_ключу.items():
            if len(элты) <= 1: continue
            # Сортируем по дате, оставляем самый свежий
            элты.sort(key=lambda x: x[2])
            for ссыл, ном, дата in элты[:-1]:
                дочерние_к_удалению.append(ссыл)
                для_удаления_типа += 1
                p(f"    [удалить] {тип} #{ном} дата={дата}")
        if для_удаления_типа:
            p(f"    Всего {тип}: {для_удаления_типа}")

p()
p(f"Всего дочерних к удалению: {len(дочерние_к_удалению)}")

# Теперь удаляем (физически — это файловая база, без последствий)
p()
p("=" * 78)
p("Удаление")
p("=" * 78)

всего = 0
ошибок = 0
для_всего_удаления = list(для_удаления) + list(дочерние_к_удалению)

# Сначала отменяем проведение, потом удаляем
for ссыл in для_всего_удаления:
    try:
        obj = ссыл.ПолучитьОбъект()
        if obj.Проведен:
            # Распровести
            obj.Записать()  # без флага = просто запись (распроведение)
        obj.Удалить()  # физическое удаление (для файловой базы)
        всего += 1
    except Exception as e:
        ошибок += 1
        p(f"  Ошибка: {ссыл}: {e}")

p(f"Удалено: {всего}, ошибок: {ошибок}")

# Чистим записи регистра, ссылающиеся на удалённые ОРП и дочерние
p()
p("=" * 78)
p("Чистка регистра TL_СтатусыЗагрузки от орфанов")
p("=" * 78)
Q = conn.NewObject("Запрос")
Q.Текст = '''ВЫБРАТЬ КлючЗагрузки ИЗ РегистрСведений.TL_СтатусыЗагрузки'''
Sel = Q.Выполнить().Выбрать()
ключи = []
while Sel.Следующий():
    ключи.append(str(Sel.КлючЗагрузки))

# Для каждого ключа проверяем — есть ли документ с таким комментарием
очищ = 0
for к in ключи:
    нашли = False
    for тип in ["ОтчетОРозничныхПродажах","ПеремещениеТоваров","КомплектацияНоменклатуры","ПриходныйКассовыйОрдер"]:
        Q2 = conn.NewObject("Запрос")
        Q2.УстановитьПараметр("П", к + "%")
        Q2.Текст = f'ВЫБРАТЬ ПЕРВЫЕ 1 1 КАК Е ИЗ Документ.{тип} ГДЕ ВЫРАЗИТЬ(Комментарий КАК СТРОКА(200)) ПОДОБНО &П'
        if not Q2.Выполнить().Пустой():
            нашли = True; break
    if not нашли:
        М = conn.РегистрыСведений.TL_СтатусыЗагрузки.СоздатьМенеджерЗаписи()
        М.КлючЗагрузки = к
        М.Прочитать()
        М.Удалить()
        очищ += 1
p(f"Удалено орфан-записей регистра: {очищ}")

OUT.close()
print("OK: scripts/_out_dedup.txt")
