# -*- coding: utf-8 -*-
"""
Анализ ОРП -> ПКО в БП ГИГ.
Запуск: py -3-32 scripts/diag_cash_orders2.py
"""
import sys
import datetime
import win32com.client

BASE_PATH = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"

def hr(t=""):
    print()
    print("=" * 78)
    if t: print(t)
    print("=" * 78)

def s(v):
    """Строковое представление 1С-ссылки/значения."""
    if v is None: return ""
    try:
        # 1С COM-объекты часто имеют свойство Представление
        return str(v)
    except Exception:
        return repr(v)

def acc(счёт):
    """Код счёта"""
    try: return str(счёт.Код)
    except Exception:
        return s(счёт)

def main():
    com = win32com.client.Dispatch("V83.COMConnector")
    conn = com.Connect(f'File="{BASE_PATH}";Usr="{USER}";Pwd="{PWD}";')

    hr("0) Метаданные ПриходныйКассовыйОрдер — какие есть реквизиты основания/связи")
    md = conn.Метаданные.Документы.ПриходныйКассовыйОрдер
    print(f"  Имя: {md.Имя}")
    print(f"  Синоним: {md.Синоним}")
    print(f"  Реквизиты:")
    for rq in md.Реквизиты:
        ttype = ""
        try: ttype = str(rq.Тип)
        except Exception: pass
        if any(k in rq.Имя.lower() for k in ["основ", "связ", "налич", "опл", "вид", "сумма", "ккт", "розн"]):
            print(f"    {rq.Имя:35} тип={ttype[:80]}")

    hr("0b) Метаданные ОтчётОРозничныхПродажах")
    md = conn.Метаданные.Документы.ОтчетОРозничныхПродажах
    print(f"  Реквизиты с признаками 'опл/налич/безнал/касс/розн':")
    for rq in md.Реквизиты:
        if any(k in rq.Имя.lower() for k in ["опл", "налич", "безнал", "касс", "розн", "ккт"]):
            ttype = ""
            try: ttype = str(rq.Тип)
            except Exception: pass
            print(f"    {rq.Имя:35} тип={ttype[:80]}")
    print(f"  ТабличныеЧасти:")
    for tch in md.ТабличныеЧасти:
        print(f"    ТЧ {tch.Имя:35}")

    hr("1) Свежий проведённый ОРП")
    q = conn.NewObject("Запрос")
    q.Текст = '''
    ВЫБРАТЬ ПЕРВЫЕ 1
        Ссылка
    ИЗ Документ.ОтчетОРозничныхПродажах
    ГДЕ Проведен = ИСТИНА
    УПОРЯДОЧИТЬ ПО Дата УБЫВ
    '''
    sel = q.Выполнить().Выбрать()
    if not sel.Следующий():
        print("Нет проведённых ОРП")
        return
    orp_ref = sel.Ссылка
    obj = orp_ref.ПолучитьОбъект()
    print(f"  Документ: {s(orp_ref)}")
    print(f"  Дата: {obj.Дата}")
    print(f"  Организация: {s(obj.Организация)}")
    print(f"  Склад: {s(obj.Склад)}")
    print(f"  Сумма: {obj.СуммаДокумента}")
    print(f"  Комментарий: {s(obj.Комментарий)[:120]}")

    hr("2) Реквизиты документа ОРП — все, что относятся к оплате")
    md = conn.Метаданные.НайтиПоПолномуИмени("Документ.ОтчетОРозничныхПродажах")
    for rq in md.Реквизиты:
        if any(k in rq.Имя.lower() for k in ["опл", "налич", "безнал", "касс", "ккт"]):
            try:
                v = getattr(obj, rq.Имя)
                print(f"    {rq.Имя:35} = {s(v)[:80]}")
            except Exception as e:
                print(f"    {rq.Имя:35} ОШИБКА {e}")

    hr("3) ТЧ ОРП — что есть и образцы")
    for tch in md.ТабличныеЧасти:
        try:
            tab = getattr(obj, tch.Имя)
            cnt = tab.Количество()
        except Exception:
            continue
        print(f"\n  ТЧ {tch.Имя}: {cnt} строк")
        if cnt > 0:
            row = tab.Получить(0)
            for rq in tch.Реквизиты:
                try:
                    v = getattr(row, rq.Имя)
                    print(f"      {rq.Имя:30} = {s(v)[:60]}")
                except Exception:
                    pass

    hr("4) Проводки ОРП (РегистрБухгалтерии.Хозрасчётный)")
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Регистратор", orp_ref)
    q.Текст = '''
    ВЫБРАТЬ Период, СчетДт, СчетКт, Сумма, Содержание
    ИЗ РегистрБухгалтерии.Хозрасчетный
    ГДЕ Регистратор = &Регистратор
    УПОРЯДОЧИТЬ ПО НомерСтроки
    '''
    sel = q.Выполнить().Выбрать()
    n = 0
    while sel.Следующий():
        n += 1
        print(f"  Дт {acc(sel.СчетДт):>8}  Кт {acc(sel.СчетКт):>8}  = {sel.Сумма:>12.2f}  | {s(sel.Содержание)[:55]}")
    print(f"  Всего проводок ОРП: {n}")

    hr("5) Поиск ВСЕХ связанных документов через Структуру подчинённости")
    # В БП 3.0 связь ищется через РегистрСведений.СтруктураПодчинённости или через _ДокументыНа...
    # Универсально — поищем ПКО по дате и складу
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("ДатаНачДок", obj.Дата)
    q.УстановитьПараметр("Организация", obj.Организация)
    q.Текст = '''
    ВЫБРАТЬ
        Ссылка, Номер, Дата, ВидОперации, СуммаДокумента, Проведен
    ИЗ Документ.ПриходныйКассовыйОрдер
    ГДЕ НАЧАЛОПЕРИОДА(Дата, ДЕНЬ) = НАЧАЛОПЕРИОДА(&ДатаНачДок, ДЕНЬ)
        И Организация = &Организация
    УПОРЯДОЧИТЬ ПО Дата
    '''
    sel = q.Выполнить().Выбрать()
    pkos = []
    while sel.Следующий():
        pkos.append(sel.Ссылка)
        print(f"  ПКО {s(sel.Номер):>12} от {sel.Дата}  Σ={sel.СуммаДокумента:>10.2f}  вид={s(sel.ВидОперации)[:35]:35}  пров={sel.Проведен}")
    print(f"  Всего ПКО за день документа ОРП: {len(pkos)}")

    hr("6) Метаданные ПКО — все реквизиты целиком")
    md_pko = conn.Метаданные.Документы.ПриходныйКассовыйОрдер
    print("  Реквизиты (все):")
    for rq in md_pko.Реквизиты:
        ttype = ""
        try: ttype = str(rq.Тип)
        except Exception: pass
        print(f"    {rq.Имя:35} тип={ttype[:90]}")

    if pkos:
        hr("7) ПКО: проводки и сопоставление с ОРП")
        for pko_ref in pkos:
            pko_obj = pko_ref.ПолучитьОбъект()
            print(f"\n  --- ПКО {s(pko_obj.Номер)} от {pko_obj.Дата} ---")
            # Проверим все реквизиты-ссылки на наш ОРП
            print("  Реквизиты-ссылки (поиск связи с ОРП):")
            for rq in md_pko.Реквизиты:
                try:
                    v = getattr(pko_obj, rq.Имя)
                    if v is None or v == "" or v == 0: continue
                    s_val = s(v)
                    if not s_val: continue
                    if "Документ." in s_val or "Регистратор" in rq.Имя.lower() \
                            or "основ" in rq.Имя.lower() or "связ" in rq.Имя.lower():
                        marker = ""
                        try:
                            if v == orp_ref:
                                marker = " ← СВЯЗАН С НАШИМ ОРП"
                        except Exception: pass
                        print(f"    {rq.Имя:30} = {s_val[:80]}{marker}")
                except Exception:
                    pass

            # Проводки
            q = conn.NewObject("Запрос")
            q.УстановитьПараметр("Регистратор", pko_ref)
            q.Текст = '''
            ВЫБРАТЬ Период, СчетДт, СчетКт, Сумма, Содержание
            ИЗ РегистрБухгалтерии.Хозрасчетный
            ГДЕ Регистратор = &Регистратор
            УПОРЯДОЧИТЬ ПО НомерСтроки
            '''
            sel = q.Выполнить().Выбрать()
            print("  Проводки:")
            n = 0
            while sel.Следующий():
                n += 1
                print(f"    Дт {acc(sel.СчетДт):>8}  Кт {acc(sel.СчетКт):>8}  = {sel.Сумма:>12.2f}  | {s(sel.Содержание)[:50]}")
            if n == 0:
                print("    (проводок НЕТ)")

    hr("8) УчётнаяПолитика организации — настройка розничных продаж")
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Орг", obj.Организация)
    q.Текст = '''
    ВЫБРАТЬ ПЕРВЫЕ 1
        Ссылка, ПрименяетсяС, Регистратор
    ИЗ РегистрСведений.УчетнаяПолитика
    ГДЕ Организация = &Орг
    УПОРЯДОЧИТЬ ПО ПрименяетсяС УБЫВ
    '''
    try:
        sel = q.Выполнить().Выбрать()
        if sel.Следующий():
            print(f"  Запись регистра: ПрименяетсяС={sel.ПрименяетсяС}")
    except Exception as e:
        print(f"  УчетнаяПолитика — нет такого регистра или ошибка: {e}")

    # Проверим параметры учёта розницы
    hr("9) Реквизиты Организации, связанные с розницей/ККТ")
    org_obj = obj.Организация.ПолучитьОбъект() if obj.Организация else None
    if org_obj:
        md_org = conn.Метаданные.Справочники.Организации
        for rq in md_org.Реквизиты:
            if any(k in rq.Имя.lower() for k in ["ккт", "розн", "касс", "опл"]):
                try:
                    v = getattr(org_obj, rq.Имя)
                    print(f"    {rq.Имя:35} = {s(v)[:80]}")
                except Exception:
                    pass

    hr("10) Свод за 30 дней: ОРП vs ПКО")
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Стоп", datetime.datetime.now())
    q.Текст = '''
    ВЫБРАТЬ
        КОЛИЧЕСТВО(*) КАК ВсегоОРП
    ИЗ Документ.ОтчетОРозничныхПродажах
    ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30)
    '''
    sel = q.Выполнить().Выбрать()
    sel.Следующий()
    n_orp = sel.ВсегоОРП

    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Стоп", datetime.datetime.now())
    q.Текст = '''
    ВЫБРАТЬ
        КОЛИЧЕСТВО(*) КАК ВсегоПКО
    ИЗ Документ.ПриходныйКассовыйОрдер
    ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30)
    '''
    sel = q.Выполнить().Выбрать()
    sel.Следующий()
    n_pko = sel.ВсегоПКО

    print(f"  ОРП за 30 дней: {n_orp}")
    print(f"  ПКО за 30 дней: {n_pko}")

    # ПКО с ВидОперации=РозничнаяВыручка / ПриходРозничнойВыручки
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Стоп", datetime.datetime.now())
    q.Текст = '''
    ВЫБРАТЬ
        ВидОперации,
        КОЛИЧЕСТВО(*) КАК Кол,
        СУММА(СуммаДокумента) КАК Сумма
    ИЗ Документ.ПриходныйКассовыйОрдер
    ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30)
    СГРУППИРОВАТЬ ПО ВидОперации
    '''
    sel = q.Выполнить().Выбрать()
    print(f"\n  Разбивка ПКО за 30 дней по ВидуОперации:")
    while sel.Следующий():
        print(f"    {s(sel.ВидОперации):40} кол={sel.Кол:>4}  Σ={sel.Сумма or 0:>12.2f}")

if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        import traceback
        traceback.print_exc()
        sys.exit(1)
