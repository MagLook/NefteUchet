# -*- coding: utf-8 -*-
"""
Полный регресс v5.4.1: имитирует поведение формы Загрузки.
1) Discovery всех сетей (как при ПриСозданииНаСервере)
2) Сохранение Станция_X_КодСистемы для новых
3) Загрузка свежей смены пилота (АКЗС Витебский ст.5 сеть 65) — должна
   создать ОРП + Перемещение + ПКО
4) Попытка опроса смен по 208 (сеть 15) — должна корректно идти в сеть 15

Запуск: py -3-32 scripts/full_check_v541.py
Выход:  scripts/_out_full.txt (UTF-8)
"""
import datetime
import win32com.client

BASE = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"
OUT_PATH = r"D:\Users\magsp\ELSYPLUS\NefteUchet\scripts\_out_full.txt"

OUT = open(OUT_PATH, "w", encoding="utf-8")
def p(*a): print(*a, file=OUT)
def hr(t):
    p(); p("=" * 78); p(t); p("=" * 78)

def s(v):
    if v is None: return ""
    sv = str(v)
    if "<COMObject" in sv or "unknown" in sv:
        for attr in ("Представление", "Наименование", "Имя", "Код", "Номер"):
            try:
                a = getattr(v, attr)
                if a is None: continue
                a_s = str(a)
                if a_s and "<COMObject" not in a_s: return a_s
            except Exception: continue
        return ""
    return sv

def acc(c):
    try:
        k = str(c.Код)
        if k and "<COMObject" not in k: return k
    except Exception: pass
    return s(c)

def main():
    com = win32com.client.Dispatch("V83.COMConnector")
    conn = com.Connect(f'File="{BASE}";Usr="{USER}";Pwd="{PWD}";')

    URL = conn.TL_Настройки.ПолучитьЗначение("URLСервера", "")
    LG = conn.TL_Настройки.ПолучитьЗначение("Логин", "")
    PW = conn.TL_Настройки.ПолучитьЗначение("Пароль", "")

    hr("Этап 1: Discovery станций — что увидит пользователь в выпадашке")
    Рез = conn.TL_Настройки.ОпроситьВсеСетиИзAPI(URL, LG, PW)
    p(f"  Найдено в API: {Рез.Станции.Количество()} АЗС")
    p(f"  Ошибки опроса: {Рез.Ошибки.Количество()}")

    # Имитируем тихий discovery: сохраняем КодСистемы только если станция новая
    новых_сохранено = 0
    конфликтов = 0
    for i in range(Рез.Станции.Количество()):
        ОС = Рез.Станции[i]
        КодСтр = str(int(ОС.Код))
        # Если уже настроен склад — пропускаем
        Склад = conn.TL_Настройки.НайтиСкладСтанции(int(ОС.Код))
        if not Склад.Пустая():
            continue
        СохранКС = conn.TL_Настройки.ПолучитьЧисло(f"Станция_{КодСтр}_КодСистемы", 0)
        if СохранКС == 0:
            conn.TL_Настройки.УстановитьЗначение(
                f"Станция_{КодСтр}_КодСистемы", str(int(ОС.КодСистемы)), "Сеть (auto)")
            новых_сохранено += 1
        elif СохранКС != int(ОС.КодСистемы):
            конфликтов += 1
    p(f"  Новых сохранено: {новых_сохранено}, конфликтов сетей: {конфликтов}")

    hr("Этап 2: Что попадёт в выпадашку — список после discovery")
    ВСтан = conn.TL_Настройки.ПолучитьВсеСтанции()
    p(f"  Всего: {ВСтан.Количество()}")
    for i in range(ВСтан.Количество()):
        Стр = ВСтан[i]
        склад = s(Стр.Склад) or "(нет)"
        состояние = "OK" if склад != "(нет)" else "(не настроен склад)"
        p(f"    [сеть {int(Стр.КодСистемы):>2}, ст.{Стр.Код:>3}]  {s(Стр.Наименование):<30}  склад: {склад[:25]:25}  {состояние}")

    hr("Этап 3: Маршрутизация — какая сеть для каких станций")
    for код in [5, 1, 2, 3, 4, 6, 8, 207, 208, 209, 210]:
        сеть = conn.TL_Настройки.ПолучитьКодСистемыСтанции(код)
        p(f"  ст.{код:>3}  → сеть {сеть}")

    hr("Этап 4: Полная цепочка для пилотной АЗС 5 (АКЗС Витебский, сеть 65)")
    Токен = conn.TL_ApiКлиент.Авторизация(URL, LG, PW, 65)
    Смены = conn.TL_ApiКлиент.ПолучитьСписокСмен(URL, Токен, 65, 5)
    p(f"  Доступно смен: {Смены.Количество()}")

    if Смены.Количество() == 0:
        p("  Смен нет — пропускаю"); OUT.close(); return

    # Берём предпоследнюю (закрытую) смену
    Идекс = max(0, Смены.Количество() - 2)
    НомСмены = int(Смены[Идекс].Получить("shift"))
    p(f"  Тестовая смена: {НомСмены}")

    Отчёт = conn.TL_ApiКлиент.ПолучитьСменныйОтчёт(URL, Токен, 65, 5, НомСмены)
    Отчёт.Вставить("station", 5)
    ДанныеJSON = conn.TL_ApiКлиент.ОбъектВJSON(Отчёт)

    КлючЗагрузки = f"TL|СМЕНА|65|5|{НомСмены}|FULL_CHECK"

    Рез = conn.TL_СозданиеДокументов.ОбработатьСмену(ДанныеJSON, КлючЗагрузки, True)  # ПРОВЕДЁМ!
    p(f"\n  Документов создано: {Рез.Документы.Количество()}")
    if Рез.Ошибки.Количество() > 0:
        p(f"  Ошибки:")
        for i in range(Рез.Ошибки.Количество()):
            p(f"    - {Рез.Ошибки[i]}")

    # Полный отчёт по созданным
    типы = {"ОтчетОРозничныхПродажах": [], "ПеремещениеТоваров": [],
            "КомплектацияНоменклатуры": [], "ПриходныйКассовыйОрдер": []}
    for i in range(Рез.Документы.Количество()):
        d = Рез.Документы[i]
        ИмяТипа = str(d.Метаданные().Имя)
        if ИмяТипа in типы:
            типы[ИмяТипа].append(d)

    p()
    p(f"  ОТЧЁТ ПО ТИПАМ:")
    for имя, лст in типы.items():
        p(f"    {имя:35}: {len(лст)} шт")

    # Проводки и ключевые поля
    for тип, лст in типы.items():
        for d in лст:
            obj = d.ПолучитьОбъект()
            p(f"\n  --- {тип} {s(obj.Номер)} ---")
            p(f"      Дата: {obj.Дата}, Σ={obj.СуммаДокумента}, Проведен: {obj.Проведен}")
            if тип == "ПриходныйКассовыйОрдер":
                p(f"      ВидОперации: {s(obj.ВидОперации)}")
                p(f"      Контрагент: {s(obj.Контрагент)}")
                p(f"      ПринятоОт: {s(obj.ПринятоОт)}")
                p(f"      Основание: {s(obj.Основание)}")
                p(f"      ДокументОснование: {s(obj.ДокументОснование)}")
                p(f"      СчетКасса: {s(obj.СчетКасса)}")
            # Проводки
            Q = conn.NewObject("Запрос")
            Q.УстановитьПараметр("Регистратор", d)
            Q.Текст = "ВЫБРАТЬ СчетДт, СчетКт, Сумма, Содержание ИЗ РегистрБухгалтерии.Хозрасчетный ГДЕ Регистратор = &Регистратор"
            Sel = Q.Выполнить().Выбрать()
            проводок = 0
            while Sel.Следующий():
                проводок += 1
                if проводок <= 5:
                    p(f"      Дт {acc(Sel.СчетДт)} Кт {acc(Sel.СчетКт)} = {Sel.Сумма:>10.2f}  | {s(Sel.Содержание)[:45]}")
            if проводок > 5:
                p(f"      ... ещё {проводок-5} проводок")
            p(f"      ИТОГО проводок: {проводок}")

    # Главный итог
    p()
    есть_орп = len(типы["ОтчетОРозничныхПродажах"]) > 0
    есть_пко = len(типы["ПриходныйКассовыйОрдер"]) > 0
    p(f"  ИТОГ: ОРП={'OK' if есть_орп else 'НЕТ'}  ПКО={'OK' if есть_пко else 'НЕТ'}")

    hr("Этап 5: Запрос смен по 208 (сеть 15) — должно идти в правильную сеть")
    # Имитируем выбор станции 208 в форме: ПолучитьКодСистемыСтанции(208) → 15
    КС208 = conn.TL_Настройки.ПолучитьКодСистемыСтанции(208)
    p(f"  Станция 208 определена в сети: {КС208}")

    Токен208 = conn.TL_ApiКлиент.Авторизация(URL, LG, PW, КС208)
    Смены208 = conn.TL_ApiКлиент.ПолучитьСписокСмен(URL, Токен208, КС208, 208)
    p(f"  Авторизация в сети {КС208}: {'OK' if Токен208 else 'НЕТ'}")
    p(f"  Смен по ст.208 в сети {КС208}: {Смены208.Количество()}")
    if Смены208.Количество() > 0:
        # Покажем 3 свежие
        n = min(3, Смены208.Количество())
        for i in range(Смены208.Количество() - n, Смены208.Количество()):
            См = Смены208[i]
            p(f"    смена {См.Получить('shift')}  открыта {См.Получить('dt_open')}  закрыта {См.Получить('dt_close')}")

if __name__ == "__main__":
    try:
        main()
    finally:
        OUT.close()
        print(f"OK: {OUT_PATH}")
