# -*- coding: utf-8 -*-
"""Найти все непровед документы ТТН-пакетов и попробовать провести —
показать конкретную ошибку проведения для каждого.
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return ""


print("=" * 100)
print("Поиск непроведённых документов ТТН-пакета")
print("=" * 100)

# 1. Из TL_СтатусыЗагрузки — ключи ТТН-пакета со статусом «Загружен»
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    Рег.КлючЗагрузки, Рег.Статус, Рег.ТипДокумента, Рег.ДатаЗагрузки
ИЗ РегистрСведений.TL_СтатусыЗагрузки КАК Рег
ГДЕ Рег.КлючЗагрузки ПОДОБНО "TL|ТТН|%"
  И Рег.Статус = "Загружен"
УПОРЯДОЧИТЬ ПО Рег.ДатаЗагрузки УБЫВ
"""
в = q.Выполнить().Выбрать()
ключи = []
while в.Следующий():
    ключи.append({"ключ": s(в.КлючЗагрузки), "тип": s(в.ТипДокумента),
                  "статус": s(в.Статус)})

print(f"\nНайдено ключей ТТН со статусом «Загружен»: {len(ключи)}")
по_статусам = {}
for к in ключи:
    по_статусам.setdefault(к["тип"], 0)
    по_статусам[к["тип"]] += 1
for тип, н in по_статусам.items():
    print(f"  {тип:<15} {н:>4}")

# 2. Для каждого ключа — найти документ, попробовать провести
print(f"\n{'='*100}")
print("Диагностика — попытка провести первые 5 непроведённых")
print(f"{'='*100}")

ТИПЫ_ПОИСКА = {
    "ТТН":          "Документ.ПоступлениеТоваровУслуг",  # обычно не используется
    "Перемещение":  "Документ.ПеремещениеТоваров",
    "Комплектация": "Документ.КомплектацияНоменклатуры",
}

проверено = 0
for к in ключи:
    if проверено >= 5:
        break
    менеджер = ТИПЫ_ПОИСКА.get(к["тип"])
    if not менеджер:
        continue
    проверено += 1
    print(f"\n[{проверено}] {к['тип']} с ключом {к['ключ']}")

    qq = conn.NewObject("Запрос")
    qq.УстановитьПараметр("К", к["ключ"])
    qq.Текст = f"""
    ВЫБРАТЬ ПЕРВЫЕ 1 Док.Ссылка КАК Сс, Док.Номер КАК Н, Док.Проведен КАК П, Док.ПометкаУдаления КАК ПУ
    ИЗ {менеджер} КАК Док
    ГДЕ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) = &К
    """
    в = qq.Выполнить().Выбрать()
    if not в.Следующий():
        print(f"  ⚠ Документ по ключу не найден")
        continue

    ссылка = в.Сс
    print(f"  Док: №{s(в.Н).strip()}  Проведён={bool(в.П)}  Помечен={bool(в.ПУ)}")

    if в.ПУ:
        print(f"  → помечен на удаление, пропускаем")
        continue
    if в.П:
        print(f"  → уже проведён, пропускаем")
        continue

    # Пробуем провести
    try:
        объ = ссылка.ПолучитьОбъект()
        объ.Записать(conn.РежимЗаписиДокумента.Проведение)
        print(f"  ✓ ПРОВЕДЁН успешно")
    except Exception as e:
        msg = str(e)
        # Извлекаем человеческое сообщение из COM error
        if "Description" in dir(e):
            msg = e.Description
        print(f"  ✗ ОШИБКА проведения: {msg[:400]}")
