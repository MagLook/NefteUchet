def query_count_sum(менеджер, доп_условие=""):
    """Считает Σ(СуммаДокумента) + COUNT(*) по активным/помеч/непроведённым."""
    Σ_усл = "СУММА(Док.СуммаДокумента)"
    qq = conn.NewObject("Запрос")
    qq.Текст = f"""
    ВЫБРАТЬ
        КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Док.Ссылка) КАК Кол,
        {Σ_усл} КАК Σ
    ИЗ {менеджер} КАК Док
    ГДЕ {ПЕРИОД} И {УСЛ_TL} И Док.Проведен И НЕ Док.ПометкаУдаления {доп_условие}
    """
    в = qq.Выполнить().Выбрать()
    в.Следующий()
    return int(в.Кол or 0), float(в.Σ or 0)


def query_count(менеджер, доп_условие=""):
    """Только COUNT без СуммаДокумента (для документов без него — Перемещение и др.)."""
    qq = conn.NewObject("Запрос")
    qq.Текст = f"""
    ВЫБРАТЬ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Док.Ссылка) КАК Кол
    ИЗ {менеджер} КАК Док
    ГДЕ {ПЕРИОД} И {УСЛ_TL} И Док.Проведен И НЕ Док.ПометкаУдаления {доп_условие}
    """
    в = qq.Выполнить().Выбрать()
    в.Следующий()
    return int(в.Кол or 0)


