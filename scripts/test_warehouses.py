# -*- coding: utf-8 -*-
"""Проверить умное создание складов: что найдётся, что создастся."""
import win32com.client

BASE = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"
OUT_PATH = r"D:\Users\magsp\ELSYPLUS\NefteUchet\scripts\_out_warehouses_test.txt"
OUT = open(OUT_PATH, "w", encoding="utf-8")
def p(*a): print(*a, file=OUT)

def s(v):
    if v is None: return ""
    sv = str(v)
    if "<COMObject" in sv or "unknown" in sv:
        for attr in ("Наименование", "Имя", "Код", "Представление"):
            try:
                a = getattr(v, attr)
                if a is None: continue
                a_s = str(a)
                if a_s and "<COMObject" not in a_s: return a_s
            except Exception: continue
        return ""
    return sv

com = win32com.client.Dispatch("V83.COMConnector")
conn = com.Connect(f'File="{BASE}";Usr="{USER}";Pwd="{PWD}";')

URL = conn.TL_Настройки.ПолучитьЗначение("URLСервера", "")
LG = conn.TL_Настройки.ПолучитьЗначение("Логин", "")
PW = conn.TL_Настройки.ПолучитьЗначение("Пароль", "")

p("=" * 78)
p("Существующие склады в БД (имеют 'АЗС/АГЗС/АКЗС' в имени)")
p("=" * 78)
Q = conn.NewObject("Запрос")
Q.Текст = '''ВЫБРАТЬ Ссылка ИЗ Справочник.Склады
ГДЕ НЕ ПометкаУдаления
    И (Наименование ПОДОБНО "%АЗС%" ИЛИ Наименование ПОДОБНО "%АКЗС%" ИЛИ Наименование ПОДОБНО "%АГЗС%")
УПОРЯДОЧИТЬ ПО Наименование'''
Sel = Q.Выполнить().Выбрать()
n = 0
while Sel.Следующий():
    n += 1
    p(f"  {n:>2}. {s(Sel.Ссылка)}")
p(f"  Всего: {n}")

p()
p("=" * 78)
p("Тест умного поиска: для каждого имени из STS API")
p("=" * 78)
Рез = conn.TL_Настройки.ОпроситьВсеСетиИзAPI(URL, LG, PW)
p(f"Из API: {Рез.Станции.Количество()} станций")
p()
p(f"  {'Имя из API':<25} {'Код':>4}  {'Сеть':>4}  → результат поиска/создания")
for i in range(Рез.Станции.Количество()):
    ОС = Рез.Станции[i]
    Имя = str(ОС.Наименование)
    Код = int(ОС.Код)
    Сеть = int(ОС.КодСистемы)

    # Что найдёт текущая логика (но без создания!)
    # Я вызову НайтиСкладСтанции — он использует уже сохранённые привязки
    # А ПолучитьИлиСоздатьСкладАЗС вызывать не буду в этом тесте — иначе создаст

    Существующий = conn.TL_Настройки.НайтиСкладСтанции(Код)
    if Существующий and not Существующий.Пустая():
        p(f"  {Имя:<25} {Код:>4}  {Сеть:>4}  → ЕСТЬ привязка: {s(Существующий)}")
        continue

    # Имитация эвристики — поиск по подстроке
    Q = conn.NewObject("Запрос")
    Q.УстановитьПараметр("М1", f"АЗС%{Код}%")
    Q.УстановитьПараметр("М2", f"АГЗС%{Код}%")
    Q.УстановитьПараметр("М3", f"АКЗС%{Код}%")
    Q.УстановитьПараметр("М4", f"%№{Код}")
    Q.УстановитьПараметр("М5", f"%№{Код} %")
    Q.Текст = '''ВЫБРАТЬ ПЕРВЫЕ 3 Ссылка ИЗ Справочник.Склады
    ГДЕ НЕ ПометкаУдаления
        И (Наименование ПОДОБНО &М1 ИЛИ Наименование ПОДОБНО &М2
           ИЛИ Наименование ПОДОБНО &М3 ИЛИ Наименование ПОДОБНО &М4
           ИЛИ Наименование ПОДОБНО &М5)
    УПОРЯДОЧИТЬ ПО Наименование'''
    Sel = Q.Выполнить().Выбрать()
    кандидаты = []
    while Sel.Следующий():
        кандидаты.append(s(Sel.Ссылка))

    if кандидаты:
        p(f"  {Имя:<25} {Код:>4}  {Сеть:>4}  → ЭВРИСТИКА: {кандидаты}")
    else:
        p(f"  {Имя:<25} {Код:>4}  {Сеть:>4}  → не найдено, нужно СОЗДАТЬ '{Имя}'")

OUT.close()
print(f"OK: {OUT_PATH}")
