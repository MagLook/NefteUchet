def сформировать_пакет(шапка, товары, ингредиенты):
    """Сформировать JSON-пакет kind=production_release с вложенным ingredients_writeoff."""
    package_id = str(uuidlib.uuid4())

    # Документ production_release
    док_выпуск = {
        "Тип": "production_release",
        "ИсточникUUID": шапка["ИсточникUUID"],
        "Номер": шапка["Номер"],
        "Дата": шапка["Дата"],
        "Проведен": шапка["Проведен"],
        "ПометкаУдаления": шапка["ПометкаУдаления"],
        "Организация": шапка["Организация"],
        "Склад": шапка["Склад"],
        "Подразделение": None,  # приёмник маппит на `АЗС 208 г. Выборг`
        "ВыпускБлюд": товары,  # 11 продуктов
        "Ингредиенты": ингредиенты,  # 51 ингредиент (для ingredients_writeoff в БП ГИГ)
    }
    canonical = json.dumps(док_выпуск, ensure_ascii=False, sort_keys=True)
    док_выпуск["Хеш"] = hashlib.sha256(canonical.encode("utf-8")).hexdigest()

    # НСИ
    нси = [
        {"Тип": "Организация", "ИсточникUUID": шапка["Организация"], "Наименование": шапка["ОрганизацияИмя"]},
        {"Тип": "Склад", "ИсточникUUID": шапка["Склад"], "Наименование": шапка["СкладИмя"]},
    ]
    видимые = set()
    for стр in товары + ингредиенты:
        u = стр["Номенклатура"]
        if u in видимые:
            continue
        видимые.add(u)
        нси.append({
            "Тип": "Номенклатура",
            "ИсточникUUID": u,
            "Код": стр.get("НоменклатураКод", ""),
            "Наименование": стр.get("НоменклатураИмя", ""),
        })

    пакет = {
        "ВерсияФормата": "1",
        "ИдентификаторПакета": package_id,
        "Источник": "ЭЛСИ.АЗК ЦБ (probe срез 3)",
        "ВремяВыгрузки": dt.datetime.now().isoformat(),
        "НСИ": нси,
        "Документы": [док_выпуск],
    }
    return пакет, package_id, док_выпуск["Хеш"]


def сохранить_пакет(пакет, package_id):
    ts = int(dt.datetime.now().timestamp())
    путь = OWNCLOUD_DIR / f"tl_{package_id}_{ts}.json"
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(пакет, f, ensure_ascii=False, indent=2)
    return путь


