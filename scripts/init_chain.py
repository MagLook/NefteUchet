# -*- coding: utf-8 -*-
"""
Создание полной цепочки начальных остатков:
1. Поступление тонн на Основной склад (41.01)
2. Перемещение тонн: Основной → АКЗС Витебский (41.01 → 41.01)
3. Комплектация: тонны → литры на АКЗС Витебский (41.01 → 41.02)

Запуск: py -3.13-32 scripts/init_chain.py
"""
import pythoncom
pythoncom.CoInitialize()
import win32com.client
from datetime import datetime

conn = win32com.client.Dispatch("V83.COMConnector")
ib = conn.Connect(r'File="D:\Users\magsp\GIG Base2";Usr="Гайворонская Татьяна";Pwd="12345"')

# --- Справочники ---
org = ib.Справочники.Организации.НайтиПоНаименованию("ГАЗИНВЕСТГРУПП ООО", True)
осн_склад = ib.Справочники.Склады.НайтиПоНаименованию("Основной склад", True)
азс_склад = ib.Справочники.Склады.НайтиПоНаименованию("АКЗС Витебский", True)

# Контрагент — ищем СУРГУТНЕФТЕГАЗ
q = ib.NewObject("Query")
q.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Контрагенты ГДЕ Наименование ПОДОБНО &Н И НЕ ПометкаУдаления"
q.УстановитьПараметр("Н", "%СУРГУТНЕФТЕГАЗ%")
r = q.Выполнить().Выбрать()
контрагент = r.Ссылка if r.Следующий() else None

# Договор
договор = None
if контрагент:
    q2 = ib.NewObject("Query")
    q2.Text = "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.ДоговорыКонтрагентов ГДЕ Владелец = &К И НЕ ПометкаУдаления"
    q2.УстановитьПараметр("К", контрагент)
    r2 = q2.Выполнить().Выбрать()
    if r2.Следующий():
        договор = r2.Ссылка

# НДС
ндс = None
try: ндс = ib.Перечисления.СтавкиНДС.НДС22
except:
    try: ндс = ib.Перечисления.СтавкиНДС.НДС20
    except: pass

print("Org:", "OK" if org and not org.Пустая() else "FAIL")
print("Main WH:", "OK" if осн_склад and not осн_склад.Пустая() else "FAIL")
print("AZS WH:", "OK" if азс_склад and not азс_склад.Пустая() else "FAIL")
print("Contr:", "OK" if контрагент else "FAIL")
print("Contract:", "OK" if договор else "FAIL")

# Топливо: (наим_тонн, наим_литры, тонны, литры, цена_за_тонну)
FUEL = [
    ("АИ-92(т)",             "АИ-92 (л)",              6.0, 8100, 90500),
    ("АИ-95(т)",             "АИ-95 (л)",              4.0, 5400, 95000),
    ("Дизельное топливо (т)", "Дизельное топливо (л)",  8.0, 9750, 85000),
]

дата = datetime(2026, 3, 1)

# ============================================================
# ШАГ 1: Поступление тонн на Основной склад
# ============================================================
print("\n=== ШАГ 1: Поступление тонн на Основной склад ===")
док1 = ib.Документы.ПоступлениеТоваровУслуг.СоздатьДокумент()
док1.Дата = дата
док1.Организация = org
док1.Комментарий = "TL|INIT_CHAIN|step1"
if контрагент: док1.Контрагент = контрагент
if договор:
    try: док1.ДоговорКонтрагента = договор
    except: pass
try: док1.ВидОперации = ib.Перечисления.ВидыОперацийПоступлениеТоваровУслуг.Получить(0)
except: pass
try: док1.Склад = осн_склад
except: pass

for наим_т, наим_л, тонны, литры, цена in FUEL:
    ном = ib.Справочники.Номенклатура.НайтиПоНаименованию(наим_т, True)
    if not ном or ном.Пустая():
        print(f"  SKIP: {наим_т}")
        continue
    стр = док1.Товары.Добавить()
    стр.Номенклатура = ном
    стр.Количество = тонны
    стр.Цена = цена
    стр.Сумма = тонны * цена
    if ндс:
        try:
            стр.СтавкаНДС = ндс
            стр.СуммаНДС = round(тонны * цена * 22 / 122, 2)
        except: pass
    print(f"  + {наим_т}: {тонны} т x {цена}")

try:
    док1.Записать(ib.РежимЗаписиДокумента.Проведение)
    print("  ПРОВЕДЕНО!")
except Exception as e:
    print(f"  Ошибка проведения: {e}")
    try:
        док1.Записать()
        print("  Записано (без проведения) - проведите в 1С вручную")
    except Exception as e2:
        print(f"  Ошибка записи: {e2}")
        exit(1)

# ============================================================
# ШАГ 2: Перемещение тонн: Основной → АКЗС Витебский
# ============================================================
print("\n=== ШАГ 2: Перемещение тонн на АКЗС ===")
док2 = ib.Документы.ПеремещениеТоваров.СоздатьДокумент()
док2.Дата = дата
док2.Организация = org
док2.Комментарий = "TL|INIT_CHAIN|step2"
try: док2.СкладОтправитель = осн_склад
except: pass
try: док2.СкладПолучатель = азс_склад
except: pass

for наим_т, наим_л, тонны, литры, цена in FUEL:
    ном = ib.Справочники.Номенклатура.НайтиПоНаименованию(наим_т, True)
    if not ном or ном.Пустая(): continue
    стр = док2.Товары.Добавить()
    стр.Номенклатура = ном
    стр.Количество = тонны
    print(f"  + {наим_т}: {тонны} т")

try:
    док2.Записать(ib.РежимЗаписиДокумента.Проведение)
    print("  ПРОВЕДЕНО!")
except Exception as e:
    print(f"  Ошибка проведения: {e}")
    try:
        док2.Записать()
        print("  Записано (без проведения)")
    except Exception as e2:
        print(f"  Ошибка записи: {e2}")

# ============================================================
# ШАГ 3: Комплектация тонны → литры на АКЗС
# ============================================================
print("\n=== ШАГ 3: Комплектация тонны -> литры ===")
for наим_т, наим_л, тонны, литры, цена in FUEL:
    ном_т = ib.Справочники.Номенклатура.НайтиПоНаименованию(наим_т, True)
    ном_л = ib.Справочники.Номенклатура.НайтиПоНаименованию(наим_л, True)
    if not ном_т or ном_т.Пустая() or not ном_л or ном_л.Пустая():
        print(f"  SKIP: {наим_т} or {наим_л}")
        continue

    док3 = ib.Документы.КомплектацияНоменклатуры.СоздатьДокумент()
    док3.Дата = дата
    док3.Организация = org
    док3.Комментарий = f"TL|INIT_CHAIN|step3|{наим_т}"
    try: док3.Склад = азс_склад
    except: pass

    # Комплектующие (расход): тонны
    стр_расход = док3.Комплектующие.Добавить()
    стр_расход.Номенклатура = ном_т
    стр_расход.Количество = тонны

    # Выпуск: литры (через реквизиты или табличную часть)
    try:
        док3.Номенклатура = ном_л
        док3.Количество = литры
    except:
        pass

    плотность = round(тонны * 1000 / литры, 4) if литры > 0 else 0
    print(f"  {наим_т} {тонны}т -> {наим_л} {литры}л (p={плотность})")

    try:
        док3.Записать(ib.РежимЗаписиДокумента.Проведение)
        print("    ПРОВЕДЕНО!")
    except Exception as e:
        print(f"    Ошибка проведения: {e}")
        try:
            док3.Записать()
            print("    Записано (без проведения)")
        except Exception as e2:
            print(f"    Ошибка записи: {e2}")

print("\n=== ГОТОВО ===")
print("Если все 3 шага проведены - на складе АКЗС Витебский есть литры с себестоимостью.")
print("Теперь смены в TradeLedger должны проводиться.")
