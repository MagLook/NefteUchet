print(f"\n{'='*90}")
print("Сверка: Σ ОРП по 90.01.1 (выручка без НДС) + 90.03 (НДС) = СуммаДокумента")
print(f"{'='*90}")

q_check = conn.NewObject("Запрос")
q_check.Текст = f"""
ВЫБРАТЬ
    Док.Ссылка КАК ОРП,
    Док.Номер КАК Н,
    Док.СуммаДокумента КАК ΣДок,
    ВЫБОР КОГДА Прв.СчетКт.Код = "90.01.1" ТОГДА Прв.Сумма ИНАЧЕ 0 КОНЕЦ КАК Выручка,
    ВЫБОР КОГДА Прв.СчетКт.Код = "68.02" ТОГДА Прв.Сумма ИНАЧЕ 0 КОНЕЦ КАК НДС
ИЗ Документ.ОтчетОРозничныхПродажах КАК Док
    ЛЕВОЕ СОЕДИНЕНИЕ РегистрБухгалтерии.Хозрасчетный КАК Прв
        ПО Прв.Регистратор = Док.Ссылка
ГДЕ {ПЕРИОД} И {УСЛ_TL} И Док.Проведен И НЕ Док.ПометкаУдаления
"""
агр = {}
в_c = q_check.Выполнить().Выбрать()
while в_c.Следующий():
    рек = s(в_c.ОРП)
    данные = агр.setdefault(рек, {"номер": s(в_c.Н).strip(),
                                  "сумдок": float(в_c.ΣДок or 0),
                                  "выручка": 0.0, "ндс": 0.0})
    данные["выручка"] += float(в_c.Выручка or 0)
    данные["ндс"] += float(в_c.НДС or 0)

расхождений = 0
для_примеров = []
for рек, дан in агр.items():
    ожидаемо = round(дан["выручка"] + дан["ндс"], 2)
    факт = round(дан["сумдок"], 2)
    разн = abs(факт - ожидаемо)
    if разн > 0.5:  # допустимая погрешность округления
        расхождений += 1
        if len(для_примеров) < 5:
            для_примеров.append((дан["номер"], факт, ожидаемо, разн))

print(f"  Всего проверено ОРП: {len(агр)}")
print(f"  С расхождением: {расхождений}")
if для_примеров:
    print(f"  Примеры расхождений (Σ выручки 90.01.1 + 90.03 ≠ СуммаДокумента):")
    for ном, ф, о, р in для_примеров:
        print(f"    №{ном:<14}  факт={fmt(ф)} ₽  ожидаемо={fmt(о)} ₽  разница={fmt(р)} ₽")
else:
    print(f"  ✓ Все ОРП — сумма по проводкам сходится с СуммаДокумента")
