# -*- coding: utf-8 -*-
"""Одноразовая правка: для базовых ТТН-ключей со статусом «Загружен», у которых
все подключи (|ПЕРЕМ + |КОМПЛ) проведены — обновить статус базового на «Проведён».
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return ""


# Все базовые ТТН-ключи (без подключей) со статусом Загружен
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ Рег.КлючЗагрузки
ИЗ РегистрСведений.TL_СтатусыЗагрузки КАК Рег
ГДЕ Рег.КлючЗагрузки ПОДОБНО "TL|ТТН|%"
  И Рег.Статус = "Загружен"
  И НЕ Рег.КлючЗагрузки ПОДОБНО "TL|ТТН|%|ПЕРЕМ"
  И НЕ Рег.КлючЗагрузки ПОДОБНО "TL|ТТН|%|КОМПЛ"
"""
в = q.Выполнить().Выбрать()
базовые = []
while в.Следующий():
    базовые.append(s(в.КлючЗагрузки))

print(f"Найдено {len(базовые)} базовых ТТН-ключей со статусом «Загружен»")
исправлено = 0
пропущено = 0

for бк in базовые:
    # Проверка: все ли подключи проведены
    qq = conn.NewObject("Запрос")
    qq.УстановитьПараметр("М", бк + "|%")
    qq.Текст = """
    ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Всего,
        СУММА(ВЫБОР КОГДА Статус = "Проведён" ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Пров
    ИЗ РегистрСведений.TL_СтатусыЗагрузки
    ГДЕ КлючЗагрузки ПОДОБНО &М
    """
    вв = qq.Выполнить().Выбрать()
    вв.Следующий()
    всего = int(вв.Всего or 0)
    пров = int(вв.Пров or 0)

    if всего > 0 and всего == пров:
        # Все подключи проведены → обновить базовый
        try:
            мз = conn.NewObject("РегистрСведенийМенеджерЗаписи.TL_СтатусыЗагрузки")
            мз.КлючЗагрузки = бк
            мз.Прочитать()
            if мз.Выбран():
                мз.Статус = "Проведён"
                мз.Записать()
                исправлено += 1
        except Exception as e:
            print(f"  ОШИБКА для {бк}: {e}")
    else:
        пропущено += 1

print(f"\nИсправлено: {исправлено} (статус обновлён на «Проведён»)")
print(f"Пропущено:  {пропущено} (подключи ещё не проведены / удалены)")
