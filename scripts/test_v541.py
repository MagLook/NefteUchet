# -*- coding: utf-8 -*-
"""
Имитация открытия формы Загрузки: вызов TL_Настройки.ОпроситьВсеСетиИзAPI
+ ручное сохранение Станция_X_КодСистемы (как делает форма теперь),
+ проверка ПолучитьКодСистемыСтанции(208/210) -> ожидаем 15.
"""
import win32com.client
BASE = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"

com = win32com.client.Dispatch("V83.COMConnector")
conn = com.Connect(f'File="{BASE}";Usr="{USER}";Pwd="{PWD}";')

URL = conn.TL_Настройки.ПолучитьЗначение("URLСервера", "")
LG = conn.TL_Настройки.ПолучитьЗначение("Логин", "")
PW = conn.TL_Настройки.ПолучитьЗначение("Пароль", "")

# Шаг 1: Опросим API (как делает форма Загрузки в ПриСозданииНаСервере)
Рез = conn.TL_Настройки.ОпроситьВсеСетиИзAPI(URL, LG, PW)
print(f"API вернул: {Рез.Станции.Количество()} станций")

# Шаг 2: Сохраним КодСистемы и Наименование (форма теперь делает то же)
for i in range(Рез.Станции.Количество()):
    ОС = Рез.Станции[i]
    КодСтр = str(ОС.Код)
    if conn.TL_Настройки.ПолучитьЧисло(f"Станция_{КодСтр}_КодСистемы", 0) == 0:
        conn.TL_Настройки.УстановитьЗначение(
            f"Станция_{КодСтр}_КодСистемы", str(int(ОС.КодСистемы)), "Сеть станции (auto)")
        print(f"  Записано: Станция_{КодСтр}_КодСистемы = {int(ОС.КодСистемы)}")
    if not conn.TL_Настройки.ПолучитьЗначение(f"Станция_{КодСтр}_Наименование", ""):
        conn.TL_Настройки.УстановитьЗначение(
            f"Станция_{КодСтр}_Наименование", str(ОС.Наименование), "Имя (auto)")

# Шаг 3: Проверка
print()
print("=== Проверка маршрутизации сетей ===")
for код in [5, 208, 209, 210]:
    сеть = conn.TL_Настройки.ПолучитьКодСистемыСтанции(код)
    print(f"  Станция {код:>3} -> сеть {сеть}")

# Шаг 4: Список ВСЕХ станций после правок
print()
print("=== ПолучитьВсеСтанции() ===")
ВСтан = conn.TL_Настройки.ПолучитьВсеСтанции()
print(f"  Всего: {ВСтан.Количество()}")
for i in range(ВСтан.Количество()):
    Стр = ВСтан[i]
    скл = str(Стр.Склад) if str(Стр.Склад) else "(нет склада)"
    print(f"  ст.{Стр.Код:>3}  сеть={int(Стр.КодСистемы):>2}  склад={скл[:30]:30}  {str(Стр.Наименование)[:30]}")

# Шаг 5: ПолучитьВсеСетиДляОпроса
print()
print("=== ПолучитьВсеСетиДляОпроса ===")
Сети = conn.TL_Настройки.ПолучитьВсеСетиДляОпроса()
for i in range(Сети.Количество()):
    print(f"  {Сети[i]}")
