# -*- coding: utf-8 -*-
"""Проверить ПометкуУдаления у старых документов смены 3867.
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return "—"
    try: return str(v)
    except Exception: return repr(v)


print("=" * 90)
print("ПометкаУдаления для всех документов смены 209/3867")
print("=" * 90)

ТИПЫ = [
    ("Документ.ОтчетОРозничныхПродажах",     "ОРП"),
    ("Документ.ПеремещениеТоваров",          "Перемещ"),
    ("Документ.СписаниеТоваров",             "Списан"),
    ("Документ.ПриходныйКассовыйОрдер",      "ПКО"),
]

всего = 0
помечено = 0
проведено = 0

for менеджер, краткое in ТИПЫ:
    q = conn.NewObject("Запрос")
    q.Текст = f"""
    ВЫБРАТЬ
        Док.Номер КАК Ном, Док.Дата КАК Дата,
        Док.Проведен КАК Пров,
        Док.ПометкаУдаления КАК Помечен,
        Док.Комментарий КАК Ком
    ИЗ {менеджер} КАК Док
    ГДЕ Док.Комментарий ПОДОБНО "%3867%"
    УПОРЯДОЧИТЬ ПО Док.Номер
    """
    в = q.Выполнить().Выбрать()
    print(f"\n=== {краткое} ===")
    while в.Следующий():
        всего += 1
        ном = s(в.Ном).strip()
        пр = bool(в.Пров)
        пом = bool(в.Помечен)
        if пом: помечено += 1
        if пр: проведено += 1
        зн = "✓" if пр else ("✗" if пом else "○")
        пом_зн = " [ПОМЕЧЕН НА УДАЛЕНИЕ]" if пом else ""
        пр_зн = "ПРОВЕДЁН" if пр else "НЕ проведён"
        print(f"  {зн} №{ном:<14} {пр_зн:<14}{пом_зн}")

print(f"\n{'='*90}")
print(f"Итого: {всего} документов, помечено на удаление: {помечено}, проведено: {проведено}")
