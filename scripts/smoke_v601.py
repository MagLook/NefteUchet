# -*- coding: utf-8 -*-
"""
Smoke v6.0.1: проверяем что после фикса TL_Маппинг.ЗаполнитьМаппингОплатПоУмолчанию
не падает и реально заполняет регистр TL_МаппингОплат.
"""
import sys, win32com.client
sys.stdout.reconfigure(encoding="utf-8")

base = r"D:\Users\magsp\GIG Base2"
user = "Гайворонская Татьяна"
pwd = "12345"

conn = win32com.client.Dispatch("V83.COMConnector").Connect(
    f'File="{base}";Usr="{user}";Pwd="{pwd}";'
)
print("Подключение установлено")

# 1. Сколько строк в маппинге сейчас
q = conn.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ РегистрСведений.TL_МаппингОплат"
v = q.Выполнить().Выбрать()
v.Следующий()
до = int(v.Кол)
print(f"  TL_МаппингОплат ДО вызова: {до} строк")

# 2. Очистим регистр для чистоты эксперимента
print("\nОчищаю регистр для чистоты теста...")
набор = conn.РегистрыСведений.TL_МаппингОплат.СоздатьНаборЗаписей()
набор.Записать()  # пустой набор = удаление всех записей

q.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ РегистрСведений.TL_МаппингОплат"
v = q.Выполнить().Выбрать()
v.Следующий()
после_очистки = int(v.Кол)
print(f"  TL_МаппингОплат после очистки: {после_очистки} строк")

# 3. Вызываем ЗаполнитьМаппингОплатПоУмолчанию через TL_Маппинг
print("\nВызываю TL_Маппинг.ЗаполнитьМаппингОплатПоУмолчанию()...")
try:
    conn.TL_Маппинг.ЗаполнитьМаппингОплатПоУмолчанию()
    print("  [PASS] вызов не упал")
except Exception as e:
    print(f"  [FAIL] исключение: {e}")
    sys.exit(1)

# 4. Сколько строк стало
q.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ РегистрСведений.TL_МаппингОплат"
v = q.Выполнить().Выбрать()
v.Следующий()
после = int(v.Кол)
print(f"  TL_МаппингОплат ПОСЛЕ: {после} строк")

if после == 15:
    print("  [PASS] заполнено ровно 15 образцов")
elif после >= 13:
    print(f"  [PASS-mostly] заполнено {после} образцов (часть могла не заполниться из-за отсутствия складов)")
else:
    print(f"  [FAIL] ожидалось 15, реально {после}")
    sys.exit(1)

# 5. Перечислим образцы
print("\nОбразцы маппинга:")
q.Текст = (
    "ВЫБРАТЬ ОбразецИмени, КаналОплаты, Склад "
    "ИЗ РегистрСведений.TL_МаппингОплат "
    "УПОРЯДОЧИТЬ ПО КаналОплаты, ОбразецИмени"
)
v = q.Выполнить().Выбрать()
i = 0
while v.Следующий():
    i += 1
    канал = str(v.КаналОплаты) if v.КаналОплаты else "(игнор)"
    склад = str(v.Склад) if v.Склад else "-"
    print(f"  {i:2}. {v.ОбразецИмени:14} → {канал:14} → {склад}")

# 6. Проверим что вызов второй раз не дублирует записи
print("\nВызываю второй раз (должно остаться столько же, без дублей)...")
conn.TL_Маппинг.ЗаполнитьМаппингОплатПоУмолчанию()
q.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ РегистрСведений.TL_МаппингОплат"
v = q.Выполнить().Выбрать()
v.Следующий()
после2 = int(v.Кол)
print(f"  TL_МаппингОплат после 2-го вызова: {после2} строк")
if после2 == после:
    print("  [PASS] идемпотентно — без дублирования")
else:
    print(f"  [FAIL] было {после}, стало {после2} — есть дублирование")
    sys.exit(1)

print("\n=== ВСЕ ШАГИ ПРОЙДЕНЫ ===")
