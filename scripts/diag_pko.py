import sys, datetime, io
import win32com.client

BASE_PATH = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"
OUT_PATH = r"D:\Users\magsp\ELSYPLUS\NefteUchet\scripts\_out_pko.txt"

OUT = open(OUT_PATH, "w", encoding="utf-8")

def p(*a):
    print(*a, file=OUT)

def hr(t=""):
    p()
    p("=" * 78)
    if t: p(t)
    p("=" * 78)

def s(v):
    """Строковое представление 1С-значения через .Наименование/.Код/.Номер/str()."""
    if v is None: return ""
    # Для COM-объектов str() даёт <COMObject> — надо подобрать атрибут
    sv = str(v)
    if "<COMObject" in sv or "unknown" in sv:
        # перечисления (Розничная выручка и т.д.)
        for attr in ("Представление", "Наименование", "Имя", "Код"):
            try:
                a = getattr(v, attr)
                if a is None: continue
                a_s = str(a)
                if a_s and "<COMObject" not in a_s: return a_s
            except Exception:
                continue
        # документ-ссылка: Номер + Дата
        try:
            n = getattr(v, "Номер"); d = getattr(v, "Дата")
            if n is not None: return f"{n} от {d}"
        except Exception: pass
        return ""
    return sv

def acc(c):
    try:
        k = str(c.Код)
        if k and "<COMObject" not in k: return k
    except Exception: pass
    return s(c)

def main():
    com = win32com.client.Dispatch("V83.COMConnector")
    conn = com.Connect(f'File="{BASE_PATH}";Usr="{USER}";Pwd="{PWD}";')

    DOC_NAME = "ПриходныйКассовыйОрдер"
    md = conn.Метаданные.НайтиПоПолномуИмени(f"Документ.{DOC_NAME}")
    if md is None:
        p("Документ не найден"); return

    hr(f"0) Метаданные Документ.{DOC_NAME}")
    p(f"  Синоним: {md.Синоним}")
    p(f"  Реквизиты:")
    for rq in md.Реквизиты:
        try: t = str(rq.Тип)
        except Exception: t = ""
        p(f"    {rq.Имя:35} тип={t[:80]}")

    hr("1) Поиск ГИ0Г-000419 + последние 30 документов")
    q = conn.NewObject("Запрос")
    q.Текст = f'''
    ВЫБРАТЬ ПЕРВЫЕ 30
        Ссылка, Номер, Дата, ВидОперации, СуммаДокумента, Организация, Проведен, Комментарий
    ИЗ Документ.{DOC_NAME}
    УПОРЯДОЧИТЬ ПО Дата УБЫВ
    '''
    sel = q.Выполнить().Выбрать()
    docs = []
    target = None
    while sel.Следующий():
        ref = sel.Ссылка
        n = s(sel.Номер); d = sel.Дата; sm = sel.СуммаДокумента
        v = s(sel.ВидОперации); pr = sel.Проведен
        marker = ""
        if "419" in n:
            marker = " ← ИСКОМЫЙ"; target = ref
        p(f"  {n:>16}  {d}  Σ={sm:>10.2f}  вид={v[:30]:30}  пров={pr}{marker}")
        docs.append(ref)

    if target is None:
        # Поищем 419 шире — за всю историю
        q2 = conn.NewObject("Запрос")
        q2.Текст = f'''
        ВЫБРАТЬ ПЕРВЫЕ 5 Ссылка, Номер, Дата
        ИЗ Документ.{DOC_NAME}
        ГДЕ Номер ПОДОБНО "%419%"
        '''
        sel2 = q2.Выполнить().Выбрать()
        while sel2.Следующий():
            target = sel2.Ссылка
            p(f"  Найдено по подстроке '419': {s(sel2.Номер)} от {sel2.Дата}")
            break

    if target is None and docs:
        # Берём проведённый "Розничная выручка"
        for d in docs:
            obj = d.ПолучитьОбъект()
            if obj.Проведен and "озничн" in s(obj.ВидОперации):
                target = d; break
        if target is None:
            target = docs[0]

    if target is None:
        p("Целевой документ не найден"); return

    obj = target.ПолучитьОбъект()
    hr(f"2) Документ {s(obj.Номер)} от {obj.Дата} — все реквизиты")
    for rq in md.Реквизиты:
        try:
            v = getattr(obj, rq.Имя)
            sv = s(v)
            if not sv: continue
            p(f"    {rq.Имя:35} = {sv[:120]}")
        except Exception as e:
            p(f"    {rq.Имя:35} ОШИБКА {e}")

    hr("3) Проводки документа")
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Регистратор", target)
    q.Текст = '''
    ВЫБРАТЬ Период, СчетДт, СчетКт, Сумма, Содержание
    ИЗ РегистрБухгалтерии.Хозрасчетный
    ГДЕ Регистратор = &Регистратор
    УПОРЯДОЧИТЬ ПО НомерСтроки
    '''
    sel = q.Выполнить().Выбрать()
    npr = 0
    while sel.Следующий():
        npr += 1
        p(f"  Дт {acc(sel.СчетДт):>8}  Кт {acc(sel.СчетКт):>8}  = {sel.Сумма:>12.2f}  | {s(sel.Содержание)[:55]}")
    p(f"  Всего проводок: {npr}")
    if npr == 0:
        p(f"  *** ПРОВОДОК НЕТ — документ не делает движений ***")

    # Движения по другим регистрам
    hr("3b) Движения по ДРУГИМ регистрам этого документа")
    реги = []
    try:
        # перебираем регистры накопления и сведений где может быть запись
        for reg in conn.Метаданные.РегистрыНакопления:
            try:
                rs = getattr(conn.РегистрыНакопления, reg.Имя).Выбрать(None, None, {"Регистратор": target})
                cnt = 0
                while rs.Следующий(): cnt += 1
                if cnt: реги.append((reg.Имя, "Накопления", cnt))
            except Exception: pass
    except Exception: pass

    for nm, kind, cnt in реги:
        p(f"  Регистр{kind}.{nm}: {cnt} записей")
    if not реги:
        p("  Других движений нет (только бухучёт)")

    hr("4) Связь с ОРП за тот же день / тот же склад")
    склад = None
    try: склад = obj.Склад
    except Exception: pass
    p(f"  Дата документа: {obj.Дата}")
    p(f"  Склад: {s(склад)}")
    p(f"  Организация: {s(obj.Организация)}")
    p(f"  ВидОперации: {s(obj.ВидОперации)}")

    if not склад:
        p("  ⚠ В документе НЕ заполнен Склад — связь с ОРП не однозначна")

    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Дата", obj.Дата)
    q.УстановитьПараметр("Орг", obj.Организация)
    q.УстановитьПараметр("Склад", склад)
    if склад:
        q.Текст = '''
        ВЫБРАТЬ
            Ссылка, Номер, Дата, СуммаДокумента, Проведен, Комментарий
        ИЗ Документ.ОтчетОРозничныхПродажах
        ГДЕ НАЧАЛОПЕРИОДА(Дата, ДЕНЬ) = НАЧАЛОПЕРИОДА(&Дата, ДЕНЬ)
            И Склад = &Склад
            И Организация = &Орг
        УПОРЯДОЧИТЬ ПО Дата
        '''
    else:
        q.Текст = '''
        ВЫБРАТЬ
            Ссылка, Номер, Дата, Склад, СуммаДокумента, Проведен, Комментарий
        ИЗ Документ.ОтчетОРозничныхПродажах
        ГДЕ НАЧАЛОПЕРИОДА(Дата, ДЕНЬ) = НАЧАЛОПЕРИОДА(&Дата, ДЕНЬ)
            И Организация = &Орг
        УПОРЯДОЧИТЬ ПО Дата
        '''
    sel = q.Выполнить().Выбрать()
    orps = []
    while sel.Следующий():
        orps.append(sel.Ссылка)
        try: wh = s(sel.Склад)
        except: wh = "(тот же)"
        p(f"  ОРП {s(sel.Номер):>15}  Σ={sel.СуммаДокумента:>10.2f}  пров={sel.Проведен}  склад={wh[:25]}  ком={s(sel.Комментарий)[:40]}")
    p(f"  ОРП за тот же день: {len(orps)}")

    if orps:
        hr("5) Сравнение сумм: ОРП наличные vs документ ПКО")
        target_sum = obj.СуммаДокумента
        for orp_ref in orps:
            orp_obj = orp_ref.ПолучитьОбъект()
            if not orp_obj.Проведен: continue
            p(f"\n  ОРП {s(orp_obj.Номер)} (Σ={orp_obj.СуммаДокумента:.2f}):")

            # Безналичные оплаты ОРП
            try:
                bezn = orp_obj.БезналичныеОплаты
                btotal = 0.0
                for i in range(bezn.Количество()):
                    row = bezn.Получить(i)
                    btotal += (row.Сумма or 0)
                p(f"    ТЧ БезналичныеОплаты: {bezn.Количество()} строк, Σ={btotal:.2f}")
                p(f"    → Расчётный 'налично': {orp_obj.СуммаДокумента - btotal:.2f}")
                p(f"    → ПКО {s(obj.Номер)} Σ={target_sum:.2f}  "
                  f"({'СОВПАЛО' if abs(target_sum - (orp_obj.СуммаДокумента - btotal)) < 0.01 else 'НЕ совпало'})")
            except Exception as e:
                p(f"    БезналичныеОплаты ошибка: {e}")

            # Проводки ОРП по сч.50/57/62Р
            q2 = conn.NewObject("Запрос")
            q2.УстановитьПараметр("Регистратор", orp_ref)
            q2.Текст = '''
            ВЫБРАТЬ
                ВЫРАЗИТЬ(СчетДт.Код КАК СТРОКА(20)) КАК ДтКод,
                ВЫРАЗИТЬ(СчетКт.Код КАК СТРОКА(20)) КАК КтКод,
                Сумма, Содержание
            ИЗ РегистрБухгалтерии.Хозрасчетный
            ГДЕ Регистратор = &Регистратор
            УПОРЯДОЧИТЬ ПО НомерСтроки
            '''
            sel2 = q2.Выполнить().Выбрать()
            p(f"    Все проводки ОРП:")
            kall = 0
            while sel2.Следующий():
                kall += 1
                dt = sel2.ДтКод or ""; kt = sel2.КтКод or ""
                mark = " ★" if (dt.startswith("50") or kt.startswith("50")) else ""
                p(f"      Дт {dt:>8} Кт {kt:>8}  Σ={sel2.Сумма:>10.2f}  | {s(sel2.Содержание)[:50]}{mark}")
            p(f"    Всего проводок ОРП: {kall}")

    hr("6) Свод за 30 дней — все ВидыОперации ПКО")
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Стоп", datetime.datetime.now())
    q.Текст = f'''
    ВЫБРАТЬ
        ВидОперации, КОЛИЧЕСТВО(*) КАК Кол, СУММА(СуммаДокумента) КАК Сумма
    ИЗ Документ.{DOC_NAME}
    ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30)
    СГРУППИРОВАТЬ ПО ВидОперации
    '''
    sel = q.Выполнить().Выбрать()
    while sel.Следующий():
        p(f"    {s(sel.ВидОперации):40} кол={sel.Кол:>4}  Σ={sel.Сумма or 0:>14.2f}")

    hr("7) Соответствие ОРП ↔ ПКО за 30 дней по дням (Розничная выручка)")
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Стоп", datetime.datetime.now())
    q.Текст = '''
    ВЫБРАТЬ
        НАЧАЛОПЕРИОДА(Дата, ДЕНЬ) КАК День,
        КОЛИЧЕСТВО(*) КАК Кол, СУММА(СуммаДокумента) КАК Сумма
    ИЗ Документ.ОтчетОРозничныхПродажах
    ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30) И Проведен
    СГРУППИРОВАТЬ ПО НАЧАЛОПЕРИОДА(Дата, ДЕНЬ)
    УПОРЯДОЧИТЬ ПО День
    '''
    by_day_orp = {}
    sel = q.Выполнить().Выбрать()
    while sel.Следующий():
        by_day_orp[s(sel.День)[:10]] = (sel.Кол, sel.Сумма)

    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Стоп", datetime.datetime.now())
    q.Текст = f'''
    ВЫБРАТЬ
        НАЧАЛОПЕРИОДА(Дата, ДЕНЬ) КАК День,
        КОЛИЧЕСТВО(*) КАК Кол, СУММА(СуммаДокумента) КАК Сумма
    ИЗ Документ.{DOC_NAME}
    ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30) И Проведен
    СГРУППИРОВАТЬ ПО НАЧАЛОПЕРИОДА(Дата, ДЕНЬ)
    УПОРЯДОЧИТЬ ПО День
    '''
    by_day_pko = {}
    sel = q.Выполнить().Выбрать()
    while sel.Следующий():
        by_day_pko[s(sel.День)[:10]] = (sel.Кол, sel.Сумма)

    all_days = sorted(set(by_day_orp.keys()) | set(by_day_pko.keys()))
    p(f"  {'День':12} {'ОРП кол':>7} {'ОРП Σ':>12}  {'ПКО кол':>7} {'ПКО Σ':>12}")
    for d in all_days:
        oc, os_ = by_day_orp.get(d, (0, 0))
        pc, ps_ = by_day_pko.get(d, (0, 0))
        p(f"  {d:12} {oc:>7} {os_ or 0:>12.2f}  {pc:>7} {ps_ or 0:>12.2f}")

if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        import traceback
        p("ИСКЛЮЧЕНИЕ:")
        p(traceback.format_exc())
    finally:
        OUT.close()
        print(f"Готово, см. {OUT_PATH}")
