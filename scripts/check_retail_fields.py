# -*- coding: utf-8 -*-
"""Check retail price fields via query. Run: py -3.13-32 scripts/check_retail_fields.py"""
import pythoncom, io
pythoncom.CoInitialize()
import win32com.client

conn = win32com.client.Dispatch("V83.COMConnector")
ib = conn.Connect(r'File="D:\Users\magsp\GIG Base2";Usr="Гайворонская Татьяна";Pwd="12345"')

out = io.open(r"D:\Users\magsp\ELSYPLUS\NefteUchet\build\retail_fields.txt", "w", encoding="utf-8")

# Check OUR doc
q = ib.NewObject("Query")
q.Text = """ВЫБРАТЬ
    Т.Номенклатура.Наименование КАК Ном,
    Т.Количество, Т.Цена, Т.Сумма,
    Т.ЦенаВРознице, Т.СуммаВРознице, Т.СтавкаНДСВРознице
ИЗ Документ.ОтчетОРозничныхПродажах.Товары КАК Т
ГДЕ Т.Ссылка.Комментарий ПОДОБНО &М И НЕ Т.Ссылка.ПометкаУдаления
УПОРЯДОЧИТЬ ПО Т.Ссылка.Дата УБЫВ"""
q.УстановитьПараметр("М", "%TL|СМЕНА%")
r = q.Выполнить().Выбрать()
out.write("=== НАШ документ ===\n")
while r.Следующий():
    out.write(f"  [{r.Ном}] кол:{r.Количество} цена:{r.Цена} сумма:{r.Сумма} рознЦена:{r.ЦенаВРознице} рознСумма:{r.СуммаВРознице} рознНДС:{r.СтавкаНДСВРознице}\n")

# Check БУХГАЛТЕРСКИЙ doc
q2 = ib.NewObject("Query")
q2.Text = """ВЫБРАТЬ ПЕРВЫЕ 3
    Т.Номенклатура.Наименование КАК Ном,
    Т.Количество, Т.Цена, Т.Сумма,
    Т.ЦенаВРознице, Т.СуммаВРознице, Т.СтавкаНДСВРознице
ИЗ Документ.ОтчетОРозничныхПродажах.Товары КАК Т
ГДЕ Т.Ссылка.Проведен И Т.Ссылка.Склад.Наименование = &С
    И Т.Ссылка.Комментарий НЕ ПОДОБНО &М"""
q2.УстановитьПараметр("С", "АКЗС Витебский")
q2.УстановитьПараметр("М", "%TL|%")
r2 = q2.Выполнить().Выбрать()
out.write("\n=== БУХГАЛТЕРСКИЙ ===\n")
while r2.Следующий():
    out.write(f"  [{r2.Ном}] кол:{r2.Количество} цена:{r2.Цена} сумма:{r2.Сумма} рознЦена:{r2.ЦенаВРознице} рознСумма:{r2.СуммаВРознице} рознНДС:{r2.СтавкаНДСВРознице}\n")

out.close()
print("Done")
