# -*- coding: utf-8 -*-
"""Что было загружено в БП ГИГ из последних N пакетов:
- Список документов в TL_СоответствиеИсточников по каждому пакету
- Какие kind проведены / записаны / ошибки
- Сверка по числу и сумме
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()

# Свежие пакеты из TL_СверкаПакета
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 8
    С.ИдентификаторПакета КАК ИдПакета,
    С.НомерСмены КАК Смена,
    С.ДатаСмены КАК ДатаСмены,
    С.КодАЗС КАК КодАЗС,
    С.СуммаЦБ КАК СуммаЦБ,
    С.СуммаБП КАК СуммаБП,
    С.СтрокДокументов КАК ВсегоДок,
    С.Статус КАК Статус,
    С.ВремяЗагрузки КАК Записан
ИЗ РегистрСведений.TL_СверкаПакета КАК С
УПОРЯДОЧИТЬ ПО С.ВремяЗагрузки УБЫВ
"""
sel = q.Выполнить().Выбрать()
пакеты = []
while sel.Следующий():
    пакеты.append({
        "ид": str(sel.ИдПакета),
        "смена": str(sel.Смена).strip(),
        "дата": str(sel.ДатаСмены),
        "азс": int(sel.КодАЗС),
        "сум_цб": float(sel.СуммаЦБ),
        "сум_бп": float(sel.СуммаБП),
        "всего_док": int(sel.ВсегоДок),
        "статус": conn.XMLСтрока(sel.Статус) if sel.Статус else "?",
        "записан": str(sel.Записан),
    })

print("=" * 100)
print(f"СВЕРКА {len(пакеты)} ПОСЛЕДНИХ ПАКЕТОВ")
print("=" * 100)

for п in пакеты:
    расх = п["сум_цб"] - п["сум_бп"]
    проц = (расх / п["сум_цб"] * 100) if п["сум_цб"] else 0
    print()
    print(f"━━━ Пакет {п['ид'][:8]}... ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━")
    print(f"  АЗС {п['азс']} · смена {п['смена']} · дата смены {п['дата'][:10]} · загружен {п['записан']} · {п['статус']}")
    print(f"  СуммаЦБ={п['сум_цб']:>14,.2f}  СуммаБП={п['сум_бп']:>14,.2f}  Расх={расх:>13,.2f} ({проц:+5.1f}%)")
    print(f"  Строк документов: {п['всего_док']}")

    # Что создано в БП из этого пакета
    q2 = conn.NewObject("Запрос")
    q2.Текст = """
    ВЫБРАТЬ
        С.Тип КАК Тип,
        С.ИсточникUUID КАК UUID,
        С.СсылкаОбъект КАК Док
    ИЗ РегистрСведений.TL_СоответствиеИсточников КАК С
    ГДЕ С.ИдентификаторПоследнегоПакета = &ИдП
    """
    q2.УстановитьПараметр("ИдП", п["ид"])
    с2 = q2.Выполнить().Выбрать()
    создано = []
    while с2.Следующий():
        тип = conn.XMLСтрока(с2.Тип) if с2.Тип else "?"
        док_ref = с2.Док
        try:
            ном = str(док_ref.Номер).strip() if док_ref else "—"
            проведен = "✓" if (док_ref and док_ref.Проведен) else ("○" if док_ref else "—")
            кл = str(док_ref) if док_ref else "—"
        except Exception as e:
            ном = "?"; проведен = "?"; кл = f"<err {e}>"
        создано.append({"тип": тип, "ном": ном, "пров": проведен, "док": кл})

    if создано:
        print(f"  Создано документов: {len(создано)}")
        # Сводка по типам
        по_типу = {}
        for c in создано:
            ключ = c["тип"]
            по_типу.setdefault(ключ, {"всего": 0, "проведено": 0})
            по_типу[ключ]["всего"] += 1
            if c["пров"] == "✓":
                по_типу[ключ]["проведено"] += 1
        for тип, ст in по_типу.items():
            print(f"    {тип}: {ст['проведено']}/{ст['всего']} проведено")
    else:
        print(f"  ⚠ Создано документов: 0")

    # Ошибки этого пакета
    q3 = conn.NewObject("Запрос")
    q3.Текст = """
    ВЫБРАТЬ
        О.ТипОбъекта КАК Тип,
        О.КодОшибки КАК Код,
        О.СообщениеОшибки КАК Сообщение
    ИЗ РегистрСведений.TL_ОшибкиЗагрузки КАК О
    ГДЕ О.ИдентификаторПакета = &ИдП
    """
    q3.УстановитьПараметр("ИдП", п["ид"])
    с3 = q3.Выполнить().Выбрать()
    ошибки = []
    while с3.Следующий():
        ошибки.append({
            "тип": conn.XMLСтрока(с3.Тип) if с3.Тип else "?",
            "код": conn.XMLСтрока(с3.Код) if с3.Код else "?",
            "сообщ": (str(с3.Сообщение)[:120] if с3.Сообщение else "")
        })
    if ошибки:
        print(f"  ⚠ Ошибки ({len(ошибки)}):")
        for o in ошибки[:5]:
            print(f"    [{o['код']}] {o['тип']}: {o['сообщ']}")
