"""Check accounting balances simplified. Run: py -3.13-32 scripts/check_bu2.py"""
import pythoncom, io
pythoncom.CoInitialize()
import win32com.client

conn = win32com.client.Dispatch("V83.COMConnector")
ib = conn.Connect(r'File="D:\Users\magsp\GIG Base2";Usr="Гайворонская Татьяна";Pwd="12345"')

out = io.open(r"D:\Users\magsp\ELSYPLUS\NefteUchet\build\bu_check2.txt", "w", encoding="utf-8")

# Простой запрос: обороты по 41.02 за март
out.write("=== Обороты по 41.02 за март 2026 ===\n")
try:
    q = ib.NewObject("Query")
    q.Text = """ВЫБРАТЬ
        Субконто1.Наименование КАК Номенклатура,
        Субконто2.Наименование КАК Склад,
        СуммаОборотДт, КоличествоОборотДт,
        СуммаОборотКт, КоличествоОборотКт,
        СуммаОстатокДт КАК СальдоСумма,
        КоличествоОстатокДт КАК СальдоКол
    ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(
        &ДатаНач, &ДатаКон,,
        Счет = &Счет,,,,)
    ГДЕ КоличествоОстатокДт <> 0 ИЛИ КоличествоОборотДт <> 0"""
    счет4102 = ib.ПланыСчетов.Хозрасчетный.НайтиПоКоду("41.02")
    from datetime import datetime
    q.УстановитьПараметр("ДатаНач", datetime(2026, 3, 1))
    q.УстановитьПараметр("ДатаКон", datetime(2026, 3, 31))
    q.УстановитьПараметр("Счет", счет4102)
    r = q.Выполнить().Выбрать()
    while r.Следующий():
        out.write(f"  [{r.Номенклатура}] [{r.Склад}]: Дт={r.КоличествоОборотДт} Кт={r.КоличествоОборотКт} Сальдо={r.СальдоКол} ({r.СальдоСумма} руб)\n")
except Exception as e:
    out.write(f"  Ошибка: {e}\n")

# То же для 41.01
