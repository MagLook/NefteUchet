BASE_PATH = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"; PWD = "12345"

com = win32com.client.Dispatch("V83.COMConnector")
conn = com.Connect(f'File="{BASE_PATH}";Usr="{USER}";Pwd="{PWD}";')

print("="*90)
print("1) Все склады с потенциально 'виртуальной' семантикой")
print("="*90)
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    Ссылка,
    Код,
    Наименование,
    ТипСклада,
    ПометкаУдаления,
    Родитель
ИЗ Справочник.Склады
УПОРЯДОЧИТЬ ПО Наименование
"""
sel = q.Выполнить().Выбрать()
allw = []
while sel.Следующий():
    allw.append({
        "ссылка": sel.Ссылка,
        "код": str(sel.Код),
        "имя": str(sel.Наименование),
        "тип": str(sel.ТипСклада),
        "уд":  bool(sel.ПометкаУдаления),
        "род": str(sel.Родитель),
    })

# Сначала покажем подозреваемых: содержащих ключевые слова
keywords = ["карт","viacard","via","балтоп","baltop","ведомост","ledger",
            "яндекс","yandex","benzuber","купон","мобил","online","talon","талон",
            "вирту"]
print(f"\nВсего складов в Catalog.Склады: {len(allw)}")
print("\n--- 'Виртуальные' (по ключевым словам) ---")
for w in allw:
    low = w["имя"].lower() + " " + w["код"].lower()
    if any(k in low for k in keywords):
        m = " [УДАЛ]" if w["уд"] else ""
        print(f"  код={w['код']:>8}  тип={w['тип']:14}  имя={w['имя']!r}  род={w['род']!r}{m}")

# Показ всех не-АЗС-складов (предположительно виртуальные/прочие)
print("\n--- Все НЕ-АЗС-склады (имя без 'АЗС') ---")
for w in allw:
    if w["уд"]: continue
    if "азс" in w["имя"].lower(): continue
    print(f"  код={w['код']:>8}  тип={w['тип']:14}  имя={w['имя']!r}")

