# -*- coding: utf-8 -*-
"""Probe: ВСЕ документы созданные на стенде GIG Base2 за последние 3 дня.
Без фильтров по маркеру комментария — чтобы найти всё что МАГ провёл руками.
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def fmt_date(d):
    try:
        return d.strftime("%d.%m %H:%M:%S")
    except Exception:
        return str(d)


print("=" * 100)
print("Probe всех документов на стенде GIG Base2 за 20-22.05.2026")
print("=" * 100)

ТИПЫ = [
    ("Документ.ОтчетОРозничныхПродажах",      "ОРП"),
    ("Документ.ПоступлениеТоваровУслуг",      "ПТУ"),
    ("Документ.ПеремещениеТоваров",           "Перем"),
    ("Документ.СписаниеТоваров",              "Списан"),
    ("Документ.ОтчетПроизводстваЗаСмену",     "ОПЗС"),
    ("Документ.КорректировкаПоступления",     "КорПост"),
    ("Документ.ИнвентаризацияТоваровНаСкладе","Инв"),
    ("Документ.ОприходованиеТоваров",         "Опр"),
    ("Документ.ПриходныйКассовыйОрдер",       "ПКО"),
]

всего_по_типам = {}

for менеджер, краткое in ТИПЫ:
    try:
        q = conn.NewObject("Запрос")
        q.Текст = f"""
        ВЫБРАТЬ
            Док.Ссылка       КАК Ссылка,
            Док.Номер        КАК Номер,
            Док.Дата         КАК Дата,
            Док.Проведен     КАК Проведен,
            Док.СуммаДокумента КАК Сумма,
            Док.Комментарий  КАК Комментарий
        ИЗ {менеджер} КАК Док
        ГДЕ Док.Дата >= ДАТАВРЕМЯ(2026,5,20,0,0,0)
          И Док.Дата <= ДАТАВРЕМЯ(2026,5,22,23,59,59)
        УПОРЯДОЧИТЬ ПО Док.Дата
        """
        в = q.Выполнить().Выбрать()
        строки = []
        while в.Следующий():
            строки.append({
                "ном": str(в.Номер).strip(),
                "дата": fmt_date(в.Дата),
                "пров": bool(в.Проведен),
                "сум": float(в.Сумма or 0),
                "ком": str(в.Комментарий or "")[:70],
            })
        if строки:
            всего_по_типам[краткое] = строки
    except Exception as ex:
        print(f"  [{краткое}] ОШИБКА: {ex}")

if not всего_по_типам:
    print("\nЗа период 20-22.05 на стенде НИКАКИХ документов не создано.")
    print("Возможно МАГ работал на другой базе (192.168.40.31 / 1c-dev-01).")
else:
    print()
    for краткое, строки in всего_по_типам.items():
        провед = sum(1 for с in строки if с["пров"])
        непр = len(строки) - провед
        print(f"=== {краткое}: всего {len(строки)} (проведено {провед}, не проведено {непр}) ===")
        for с in строки[:20]:
            знак = "✓" if с["пров"] else "○"
            сум = f"{с['сум']:>12,.2f}".replace(",", " ")
            print(f"  {знак} {с['ном']:<14} {с['дата']:<18} {сум} ₽  {с['ком']}")
        if len(строки) > 20:
            print(f"  ... ещё {len(строки)-20}")
        print()

print("=" * 100)
