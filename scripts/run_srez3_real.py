def загрузить_в_бп_гиг(путь_пакета):
    print(f"  Подключение к БП ГИГ: {BP_BASE}")
    connector = win32com.client.Dispatch("V83.COMConnector")
    cs = f'File="{BP_BASE}";Usr="{BP_USER}";Pwd="{BP_PWD}";'
    conn = connector.Connect(cs)
    print(f"  OK. Конфа {conn.Метаданные.Версия}")
    try:
        пакет_объект = conn.TL_HTTPКлиентЦБ.ПрочитатьПакетИзФайла(str(путь_пакета))
        результат = conn.TL_СопуткаСервис.ОбработатьПакет(пакет_объект, True)
        print(f"  Документов создано: {результат.Документы.Количество()}")
        print(f"  Ошибок: {результат.Ошибки.Количество()}")
        if результат.Ошибки.Количество() > 0:
            for i in range(результат.Ошибки.Количество()):
                print(f"    [{i+1}] {результат.Ошибки.Получить(i)}")
        return результат
    except Exception as e:
        print(f"  [EXPECTED FAIL] {e}")
        print(f"  Причина: kind='production_release' пока не покрыт в TL_СопуткаСервис.")
        print(f"  Срез 3 заработает после: TL_СопуткаСервис.bsl:84-88 + новый ОбработатьProductionRelease()")
        return None


