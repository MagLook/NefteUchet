# -*- coding: utf-8 -*-
"""Найти имя документа инвентаризации в БП ГИГ."""
import sys, os
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()
for имя in ("ИнвентаризацияТоваров", "ИнвентаризацияТоваровНаСкладе",
            "Инвентаризация", "ИнвентаризацияНаСкладе"):
    md = conn.Метаданные.Документы.Найти(имя)
    print(f"{имя}: {'ЕСТЬ' if md is not None else 'нет'}")

# Оприходование и Списание — какое имя реквизита-ссылки на Инвентаризацию
for имя_док in ("ОприходованиеТоваров", "СписаниеТоваров"):
    md = conn.Метаданные.Документы.Найти(имя_док)
    if md is None:
        continue
    реквизиты = [md.Реквизиты.Получить(i).Имя for i in range(md.Реквизиты.Количество())]
    инв_рек = [r for r in реквизиты if "нвентаризац" in r]
    print(f"\n{имя_док} ссылка на инвентаризацию: {инв_рек}")

# Также проверим Перемещение — какие реквизиты у строки ТЧ Товары
md = conn.Метаданные.Документы.Найти("ПеремещениеТоваров")
if md is not None:
    тч = md.ТабличныеЧасти.Найти("Товары")
    реквизиты = [тч.Реквизиты.Получить(i).Имя for i in range(тч.Реквизиты.Количество())]
    print(f"\nПеремещениеТоваров.Товары реквизиты: {реквизиты}")
