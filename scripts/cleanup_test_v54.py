# -*- coding: utf-8 -*-
"""Удалить документы и записи, созданные тестом v5.4 (КлючЗагрузки = TL|...|TEST_V54)."""
import win32com.client

BASE = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"

com = win32com.client.Dispatch("V83.COMConnector")
conn = com.Connect(f'File="{BASE}";Usr="{USER}";Pwd="{PWD}";')

# 1. Удалить записи в регистре статусов с TEST_V54 в ключе (по измерению КлючЗагрузки)
try:
    Q = conn.NewObject("Запрос")
    Q.Текст = '''
    ВЫБРАТЬ КлючЗагрузки
    ИЗ РегистрСведений.TL_СтатусыЗагрузки
    ГДЕ КлючЗагрузки ПОДОБНО "%TEST_V54%"
    '''
    Sel = Q.Выполнить().Выбрать()
    keys = []
    while Sel.Следующий():
        keys.append(str(Sel.КлючЗагрузки))
    print(f"Найдено записей в регистре: {len(keys)}")
    for k in keys: print(f"  {k}")
    for k in keys:
        try:
            М = conn.РегистрыСведений.TL_СтатусыЗагрузки.СоздатьМенеджерЗаписи()
            М.КлючЗагрузки = k
            М.Прочитать()
            М.Удалить()
            print(f"  Запись регистра удалена: {k}")
        except Exception as e:
            print(f"  Ошибка удаления записи {k}: {e}")
except Exception as e:
    print(f"ОШИБКА регистр: {e}")

# 2. Найти и пометить на удаление документы по комментарию
for ИмяДок in ["ОтчетОРозничныхПродажах", "ПеремещениеТоваров", "КомплектацияНоменклатуры", "ПриходныйКассовыйОрдер"]:
    try:
        Q = conn.NewObject("Запрос")
        Q.Текст = f'''
        ВЫБРАТЬ Ссылка, Номер ИЗ Документ.{ИмяДок}
        ГДЕ Комментарий ПОДОБНО "%TEST_V54%"
        '''
        Sel = Q.Выполнить().Выбрать()
        cnt = 0
        while Sel.Следующий():
            try:
                obj = Sel.Ссылка.ПолучитьОбъект()
                # Снять проведение если проведён
                if obj.Проведен:
                    obj.Записать()  # снимет проведение, если возможно
                obj.Удалить()
                cnt += 1
            except Exception as e:
                print(f"  ОШИБКА удаления {ИмяДок} {Sel.Номер}: {e}")
        if cnt > 0:
            print(f"  Удалено {ИмяДок}: {cnt}")
    except Exception as e:
        print(f"  ОШИБКА запроса по {ИмяДок}: {e}")

print("Cleanup completed.")
