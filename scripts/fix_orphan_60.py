# -*- coding: utf-8 -*-
"""Одноразовая правка: пометить на удаление СписаниеТоваров №ГИ0Г-000060
(дубль смены 209/3867, оставшийся от прошлой ручной правки)."""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()

q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 Док.Ссылка КАК С
ИЗ Документ.СписаниеТоваров КАК Док
ГДЕ Док.Номер ПОДОБНО "%000060"
  И Док.Комментарий ПОДОБНО "%3867%"
  И НЕ Док.ПометкаУдаления
"""
в = q.Выполнить().Выбрать()
if not в.Следующий():
    print("№60 не найден или уже помечен")
    sys.exit(0)

ссылка = в.С
объ = ссылка.ПолучитьОбъект()
print(f"Найден: {объ}")
print(f"Проведён: {объ.Проведен}, ПометкаУдаления: {объ.ПометкаУдаления}")

if объ.Проведен:
    объ.Записать(conn.РежимЗаписиДокумента.ОтменаПроведения)
    объ = ссылка.ПолучитьОбъект()
    print("✓ Распроведён")

объ.УстановитьПометкуУдаления(True)
print("✓ Помечен на удаление")
