def прочитать_ттк_из_цб(uuid_номенклатур):
    """Прочитать ТТК (Технологические карты) для заданного списка номенклатур-блюд."""
    if not uuid_номенклатур:
        return []
    from _msn_secrets import connect
    цб = connect()

    # ТТК хранится как Документ.ТТК (а не Справочник) — есть в memory
    q = цб.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ ПЕРВЫЕ 100 ТТК.Ссылка, ТТК.Дата, ТТК.Номер, "
        "  ТТК.Блюдо КАК БлюдоСсылка "
        "ИЗ Документ.ТТК КАК ТТК "
        "ГДЕ НЕ ТТК.ПометкаУдаления "
        "УПОРЯДОЧИТЬ ПО ТТК.Дата УБЫВ"
    )
    try:
        v = q.Выполнить().Выбрать()
    except Exception as e:
        print(f"  [WARN] Документ.ТТК недоступен: {e}")
        return []
    ттки = []
    while v.Следующий():
        ттки.append({
            "Номер": str(v.Номер).strip(),
            "Дата": v.Дата.isoformat(),
        })
    return ттки[:5]  # отдаём первые 5 как пример


