# -*- coding: utf-8 -*-
"""Сводка по документам TradeLedger за 01-15.05.2026: типы, статусы, АЗС."""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return ""


def fmt(n):
    return f"{n:,.2f}".replace(",", " ")


ТИПЫ = [
    ("Документ.ОтчетОРозничныхПродажах",     "ОРП"),
    ("Документ.ПоступлениеТоваровУслуг",     "ПТУ"),
    ("Документ.ПеремещениеТоваров",          "Перемещ"),
    ("Документ.КомплектацияНоменклатуры",    "Компл"),
    ("Документ.СписаниеТоваров",             "Списан"),
    ("Документ.ПриходныйКассовыйОрдер",      "ПКО"),
]

print("=" * 100)
print("Документы TradeLedger в БП ГИГ за 01-15.05.2026")
print("=" * 100)

ИТОГ = {краткое: {"провед": 0, "непров": 0, "помеч": 0, "сумма_п": 0.0, "сумма_н": 0.0}
        for _, краткое in ТИПЫ}

ПО_АЗС = {}  # станция → {тип → counts}

for менеджер, краткое in ТИПЫ:
    q = conn.NewObject("Запрос")
    q.Текст = f"""
    ВЫБРАТЬ
        Док.Ссылка КАК Ссылка,
        Док.Дата КАК Дата,
        Док.Проведен КАК Пров,
        Док.ПометкаУдаления КАК Помеч,
        Док.Комментарий КАК Ком
    ИЗ {менеджер} КАК Док
    ГДЕ Док.Дата >= ДАТАВРЕМЯ(2026,5,1,0,0,0)
      И Док.Дата <= ДАТАВРЕМЯ(2026,5,15,23,59,59)
      И (ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО "TL|%"
         ИЛИ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО "% | TL|%")
    """
    в = q.Выполнить().Выбрать()
    while в.Следующий():
        ком = s(в.Ком)
        # Извлечь станцию из TL|СМЕНА|15|208|... или TL|ТТН|15|208|...
        части = ком.split("|")
        станция = части[3] if len(части) >= 4 and части[3].isdigit() else "?"

        запись = ИТОГ[краткое]
        ПО_АЗС.setdefault(станция, {}).setdefault(краткое, {"п": 0, "н": 0, "пм": 0})
        счёт = ПО_АЗС[станция][краткое]

        if в.Помеч:
            запись["помеч"] += 1
            счёт["пм"] += 1
        elif в.Пров:
            запись["провед"] += 1
            счёт["п"] += 1
        else:
            запись["непров"] += 1
            счёт["н"] += 1

# Сводка по типам
print(f"\n{'Тип':<10} {'Проведено':>10} {'Не провед.':>10} {'Помечено':>10} {'Всего':>10}")
print("-" * 60)
for краткое, dat in ИТОГ.items():
    всего = dat["провед"] + dat["непров"] + dat["помеч"]
    print(f"{краткое:<10} {dat['провед']:>10} {dat['непров']:>10} {dat['помеч']:>10} {всего:>10}")

# Разбивка по АЗС
print(f"\n{'='*100}")
print(f"Разбивка по АЗС (П=проведено, Н=не проведено, М=помечено)")
print(f"{'='*100}")
заголовок = f"{'АЗС':<6}"
for _, краткое in ТИПЫ:
    заголовок += f" {краткое:>14}"
print(заголовок)
print("-" * 100)
for станция in sorted(ПО_АЗС.keys()):
    стр = f"{станция:<6}"
    for _, краткое in ТИПЫ:
        счёт = ПО_АЗС[станция].get(краткое, {"п":0,"н":0,"пм":0})
        стр += f"   {счёт['п']:>3}/{счёт['н']:>2}/{счёт['пм']:>3}"
    print(стр)

# Сводка из TL_СтатусыЗагрузки
print(f"\n{'='*100}")
print(f"Статусы в TL_СтатусыЗагрузки за тот же период")
print(f"{'='*100}")
q2 = conn.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ ТипДокумента, Статус, КОЛИЧЕСТВО(*) КАК Кол
ИЗ РегистрСведений.TL_СтатусыЗагрузки
ГДЕ ДатаЗагрузки >= ДАТАВРЕМЯ(2026,5,1,0,0,0)
СГРУППИРОВАТЬ ПО ТипДокумента, Статус
УПОРЯДОЧИТЬ ПО ТипДокумента, Статус
"""
в2 = q2.Выполнить().Выбрать()
while в2.Следующий():
    print(f"  {s(в2.ТипДокумента):<14} {s(в2.Статус):<14} {int(в2.Кол):>6}")
