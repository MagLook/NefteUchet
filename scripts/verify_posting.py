# -*- coding: utf-8 -*-
"""Verify full posting results. Run: py -3.13-32 scripts/verify_posting.py"""
import pythoncom, io
pythoncom.CoInitialize()
import win32com.client

conn = win32com.client.Dispatch("V83.COMConnector")
ib = conn.Connect(r'File="D:\Users\magsp\GIG Base2";Usr="Гайворонская Татьяна";Pwd="12345"')

out = io.open(r"D:\Users\magsp\ELSYPLUS\NefteUchet\build\verify_posting.txt", "w", encoding="utf-8")

# 1. Find all TL documents (not deleted)
out.write("=== Документы TL ===\n\n")

for doc_type, label in [
    ("ОтчетОРозничныхПродажах", "Отчёт о розн. продажах"),
    ("ПеремещениеТоваров", "Перемещение"),
]:
    q = ib.NewObject("Query")
    q.Text = f"""ВЫБРАТЬ Ссылка, Номер, Дата, Проведен, Комментарий,
        Склад.Наименование КАК Склад
    ИЗ Документ.{doc_type}
    ГДЕ Комментарий ПОДОБНО &М И НЕ ПометкаУдаления
    УПОРЯДОЧИТЬ ПО Дата УБЫВ"""
    q.УстановитьПараметр("М", "%TL|СМЕНА%")
    r = q.Выполнить().Выбрать()
    while r.Следующий():
        out.write(f"--- {label}: {r.Номер} от {r.Дата} ---\n")
        out.write(f"  Проведён: {r.Проведен}\n")
        out.write(f"  Склад: {r.Склад}\n")
        out.write(f"  Комментарий: {r.Комментарий}\n")

        # Товарные строки
        doc = r.Ссылка.ПолучитьОбъект()
        out.write(f"  Товары ({doc.Товары.Количество()}):\n")
        for i in range(doc.Товары.Количество()):
            row = doc.Товары.Получить(i)
            out.write(f"    [{i}] {row.Номенклатура.Наименование}: кол={row.Количество}")
            try: out.write(f" цена={row.Цена} сумма={row.Сумма}")
            except: pass
            out.write("\n")

        # Проводки
        if r.Проведен:
            q2 = ib.NewObject("Query")
            q2.Text = """ВЫБРАТЬ НомерСтроки, СчетДт.Код КАК Дт, СчетКт.Код КАК Кт,
                Сумма, КоличествоДт, КоличествоКт, Содержание
            ИЗ РегистрБухгалтерии.Хозрасчетный ГДЕ Регистратор = &Д
            УПОРЯДОЧИТЬ ПО НомерСтроки"""
            q2.УстановитьПараметр("Д", r.Ссылка)
            r2 = q2.Выполнить().Выбрать()
            out.write(f"  Проводки:\n")
            while r2.Следующий():
                out.write(f"    [{r2.НомерСтроки}] Дт:{r2.Дт} Кт:{r2.Кт} Сумма:{r2.Сумма}")
                if r2.КоличествоДт: out.write(f" КолДт:{r2.КоличествоДт}")
                if r2.КоличествоКт: out.write(f" КолКт:{r2.КоличествоКт}")
                out.write(f" [{r2.Содержание}]\n")
        out.write("\n")

# 2. Перемещения на виртуальные склады
out.write("\n=== Перемещения на виртуальные склады ===\n")
q3 = ib.NewObject("Query")
q3.Text = """ВЫБРАТЬ Номер, Дата, Проведен, Комментарий,
    СкладОтправитель.Наименование КАК Откуда,
    СкладПолучатель.Наименование КАК Куда
ИЗ Документ.ПеремещениеТоваров
ГДЕ Комментарий ПОДОБНО &М И НЕ ПометкаУдаления
УПОРЯДОЧИТЬ ПО Дата УБЫВ"""
q3.УстановитьПараметр("М", "%TL|СМЕНА%")
r3 = q3.Выполнить().Выбрать()
while r3.Следующий():
    out.write(f"  {r3.Номер} {r3.Дата} [{r3.Откуда}] -> [{r3.Куда}] Проведён:{r3.Проведен}\n")
    out.write(f"    Комментарий: {r3.Комментарий}\n")

# 3. Регистр статусов
out.write("\n=== Регистр TL_СтатусыЗагрузки ===\n")
q4 = ib.NewObject("Query")
q4.Text = "ВЫБРАТЬ КлючЗагрузки, Статус ИЗ РегистрСведений.TL_СтатусыЗагрузки ГДЕ КлючЗагрузки ПОДОБНО &М УПОРЯДОЧИТЬ ПО КлючЗагрузки"
q4.УстановитьПараметр("М", "%TL|СМЕНА%")
r4 = q4.Выполнить().Выбрать()
while r4.Следующий():
    out.write(f"  {r4.КлючЗагрузки}: {r4.Статус}\n")

out.close()
print("Done")
