# -*- coding: utf-8 -*-
"""
COM-тест end-to-end для подсистемы TL_Сопутка.

Запуск:
    py -3-32 D:\\Users\\magsp\\ELSYPLUS\\NefteUchet\\scripts\\test_a3_com.py

Что делает:
1. Подключается к БП ГИГ (D:\\Users\\magsp\\GIG Base2) через V83.COMConnector.
2. Находит в БП существующие Организацию / Контрагента / Склад / Номенклатуру
   (по ИНН и наименованиям, известным по разведке).
3. Записывает в РегистрСведений.TL_СоответствиеИсточников связки
   UUID источника → объект БП. Это эмулирует ручной маппинг, который
   на реальном A3 будет делать бухгалтер через DataProcessor.TL_СоответствияИсточников.
4. Формирует синтетический JSON-пакет с одним документом kind=purchase
   и сохраняет его во временный файл.
5. Вызывает TL_HTTPКлиентЦБ.ПрочитатьПакетИзФайла → TL_СопуткаСервис.ОбработатьПакет.
6. Проверяет результат: создан ли Document.ПоступлениеТоваровУслуг,
   правильные ли счета учёта и проводки, корректен ли комментарий.

Тест не использует реальный кандидат A3 (Мегаполис ТК, 35 строк) — это требует
ручного создания 35 номенклатур в БП. Для технической проверки end-to-end
достаточно одной строки.
"""
import sys
import os
import json
import uuid
import tempfile
import datetime

# Установить UTF-8 для stdout — иначе cp1251 не справится с → ✓ ⚠
try:
    sys.stdout.reconfigure(encoding='utf-8')
except Exception:
    pass

try:
    import win32com.client
except ImportError:
    print("ERROR: pywin32 не установлен в этой версии Python")
    print("Запускайте: py -3-32 (32-битный Python)")
    sys.exit(1)

# ---------------------------------------------------------------------------
# Подключение
# ---------------------------------------------------------------------------
BASE = r'D:\Users\magsp\GIG Base2'
USER = 'Гайворонская Татьяна'
PWD = '12345'

CONNSTR = f'File="{BASE}";Usr="{USER}";Pwd="{PWD}";'

print('=' * 72)
print('COM-тест end-to-end: TL_СопуткаСервис.ОбработатьПакет')
print('=' * 72)
print(f'База:   {BASE}')
print(f'Юзер:   {USER}')
print()

print('Шаг 1. Подключение к БП через V83.COMConnector...')
try:
    connector = win32com.client.Dispatch('V83.COMConnector')
    conn = connector.Connect(CONNSTR)
    print(f'  OK. Версия конфигурации: {conn.Метаданные.Версия}')
except Exception as e:
    print(f'  FAIL: {e}')
    sys.exit(1)

# ---------------------------------------------------------------------------
# Шаг 2. Поиск НСИ в БП
# ---------------------------------------------------------------------------
print()
print('Шаг 2. Поиск существующих объектов БП ГИГ для маппинга...')


def find_one(query_text, params):
    q = conn.NewObject('Запрос')
    q.Текст = query_text
    for k, v in params.items():
        q.УстановитьПараметр(k, v)
    sel = q.Выполнить().Выбрать()
    if sel.Следующий():
        return sel.Ссылка
    return None


# Организация ГАЗИНВЕСТГРУПП по ИНН
org = find_one(
    "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Организации "
    "ГДЕ ИНН = &ИНН И НЕ ПометкаУдаления",
    {'ИНН': '7839440090'},
)
if not org:
    print('  FAIL: Организация ГАЗИНВЕСТГРУПП ООО (ИНН 7839440090) не найдена')
    sys.exit(1)
print(f'  Организация:  {org}')

# Контрагент ТК МЕГАПОЛИС по ИНН
contr = find_one(
    "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Контрагенты "
    "ГДЕ ИНН = &ИНН И НЕ ПометкаУдаления",
    {'ИНН': '5003052454'},
)
if not contr:
    print('  FAIL: Контрагент ТК МЕГАПОЛИС АО (ИНН 5003052454) не найден')
    sys.exit(1)
print(f'  Контрагент:   {contr}')

# Склад АЗС 208 (по имени)
warehouse = None
for pattern in ('АЗС 208 г.Выборг', 'АЗС 208', 'АЗС №208', 'Выборг'):
    warehouse = find_one(
        "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Склады "
        "ГДЕ Наименование ПОДОБНО &Имя И НЕ ПометкаУдаления",
        {'Имя': f'%{pattern}%'},
    )
    if warehouse:
        break
if not warehouse:
    print('  FAIL: Склад АЗС 208 не найден')
    sys.exit(1)
print(f'  Склад:        {warehouse}')

# Номенклатура — берём первую попавшуюся со СтавкаНДС=НДС20 (или НДС22)
nom = find_one(
    "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Номенклатура "
    "ГДЕ НЕ ПометкаУдаления И НЕ ЭтоГруппа "
    "  И ВидНоменклатуры.Наименование ПОДОБНО &Шаблон",
    {'Шаблон': '%Товар%'},
)
if not nom:
    # fallback — любая
    nom = find_one(
        "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Номенклатура "
        "ГДЕ НЕ ПометкаУдаления И НЕ ЭтоГруппа",
        {},
    )
if not nom:
    print('  FAIL: ни одной Номенклатуры в БП ГИГ')
    sys.exit(1)
print(f'  Номенклатура: {nom}')

# Договор — найти первый договор контрагента или None
contract = find_one(
    "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.ДоговорыКонтрагентов "
    "ГДЕ Владелец = &К И НЕ ПометкаУдаления",
    {'К': contr},
)
print(f'  Договор:      {contract or "(не найден, передадим без UUID)"}')

# ---------------------------------------------------------------------------
# Шаг 3. Запись соответствий в TL_СоответствиеИсточников
# ---------------------------------------------------------------------------
print()
print('Шаг 3. Запись соответствий UUID-источника → объекты БП...')

src_org_uuid = str(uuid.uuid4())
src_contr_uuid = str(uuid.uuid4())
src_warehouse_uuid = str(uuid.uuid4())
src_nom_uuid = str(uuid.uuid4())
src_contract_uuid = str(uuid.uuid4()) if contract else None
src_doc_uuid = str(uuid.uuid4())  # UUID самого документа purchase в источнике

ENUM = conn.Перечисления.TL_ТипОбъектаИсточника


def write_match(тип_перечисление, src_uuid, обj_ссылка):
    мз = conn.РегистрыСведений.TL_СоответствиеИсточников.СоздатьМенеджерЗаписи()
    мз.Тип = тип_перечисление
    мз.ИсточникUUID = src_uuid
    мз.СсылкаОбъект = обj_ссылка
    мз.ДатаПоследнейЗагрузки = datetime.datetime.now()
    мз.Записать()


write_match(ENUM.Организация, src_org_uuid, org)
print(f'  Организация:  {src_org_uuid[:8]}... → {org}')
write_match(ENUM.Контрагент, src_contr_uuid, contr)
print(f'  Контрагент:   {src_contr_uuid[:8]}... → {contr}')
write_match(ENUM.Склад, src_warehouse_uuid, warehouse)
print(f'  Склад:        {src_warehouse_uuid[:8]}... → {warehouse}')
write_match(ENUM.Номенклатура, src_nom_uuid, nom)
print(f'  Номенклатура: {src_nom_uuid[:8]}... → {nom}')
if contract:
    write_match(ENUM.Договор, src_contract_uuid, contract)
    print(f'  Договор:      {src_contract_uuid[:8]}... → {contract}')

# ---------------------------------------------------------------------------
# Шаг 4. Формирование JSON-пакета
# ---------------------------------------------------------------------------
print()
print('Шаг 4. Формирование тестового JSON-пакета...')

package_id = str(uuid.uuid4())
total_qty = 10
price = 100.00
total_sum = total_qty * price  # 1000.00 включая НДС
# При НДС20 включённом в сумму: НДС = total_sum * 20/120
vat_amount = round(total_sum * 20 / 120, 2)  # 166.67

doc = {
    'Тип': 'purchase',
    'ИсточникUUID': src_doc_uuid,
    'Номер': 'TEST-001',
    'Дата': '2026-04-28T10:41:50+03:00',
    'Проведен': True,
    'ПометкаУдаления': False,
    'Организация': src_org_uuid,
    'Контрагент': src_contr_uuid,
    'Склад': src_warehouse_uuid,
    'ВидОперации': 'ОтПоставщика',
    'СуммаДокумента': total_sum,
    'СуммаНДС': vat_amount,
    'ВалютаДокумента': 'RUB',
    'СуммаВключаетНДС': True,
    'НДСНеВыделять': False,
    'НДСВключенВСтоимость': False,
    'НомерВходящегоДокумента': 'УПД-TEST',
    'ДатаВходящегоДокумента': '2026-04-28',
    'Товары': [
        {
            'НомерСтроки': 1,
            'Номенклатура': src_nom_uuid,
            'Количество': total_qty,
            'Единица': 'шт',
            'Цена': price,
            'Сумма': total_sum,
            'СтавкаНДС': 'НДС20',
            'СуммаНДС': vat_amount,
        }
    ],
}
if contract:
    doc['ДоговорКонтрагента'] = src_contract_uuid

package = {
    'ВерсияФормата': '1',
    'ВремяВыгрузки': '2026-05-07T10:00:00+03:00',
    'ИдентификаторПакета': package_id,
    'Источник': 'ЭЛСИ.АЗК ЦБ (тест)',
    'Пакет': {
        'ОрганизацияЦБ': src_org_uuid,
        'Склад': src_warehouse_uuid,
        'ПериодС': '2026-04-28',
        'ПериодПо': '2026-04-28',
    },
    'НСИ': [
        {'Тип': 'Организация', 'ИсточникUUID': src_org_uuid, 'Наименование': 'ООО ГАЗИНВЕСТГРУПП', 'ИНН': '7839440090', 'ПометкаУдаления': False},
        {'Тип': 'Контрагент', 'ИсточникUUID': src_contr_uuid, 'Наименование': 'ТК МЕГАПОЛИС АО', 'ИНН': '5003052454', 'ПометкаУдаления': False},
        {'Тип': 'Склад', 'ИсточникUUID': src_warehouse_uuid, 'Наименование': 'АЗС 208 г.Выборг', 'ПометкаУдаления': False},
        {'Тип': 'Номенклатура', 'ИсточникUUID': src_nom_uuid, 'Наименование': 'Тестовая номенклатура', 'СтавкаНДС': 'НДС20', 'Единица': 'шт', 'ПометкаУдаления': False},
    ],
    'Документы': [doc],
}
if contract:
    package['НСИ'].append({
        'Тип': 'Договор',
        'ИсточникUUID': src_contract_uuid,
        'ВладелецКонтрагент': src_contr_uuid,
        'Наименование': 'Тестовый договор',
        'Номер': 'TEST',
        'Дата': '2026-01-01',
        'ВидДоговора': 'СПоставщиком',
        'ПометкаУдаления': False,
    })

# Сохранить во временный файл
tmp_path = os.path.join(tempfile.gettempdir(), f'tl_test_package_{package_id}.json')
with open(tmp_path, 'w', encoding='utf-8') as f:
    json.dump(package, f, ensure_ascii=False, indent=2)
print(f'  Файл:         {tmp_path}')
print(f'  Размер:       {os.path.getsize(tmp_path)} байт')
print(f'  ПакетID:      {package_id}')
print(f'  Сумма:        {total_sum:.2f} руб (НДС {vat_amount:.2f})')

# ---------------------------------------------------------------------------
# Шаг 5. Вызов TL_HTTPКлиентЦБ.ПрочитатьПакетИзФайла → ОбработатьПакет
# ---------------------------------------------------------------------------
print()
print('Шаг 5. Загрузка через TL_HTTPКлиентЦБ + ОбработатьПакет...')

read_result = conn.TL_HTTPКлиентЦБ.ПрочитатьПакетИзФайла(tmp_path)
if read_result.Ошибка:
    print(f'  FAIL чтения: {read_result.Ошибка}')
    sys.exit(1)
print(f'  ИсточникДанных: {read_result.ИсточникДанных}, ХешСовпал: {read_result.ХешСовпал}')

processing = conn.TL_СопуткаСервис.ОбработатьПакет(read_result.Пакет, True)

print(f'  Статус:       {processing.Статус}')
print(f'  ВсегоНСИ:     {processing.ВсегоНСИ}')
print(f'  ВсегоДокументов: {processing.ВсегоДокументов}')
print(f'  Создано документов: {processing.Документы.Количество()}')
print(f'  Ошибок:       {processing.Ошибки.Количество()}')

if processing.Ошибки.Количество() > 0:
    print('  --- Ошибки ---')
    for i in range(processing.Ошибки.Количество()):
        print(f'    [{i}] {processing.Ошибки.Получить(i)}')

# ---------------------------------------------------------------------------
# Шаг 6. Проверка результата
# ---------------------------------------------------------------------------
print()
print('Шаг 6. Проверка созданного документа в БП...')

if processing.Документы.Количество() == 0:
    print('  FAIL: документы не созданы')
    sys.exit(1)

# Перезапросим документ через НайтиПоНомеру (feedback_com_reference_cache)
# Ссылка из processing.Документы — может быть «грязной» из-за кэша Dispatch.
# Найдём по комментарию.
q = conn.NewObject('Запрос')
q.Текст = (
    "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Документ.ПоступлениеТоваровУслуг "
    "ГДЕ ВЫРАЗИТЬ(Комментарий КАК СТРОКА(200)) ПОДОБНО &Шаблон"
)
q.УстановитьПараметр('Шаблон', f'TL|ЦБ|{package_id}|%')
sel = q.Выполнить().Выбрать()
if not sel.Следующий():
    print('  FAIL: документ не найден по комментарию TL|ЦБ|...')
    sys.exit(1)

doc_ref = sel.Ссылка
print(f'  Найден:       {doc_ref}')

# Перезапросим реквизиты
obj = doc_ref.ПолучитьОбъект()
print(f'  Дата:         {obj.Дата}')
print(f'  Организация:  {obj.Организация}')
print(f'  Контрагент:   {obj.Контрагент}')
print(f'  Склад:        {obj.Склад}')
print(f'  ВидОперации:  {obj.ВидОперации}')
print(f'  СуммаДок:     {obj.СуммаДокумента}')
print(f'  Проведен:     {obj.Проведен}')
print(f'  Комментарий:  {obj.Комментарий}')
print(f'  Строк Товаров: {obj.Товары.Количество()}')

# Проверка строк
ok = True
for i in range(obj.Товары.Количество()):
    row = obj.Товары.Получить(i)
    print(f'    [{i+1}] Ном={row.Номенклатура} Кол={row.Количество} '
          f'Цена={row.Цена} Сумма={row.Сумма} СтавкаНДС={row.СтавкаНДС}')
    try:
        счёт_кода = row.СчетУчета.Код
        print(f'        СчетУчета={счёт_кода}, СчетУчетаНДС={row.СчетУчетаНДС.Code if hasattr(row.СчетУчетаНДС,"Code") else row.СчетУчетаНДС.Код}')
        if счёт_кода != '41.02':
            print(f'        WARN: ожидался 41.02')
            ok = False
    except Exception as e:
        print(f'        WARN: не удалось прочитать счёт: {e}')

# Проводки — через регистр Хозрасчётный
print()
print('Шаг 7. Проводки в Регистре бухгалтерии Хозрасчетный...')
q2 = conn.NewObject('Запрос')
q2.Текст = (
    "ВЫБРАТЬ Период, СчетДт.Код КАК ДтКод, СчетКт.Код КАК КтКод, Сумма "
    "ИЗ РегистрБухгалтерии.Хозрасчетный "
    "ГДЕ Регистратор = &Рег "
    "УПОРЯДОЧИТЬ ПО Период"
)
q2.УстановитьПараметр('Рег', doc_ref)
sel2 = q2.Выполнить().Выбрать()
n = 0
while sel2.Следующий():
    n += 1
    print(f'  [{n}] Дт {sel2.ДтКод} Кт {sel2.КтКод} = {sel2.Сумма}')

if n == 0:
    print('  WARN: проводок нет (документ не проведён или схема счетов не отрабатывает)')

# Запись соответствия
print()
print('Шаг 8. Проверка TL_СоответствиеИсточников по созданному документу...')
q3 = conn.NewObject('Запрос')
q3.Текст = (
    "ВЫБРАТЬ СсылкаОбъект, ДатаПоследнейЗагрузки, ИдентификаторПоследнегоПакета "
    "ИЗ РегистрСведений.TL_СоответствиеИсточников "
    "ГДЕ Тип = &Т И ИсточникUUID = &UUID"
)
q3.УстановитьПараметр('Т', conn.Перечисления.TL_ТипОбъектаИсточника.Поступление)
q3.УстановитьПараметр('UUID', src_doc_uuid)
sel3 = q3.Выполнить().Выбрать()
if sel3.Следующий():
    print(f'  Связка:     {sel3.СсылкаОбъект}')
    print(f'  Дата:       {sel3.ДатаПоследнейЗагрузки}')
    print(f'  ПакетID:    {sel3.ИдентификаторПоследнегоПакета}')
else:
    print('  FAIL: соответствие не записано')
    ok = False

print()
print('=' * 72)
if ok and processing.Ошибки.Количество() == 0 and n > 0:
    print('РЕЗУЛЬТАТ: ✓ end-to-end OK (документ создан, проводки сформированы)')
else:
    print('РЕЗУЛЬТАТ: ⚠ есть отклонения — см. WARN/FAIL выше')
print('=' * 72)

# Очистить временный файл
try:
    os.remove(tmp_path)
except Exception:
    pass
