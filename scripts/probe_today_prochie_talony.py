# -*- coding: utf-8 -*-
"""Probe на стенде GIG Base2: проведены ли сегодня (22.05.2026) документы по
каналам Прочие (writeoff_fuel → СписаниеТоваров) и Талоны (voucher → перемещение
на склад «Талоны»).
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def fmt(num):
    return f"{num:,.2f}".replace(",", " ")


def fmt_date(d):
    try:
        return d.strftime("%d.%m %H:%M")
    except Exception:
        return str(d)


print("=" * 90)
print("Probe Прочие + Талоны на стенде GIG Base2 за 22.05.2026")
print("=" * 90)

# ───────────────────────────────────────────────────────────────────────
# 1. ПРОЧИЕ — Документ.СписаниеТоваров с Комментарий начинающимся 'TL|СПИСАНИЕ|'
# ───────────────────────────────────────────────────────────────────────
print("\n[1] СПИСАНИЕ ТОПЛИВА ПО КАНАЛУ writeoff_fuel (Прочие)")
print("-" * 90)

q1 = conn.NewObject("Запрос")
q1.Текст = """
ВЫБРАТЬ
    Док.Ссылка       КАК Ссылка,
    Док.Номер        КАК Номер,
    Док.Дата         КАК Дата,
    Док.Проведен     КАК Проведен,
    Док.Организация  КАК Организация,
    Док.Склад        КАК Склад,
    Док.ВидОперации  КАК ВидОперации,
    Док.Комментарий  КАК Комментарий
ИЗ Документ.СписаниеТоваров КАК Док
ГДЕ Док.Дата >= ДАТАВРЕМЯ(2026,5,22,0,0,0)
  И Док.Дата <= ДАТАВРЕМЯ(2026,5,22,23,59,59)
  И Док.Комментарий ПОДОБНО "TL|СПИСАНИЕ|%"
УПОРЯДОЧИТЬ ПО Док.Дата
"""
вып1 = q1.Выполнить().Выбрать()
списания = []
while вып1.Следующий():
    списания.append({
        "ссылка": вып1.Ссылка,
        "ном": str(вып1.Номер).strip(),
        "дата": fmt_date(вып1.Дата),
        "пров": bool(вып1.Проведен),
        "орг": str(вып1.Организация or "—"),
        "скл": str(вып1.Склад or "—"),
        "вид": str(вып1.ВидОперации or "—"),
        "ком": str(вып1.Комментарий or ""),
    })

if not списания:
    print("  Сегодня СписаниеТоваров с маркером TL|СПИСАНИЕ| не найдено.")
else:
    print(f"  Найдено: {len(списания)} документ(ов)\n")
    for с in списания:
        зн = "✓ проведён" if с["пров"] else "○ НЕ проведён"
        print(f"  {зн}  №{с['ном']}  {с['дата']}")
        print(f"     Организация: {с['орг']}")
        print(f"     Склад:       {с['скл']}")
        print(f"     ВидОперации: {с['вид']}")
        print(f"     Комментарий: {с['ком']}")

        # ТЧ Товары
        q1_тч = conn.NewObject("Запрос")
        q1_тч.УстановитьПараметр("Док", с["ссылка"])
        q1_тч.Текст = """
        ВЫБРАТЬ
            ТЧ.Номенклатура  КАК Номенклатура,
            ТЧ.Количество    КАК Количество,
            ТЧ.Сумма         КАК Сумма,
            ТЧ.СчетУчета     КАК Счёт
        ИЗ Документ.СписаниеТоваров.Товары КАК ТЧ
        ГДЕ ТЧ.Ссылка = &Док
        """
        твв = q1_тч.Выполнить().Выбрать()
        стр_тч = []
        while твв.Следующий():
            стр_тч.append((str(твв.Номенклатура), float(твв.Количество or 0),
                           float(твв.Сумма or 0), str(твв.Счёт or "—")))
        if стр_тч:
            print(f"     ТЧ Товары ({len(стр_тч)} стр):")
            for ном, кол, сум, сч in стр_тч:
                print(f"        {ном:<40}  {кол:>10.2f}  {fmt(сум):>12} ₽   счёт={сч}")

        # Проводки (РегистрБухгалтерии.Хозрасчетный)
        q1_пр = conn.NewObject("Запрос")
        q1_пр.УстановитьПараметр("Док", с["ссылка"])
        q1_пр.Текст = """
        ВЫБРАТЬ
            Прв.СчетДт   КАК Дт,
            Прв.СчетКт   КАК Кт,
            Прв.Сумма    КАК Сумма,
            Прв.Содержание КАК Сод
        ИЗ РегистрБухгалтерии.Хозрасчетный КАК Прв
        ГДЕ Прв.Регистратор = &Док
        """
        пвв = q1_пр.Выполнить().Выбрать()
        пров = []
        while пвв.Следующий():
            пров.append((str(пвв.Дт), str(пвв.Кт), float(пвв.Сумма or 0), str(пвв.Сод or "")))
        if пров:
            print(f"     Проводки ({len(пров)}):")
            for дт, кт, сум, сод in пров:
                print(f"        Дт {дт:<10} Кт {кт:<10} {fmt(сум):>12} ₽   {сод[:50]}")
        elif с["пров"]:
            print(f"     ⚠ Проведён, но проводок нет (учётная политика стенда?)")
        print()

# ───────────────────────────────────────────────────────────────────────
# 2. ТАЛОНЫ — Документ.ПеремещениеТоваров со складом-получателем «Талоны»
# ───────────────────────────────────────────────────────────────────────
print("\n[2] ПЕРЕМЕЩЕНИЯ НА СКЛАД «ТАЛОНЫ»")
print("-" * 90)

q2 = conn.NewObject("Запрос")
q2.Текст = """
ВЫБРАТЬ
    Док.Ссылка          КАК Ссылка,
    Док.Номер           КАК Номер,
    Док.Дата            КАК Дата,
    Док.Проведен        КАК Проведен,
    Док.Организация     КАК Организация,
    Док.СкладОтправитель КАК СкладОтпр,
    Док.СкладПолучатель  КАК СкладПол,
    Док.Комментарий     КАК Комментарий
ИЗ Документ.ПеремещениеТоваров КАК Док
ГДЕ Док.Дата >= ДАТАВРЕМЯ(2026,5,22,0,0,0)
  И Док.Дата <= ДАТАВРЕМЯ(2026,5,22,23,59,59)
  И (Док.СкладПолучатель.Наименование ПОДОБНО "%алон%"
     ИЛИ Док.Комментарий ПОДОБНО "TL|%ВОУЧЕР%"
     ИЛИ Док.Комментарий ПОДОБНО "TL|%VOUCHER%"
     ИЛИ Док.Комментарий ПОДОБНО "TL|ТАЛОН%"
     ИЛИ Док.Комментарий ПОДОБНО "TL|voucher%")
УПОРЯДОЧИТЬ ПО Док.Дата
"""
вып2 = q2.Выполнить().Выбрать()
переме = []
while вып2.Следующий():
    переме.append({
        "ссылка": вып2.Ссылка,
        "ном": str(вып2.Номер).strip(),
        "дата": fmt_date(вып2.Дата),
        "пров": bool(вып2.Проведен),
        "орг": str(вып2.Организация or "—"),
        "отпр": str(вып2.СкладОтпр or "—"),
        "пол": str(вып2.СкладПол or "—"),
        "ком": str(вып2.Комментарий or ""),
    })

if not переме:
    print("  Сегодня ПеремещениеТоваров на склад «Талоны» не найдено.")
    # Подсказка — проверить вообще все перемещения за сегодня
    q2x = conn.NewObject("Запрос")
    q2x.Текст = """
    ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Всего
    ИЗ Документ.ПеремещениеТоваров КАК Док
    ГДЕ Док.Дата >= ДАТАВРЕМЯ(2026,5,22,0,0,0)
      И Док.Дата <= ДАТАВРЕМЯ(2026,5,22,23,59,59)
    """
    вы2x = q2x.Выполнить().Выбрать()
    вы2x.Следующий()
    print(f"  Всего перемещений за сегодня: {int(вы2x.Всего)} (но без слова 'талон' в складе/комментарии)")
else:
    print(f"  Найдено: {len(переме)} перемещение(й)\n")
    for п in переме:
        зн = "✓ проведён" if п["пров"] else "○ НЕ проведён"
        print(f"  {зн}  №{п['ном']}  {п['дата']}")
        print(f"     Организация:      {п['орг']}")
        print(f"     Склад-отправитель: {п['отпр']}")
        print(f"     Склад-получатель:  {п['пол']}")
        print(f"     Комментарий:      {п['ком']}")

        # ТЧ Товары
        q2_тч = conn.NewObject("Запрос")
        q2_тч.УстановитьПараметр("Док", п["ссылка"])
        q2_тч.Текст = """
        ВЫБРАТЬ
            ТЧ.Номенклатура КАК Номенклатура,
            ТЧ.Количество   КАК Количество,
            ТЧ.СчетУчета    КАК СчётОтпр,
            ТЧ.СчетУчетаПолучателя КАК СчётПолуч
        ИЗ Документ.ПеремещениеТоваров.Товары КАК ТЧ
        ГДЕ ТЧ.Ссылка = &Док
        """
        твв = q2_тч.Выполнить().Выбрать()
        стр_тч = []
        итого_кол = 0
        while твв.Следующий():
            кол = float(твв.Количество or 0)
            стр_тч.append((str(твв.Номенклатура), кол, str(твв.СчётОтпр or "—"), str(твв.СчётПолуч or "—")))
            итого_кол += кол
        if стр_тч:
            print(f"     ТЧ Товары ({len(стр_тч)} стр, Σколичество={итого_кол:.2f}):")
            for ном, кол, со, сп in стр_тч[:10]:
                print(f"        {ном:<40}  {кол:>10.2f}  отпр={со}  пол={сп}")
            if len(стр_тч) > 10:
                print(f"        ... ещё {len(стр_тч)-10} стр")

        # Регистр накопления ТоварыНаСкладах — что в БД из этого документа
        q2_рег = conn.NewObject("Запрос")
        q2_рег.УстановитьПараметр("Док", п["ссылка"])
        q2_рег.Текст = """
        ВЫБРАТЬ
            Рег.ВидДвижения  КАК ВидДвижения,
            Рег.Склад        КАК Склад,
            СУММА(Рег.Количество) КАК Σ
        ИЗ РегистрНакопления.ТоварыНаСкладах КАК Рег
        ГДЕ Рег.Регистратор = &Док
        СГРУППИРОВАТЬ ПО Рег.ВидДвижения, Рег.Склад
        """
        рвв = q2_рег.Выполнить().Выбрать()
        двжн = []
        while рвв.Следующий():
            двжн.append((str(рвв.ВидДвижения), str(рвв.Склад), float(рвв.Σ or 0)))
        if двжн:
            print(f"     Движения регистра ТоварыНаСкладах:")
            for вд, скл, кол in двжн:
                print(f"        {вд:<10} склад={скл:<35} Σ={кол:.2f}")
        elif п["пров"]:
            print(f"     ⚠ Проведён, но движений регистра нет")
        print()

print("=" * 90)
print("Готово")
print("=" * 90)
