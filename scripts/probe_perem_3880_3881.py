# -*- coding: utf-8 -*-
"""Найти ВСЕ Перемещения и ПКО для смен 209/3880 и 209/3881
(включая те что датированы 20.05/21.05).
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return "—"
    try: return str(v)
    except Exception: return repr(v)


def fmt(n):
    return f"{n:,.2f}".replace(",", " ")


def fmt_date(d):
    try: return d.strftime("%d.%m %H:%M")
    except Exception: return str(d)


print("=" * 100)
print("Документы для смен 209/3880 и 209/3881 (поиск по Комментарию)")
print("=" * 100)

ТИПЫ = [
    ("Документ.ПеремещениеТоваров",     "Перемещение"),
    ("Документ.ПриходныйКассовыйОрдер", "ПКО"),
    ("Документ.СписаниеТоваров",        "СписаниеТов"),
]

for менеджер, краткое in ТИПЫ:
    q = conn.NewObject("Запрос")
    q.Текст = f"""
    ВЫБРАТЬ
        Док.Ссылка        КАК Ссылка,
        Док.Номер         КАК Ном,
        Док.Дата          КАК Дата,
        Док.Проведен      КАК Пров,
        Док.Комментарий   КАК Ком
    ИЗ {менеджер} КАК Док
    ГДЕ (Док.Комментарий ПОДОБНО "%3880%" ИЛИ Док.Комментарий ПОДОБНО "%3881%")
      И Док.Дата >= ДАТАВРЕМЯ(2026,5,15,0,0,0)
    УПОРЯДОЧИТЬ ПО Док.Дата
    """
    в = q.Выполнить().Выбрать()
    строки = []
    while в.Следующий():
        строки.append({
            "ссылка": в.Ссылка,
            "ном": s(в.Ном).strip(),
            "дата": fmt_date(в.Дата),
            "пров": bool(в.Пров),
            "ком": s(в.Ком),
        })
    print(f"\n[{краткое}] найдено {len(строки)}")
    print("-" * 100)
    for ст in строки:
        зн = "✓" if ст["пров"] else "○"
        print(f"  {зн} №{ст['ном']:<14} {ст['дата']:<14}  {ст['ком']}")

        if краткое == "Перемещение":
            # СкладОтпр, СкладПолуч, ТЧ Товары
            q1 = conn.NewObject("Запрос")
            q1.УстановитьПараметр("Док", ст["ссылка"])
            q1.Текст = """
            ВЫБРАТЬ
                Док.СкладОтправитель.Наименование КАК Отпр,
                Док.СкладПолучатель.Наименование  КАК Полу
            ИЗ Документ.ПеремещениеТоваров КАК Док
            ГДЕ Док.Ссылка = &Док
            """
            в1 = q1.Выполнить().Выбрать()
            в1.Следующий()
            print(f"      Отпр: {s(в1.Отпр)}  →  Полу: {s(в1.Полу)}")

            q2 = conn.NewObject("Запрос")
            q2.УстановитьПараметр("Док", ст["ссылка"])
            q2.Текст = """
            ВЫБРАТЬ
                ТЧ.Номенклатура.Наименование КАК Ном,
                ТЧ.Количество КАК Кол,
                ТЧ.СчетУчета.Код КАК СчётО
            ИЗ Документ.ПеремещениеТоваров.Товары КАК ТЧ
            ГДЕ ТЧ.Ссылка = &Док
            """
            в2 = q2.Выполнить().Выбрать()
            σ_л = 0
            тч_строк = 0
            while в2.Следующий():
                тч_строк += 1
                кол = float(в2.Кол or 0)
                σ_л += кол
                print(f"      • {s(в2.Ном):<35}  {кол:>8.2f} л   счёт {s(в2.СчётО)}")
            if тч_строк > 0:
                print(f"      ⤴ Итого литров: {σ_л:.2f}")

        if краткое == "ПКО":
            q1 = conn.NewObject("Запрос")
            q1.УстановитьПараметр("Док", ст["ссылка"])
            q1.Текст = """
            ВЫБРАТЬ
                Док.ВидОперации   КАК ВО,
                Док.СуммаДокумента КАК Сумма,
                Док.СчетУчета.Код  КАК СчётКассы
            ИЗ Документ.ПриходныйКассовыйОрдер КАК Док
            ГДЕ Док.Ссылка = &Док
            """
            в1 = q1.Выполнить().Выбрать()
            в1.Следующий()
            print(f"      ВидОп={s(в1.ВО)}  Сумма={fmt(float(в1.Сумма or 0))} ₽  СчётКассы={s(в1.СчётКассы)}")

print("\n" + "=" * 100)
print("Готово")
