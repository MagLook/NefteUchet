# -*- coding: utf-8 -*-
"""
Реальный тест: вызов ПолучитьИлиСоздатьСкладАЗС для каждой АЗС из API
с обновлёнными строгими масками.
"""
import win32com.client

BASE = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"
OUT = open(r"D:\Users\magsp\ELSYPLUS\NefteUchet\scripts\_out_warehouses_real.txt", "w", encoding="utf-8")
def p(*a): print(*a, file=OUT)

def s(v):
    if v is None: return ""
    sv = str(v)
    if "<COMObject" in sv or "unknown" in sv:
        for attr in ("Наименование", "Имя", "Код", "Представление"):
            try:
                a = getattr(v, attr)
                if a is None: continue
                a_s = str(a)
                if a_s and "<COMObject" not in a_s: return a_s
            except Exception: continue
        return ""
    return sv

com = win32com.client.Dispatch("V83.COMConnector")
conn = com.Connect(f'File="{BASE}";Usr="{USER}";Pwd="{PWD}";')

# Список складов до теста
def list_wh(label):
    p(f"\n=== {label} ===")
    Q = conn.NewObject("Запрос")
    Q.Текст = '''ВЫБРАТЬ Ссылка ИЗ Справочник.Склады
    ГДЕ НЕ ПометкаУдаления И (Наименование ПОДОБНО "%АЗС%" ИЛИ Наименование ПОДОБНО "%АКЗС%" ИЛИ Наименование ПОДОБНО "%АГЗС%")
    УПОРЯДОЧИТЬ ПО Наименование'''
    Sel = Q.Выполнить().Выбрать()
    n = 0
    while Sel.Следующий():
        n += 1
        p(f"  {n:>2}. {s(Sel.Ссылка)}")
    p(f"  Всего: {n}")
    return n

n_до = list_wh("Склады до теста")

# Удалим возможные тестовые мусорные привязки и склады которые мы могли создать
p("\n=== Откат предыдущих тестовых привязок ===")
for код in [1, 2, 3, 4, 6, 207, 208, 209, 210, 8, 205]:
    КодСтр = str(код)
    # Удаляем ключи привязки
    for ключ in [f"Станция_{КодСтр}_Склад", f"Станция_{КодСтр}_СкладGUID"]:
        try:
            М = conn.РегистрыСведений.TL_Настройки.СоздатьМенеджерЗаписи()
            М.Ключ = ключ
            М.Прочитать()
            if str(М.Значение):
                М.Удалить()
                p(f"  Удалён ключ: {ключ}")
        except Exception:
            pass

URL = conn.TL_Настройки.ПолучитьЗначение("URLСервера", "")
LG = conn.TL_Настройки.ПолучитьЗначение("Логин", "")
PW = conn.TL_Настройки.ПолучитьЗначение("Пароль", "")
Рез = conn.TL_Настройки.ОпроситьВсеСетиИзAPI(URL, LG, PW)
p(f"\nИз API: {Рез.Станции.Количество()} станций")

p("\n=== Реальный вызов ПолучитьИлиСоздатьСкладАЗС ===")
p(f"  {'Имя из API':<25} {'Код':>4}  → результат")
для_очистки = []
for i in range(Рез.Станции.Количество()):
    ОС = Рез.Станции[i]
    Имя = str(ОС.Наименование)
    Код = int(ОС.Код)
    Сеть = int(ОС.КодСистемы)
    if Сеть != 15: continue  # тест только для сети 15

    # Запомним список складов до — чтобы понять создан ли новый
    n_перед = conn.Справочники.Склады.Выбрать()
    cnt_перед = 0
    while n_перед.Следующий(): cnt_перед += 1

    Скл = conn.TL_Настройки.ПолучитьИлиСоздатьСкладАЗС(Имя, Код)

    n_после = conn.Справочники.Склады.Выбрать()
    cnt_после = 0
    while n_после.Следующий(): cnt_после += 1
    создан = cnt_после > cnt_перед

    статус = "СОЗДАН" if создан else "найден"
    p(f"  {Имя:<25} {Код:>4}  → {статус}: {s(Скл)}")
    if создан:
        для_очистки.append(Скл)

n_после = list_wh("Склады после теста")
p(f"\nИзменение: было {n_до} → стало {n_после}, создано {len(для_очистки)}")

# Откат: удалим автосозданные склады, чтобы база осталась чистой
if для_очистки:
    p("\n=== Откат: удаление созданных тестом складов ===")
    for ссыл in для_очистки:
        try:
            obj = ссыл.ПолучитьОбъект()
            obj.Удалить()
            p(f"  Удалён: {s(ссыл)}")
        except Exception as e:
            p(f"  Ошибка удаления {s(ссыл)}: {e}")

OUT.close()
print(f"OK: scripts/_out_warehouses_real.txt")
