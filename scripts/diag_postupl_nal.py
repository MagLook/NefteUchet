# -*- coding: utf-8 -*-
"""
Анализ Документ.ПоступлениеНаличных (ПКО КО-1) в БП ГИГ.
Запуск: py -3-32 scripts/diag_postupl_nal.py
"""
import sys, datetime
import win32com.client

BASE_PATH = r"D:\Users\magsp\GIG Base2"
USER = "Гайворонская Татьяна"
PWD = "12345"

def hr(t=""):
    print()
    print("=" * 78)
    if t: print(t)
    print("=" * 78)

def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return repr(v)

def acc(c):
    try: return str(c.Код)
    except Exception:
        return s(c)

def main():
    com = win32com.client.Dispatch("V83.COMConnector")
    conn = com.Connect(f'File="{BASE_PATH}";Usr="{USER}";Pwd="{PWD}";')

    hr("0) Метаданные Документ.ПоступлениеНаличных")
    md = conn.Метаданные.НайтиПоПолномуИмени("Документ.ПоступлениеНаличных")
    if md is None:
        print("  НЕ НАЙДЕНО — пробую другие имена...")
        for cand in ["Документ.ПКО", "Документ.КассовыйОрдер", "Документ.ПриходНаличных", "Документ.ПриходныйКассовыйОрдер"]:
            md = conn.Метаданные.НайтиПоПолномуИмени(cand)
            if md is not None:
                print(f"  Найдено: {cand}")
                break
    if md is None:
        # Перебор всех документов
        print("  Список всех документов с 'нал' / 'касс' / 'опл':")
        for d in conn.Метаданные.Документы:
            if any(k in d.Имя.lower() for k in ["нал", "касс", "опл", "приход"]):
                print(f"    {d.Имя:35} — {d.Синоним}")
        return

    print(f"  Имя: {md.Имя}")
    print(f"  Синоним: {md.Синоним}")
    print(f"  Реквизиты:")
    for rq in md.Реквизиты:
        ttype = ""
        try: ttype = str(rq.Тип)
        except Exception: pass
        print(f"    {rq.Имя:35} тип={ttype[:80]}")

    hr("1) Поиск ГИ0Г-000419 / последние документы ПоступлениеНаличных")
    q = conn.NewObject("Запрос")
    q.Текст = '''
    ВЫБРАТЬ ПЕРВЫЕ 30
        Ссылка, Номер, Дата, ВидОперации, СуммаДокумента, Организация, Проведен, Комментарий
    ИЗ Документ.ПоступлениеНаличных
    УПОРЯДОЧИТЬ ПО Дата УБЫВ
    '''
    sel = q.Выполнить().Выбрать()
    docs = []
    while sel.Следующий():
        docs.append(sel.Ссылка)
        n = s(sel.Номер); d = sel.Дата; sm = sel.СуммаДокумента
        v = s(sel.ВидОперации); p = sel.Проведен
        marker = " ← С ЭКРАНА" if "419" in n else ""
        print(f"  {n:>15}  {d}  Σ={sm:>10.2f}  вид={v[:25]:25}  пров={p}{marker}")

    if not docs:
        print("  Нет документов ПоступлениеНаличных")
        return

    # Найти именно ГИ0Г-000419 если есть, иначе свежий проведённый
    target = None
    for d in docs:
        if "419" in s(d.Номер):
            target = d; break
    if target is None:
        for d in docs:
            obj = d.ПолучитьОбъект()
            if obj.Проведен and "Розничная" in s(obj.ВидОперации):
                target = d; break
    if target is None and docs:
        target = docs[0]

    obj = target.ПолучитьОбъект()
    hr(f"2) Документ {s(obj.Номер)} от {obj.Дата} — все реквизиты")
    for rq in md.Реквизиты:
        try:
            v = getattr(obj, rq.Имя)
            print(f"    {rq.Имя:35} = {s(v)[:90]}")
        except Exception as e:
            print(f"    {rq.Имя:35} ОШИБКА {e}")

    print(f"\n  ТабличныеЧасти:")
    for tch in md.ТабличныеЧасти:
        try:
            tab = getattr(obj, tch.Имя)
            print(f"    ТЧ {tch.Имя}: {tab.Количество()} строк")
        except Exception:
            pass

    hr("3) Проводки документа (РегистрБухгалтерии.Хозрасчётный)")
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Регистратор", target)
    q.Текст = '''
    ВЫБРАТЬ Период, СчетДт, СчетКт, Сумма, Содержание,
            СубконтоДт1, СубконтоДт2, СубконтоДт3,
            СубконтоКт1, СубконтоКт2, СубконтоКт3
    ИЗ РегистрБухгалтерии.Хозрасчетный
    ГДЕ Регистратор = &Регистратор
    УПОРЯДОЧИТЬ ПО НомерСтроки
    '''
    sel = q.Выполнить().Выбрать()
    n = 0
    while sel.Следующий():
        n += 1
        print(f"  Дт {acc(sel.СчетДт):>8}  Кт {acc(sel.СчетКт):>8}  = {sel.Сумма:>12.2f}  | {s(sel.Содержание)[:55]}")
        sd = [s(sel.СубконтоДт1), s(sel.СубконтоДт2), s(sel.СубконтоДт3)]
        sk = [s(sel.СубконтоКт1), s(sel.СубконтоКт2), s(sel.СубконтоКт3)]
        sd = [x for x in sd if x]; sk = [x for x in sk if x]
        if sd: print(f"      СубкДт: {' / '.join(sd)[:80]}")
        if sk: print(f"      СубкКт: {' / '.join(sk)[:80]}")
    print(f"  Всего проводок: {n}")
    if n == 0:
        print(f"  ⚠ ПРОВОДОК НЕТ — документ не делает движений!")

    hr("4) Связь с ОРП за тот же день / тот же склад")
    склад = None
    try:
        склад = obj.Склад
    except Exception:
        pass
    дата = obj.Дата
    print(f"  Дата документа: {дата}, Склад: {s(склад)}")

    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Дата", дата)
    q.УстановитьПараметр("Склад", склад)
    q.УстановитьПараметр("Орг", obj.Организация)
    q.Текст = '''
    ВЫБРАТЬ
        Ссылка, Номер, Дата, СуммаДокумента, Проведен, Комментарий
    ИЗ Документ.ОтчетОРозничныхПродажах
    ГДЕ НАЧАЛОПЕРИОДА(Дата, ДЕНЬ) = НАЧАЛОПЕРИОДА(&Дата, ДЕНЬ)
        И Склад = &Склад
        И Организация = &Орг
    УПОРЯДОЧИТЬ ПО Дата
    '''
    sel = q.Выполнить().Выбрать()
    orps = []
    while sel.Следующий():
        orps.append(sel.Ссылка)
        print(f"  ОРП {s(sel.Номер):>15}  Σ={sel.СуммаДокумента:>10.2f}  пров={sel.Проведен}  ком={s(sel.Комментарий)[:50]}")
    print(f"  ОРП за день/склад/орг: {len(orps)}")

    if orps:
        hr("5) Сопоставление сумм: ОРП наличные vs ПоступлениеНаличных")
        # Возьмём проведённый ОРП и посмотрим разбивку оплаты
        for orp_ref in orps:
            orp_obj = orp_ref.ПолучитьОбъект()
            if not orp_obj.Проведен: continue
            print(f"\n  Анализ ОРП {s(orp_obj.Номер)}:")
            print(f"    СуммаДокумента: {orp_obj.СуммаДокумента}")
            # Поиск ТЧ с оплатами — могут быть разные имена
            for tch_name in ["БезналичныеОплаты", "ОплатаПлатежнымиКартами", "Оплаты", "Оплата", "Платежи", "ВыручкаПоВидамОплат"]:
                try:
                    tab = getattr(orp_obj, tch_name)
                    cnt = tab.Количество()
                    if cnt > 0:
                        print(f"    ТЧ {tch_name}: {cnt} строк")
                        total = 0
                        for i in range(cnt):
                            row = tab.Получить(i)
                            try:
                                vop = s(row.ВидОплаты) if hasattr(row, "ВидОплаты") else "?"
                            except Exception: vop = "?"
                            try:
                                sm = row.Сумма
                            except Exception: sm = 0
                            total += sm or 0
                            print(f"      ВидОплаты={vop[:35]:35}  Σ={sm or 0:>10.2f}")
                        print(f"    ИТОГО безнал по ТЧ {tch_name}: {total:>10.2f}")
                except Exception:
                    pass

            # Проверим проводки ОРП — есть ли там 50.01
            q = conn.NewObject("Запрос")
            q.УстановитьПараметр("Регистратор", orp_ref)
            q.Текст = '''
            ВЫБРАТЬ Сумма, СчетДт, СчетКт, Содержание
            ИЗ РегистрБухгалтерии.Хозрасчетный
            ГДЕ Регистратор = &Регистратор
                И (СчетДт В ИЕРАРХИИ (ПланСчетов.Хозрасчетный.НайтиПоКоду("50"))
                    ИЛИ СчетКт В ИЕРАРХИИ (ПланСчетов.Хозрасчетный.НайтиПоКоду("50")))
            '''
            try:
                sel2 = q.Выполнить().Выбрать()
                print(f"    Проводки ОРП по сч.50:")
                k = 0
                while sel2.Следующий():
                    k += 1
                    print(f"      Дт {acc(sel2.СчетДт):>6} Кт {acc(sel2.СчетКт):>6}  Σ={sel2.Сумма:>10.2f}  | {s(sel2.Содержание)[:50]}")
                if k == 0:
                    print(f"      (НЕТ проводок по 50 → ОРП не делает кассовых проводок)")
            except Exception as e:
                # Альтернативный синтаксис
                q = conn.NewObject("Запрос")
                q.УстановитьПараметр("Регистратор", orp_ref)
                q.Текст = '''
                ВЫБРАТЬ Сумма, СчетДт.Код КАК ДтКод, СчетКт.Код КАК КтКод, Содержание
                ИЗ РегистрБухгалтерии.Хозрасчетный
                ГДЕ Регистратор = &Регистратор
                '''
                sel2 = q.Выполнить().Выбрать()
                print(f"    Все проводки ОРП:")
                k = 0
                while sel2.Следующий():
                    k += 1
                    if "50" in (sel2.ДтКод or "") or "50" in (sel2.КтКод or ""):
                        print(f"      ★ Дт {sel2.ДтКод:>6} Кт {sel2.КтКод:>6}  Σ={sel2.Сумма:>10.2f}  | {s(sel2.Содержание)[:50]}")
                    else:
                        print(f"        Дт {sel2.ДтКод:>6} Кт {sel2.КтКод:>6}  Σ={sel2.Сумма:>10.2f}")

    hr("6) Свод за 30 дней: ПоступлениеНаличных по ВидамОперации")
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Стоп", datetime.datetime.now())
    q.Текст = '''
    ВЫБРАТЬ
        ВидОперации, КОЛИЧЕСТВО(*) КАК Кол, СУММА(СуммаДокумента) КАК Сумма
    ИЗ Документ.ПоступлениеНаличных
    ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30)
    СГРУППИРОВАТЬ ПО ВидОперации
    '''
    sel = q.Выполнить().Выбрать()
    while sel.Следующий():
        print(f"    {s(sel.ВидОперации):40} кол={sel.Кол:>4}  Σ={sel.Сумма or 0:>14.2f}")

    hr("7) Сравним: ОРП за 30 дней vs ПоступлениеНаличных за 30 дней — есть ли соответствие 1-к-1?")
    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Стоп", datetime.datetime.now())
    q.Текст = '''
    ВЫБРАТЬ
        НАЧАЛОПЕРИОДА(Дата, ДЕНЬ) КАК День,
        КОЛИЧЕСТВО(*) КАК Кол, СУММА(СуммаДокумента) КАК Сумма
    ИЗ Документ.ОтчетОРозничныхПродажах
    ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30) И Проведен
    СГРУППИРОВАТЬ ПО НАЧАЛОПЕРИОДА(Дата, ДЕНЬ)
    УПОРЯДОЧИТЬ ПО День
    '''
    by_day_orp = {}
    sel = q.Выполнить().Выбрать()
    while sel.Следующий():
        by_day_orp[s(sel.День)[:10]] = (sel.Кол, sel.Сумма)

    q = conn.NewObject("Запрос")
    q.УстановитьПараметр("Стоп", datetime.datetime.now())
    q.Текст = '''
    ВЫБРАТЬ
        НАЧАЛОПЕРИОДА(Дата, ДЕНЬ) КАК День,
        КОЛИЧЕСТВО(*) КАК Кол, СУММА(СуммаДокумента) КАК Сумма
    ИЗ Документ.ПоступлениеНаличных
    ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30) И Проведен
        И ВидОперации = ЗНАЧЕНИЕ(Перечисление.ВидыОперацийПоступлениеНаличных.РозничнаяВыручка)
    СГРУППИРОВАТЬ ПО НАЧАЛОПЕРИОДА(Дата, ДЕНЬ)
    УПОРЯДОЧИТЬ ПО День
    '''
    by_day_pko = {}
    try:
        sel = q.Выполнить().Выбрать()
        while sel.Следующий():
            by_day_pko[s(sel.День)[:10]] = (sel.Кол, sel.Сумма)
    except Exception as e:
        print(f"  (перечисление РозничнаяВыручка не найдено: {e})")
        # Без фильтра по виду
        q.Текст = '''
        ВЫБРАТЬ
            НАЧАЛОПЕРИОДА(Дата, ДЕНЬ) КАК День,
            КОЛИЧЕСТВО(*) КАК Кол, СУММА(СуммаДокумента) КАК Сумма
        ИЗ Документ.ПоступлениеНаличных
        ГДЕ Дата >= ДОБАВИТЬКДАТЕ(&Стоп, ДЕНЬ, -30) И Проведен
        СГРУППИРОВАТЬ ПО НАЧАЛОПЕРИОДА(Дата, ДЕНЬ)
        УПОРЯДОЧИТЬ ПО День
        '''
        q.УстановитьПараметр("Стоп", datetime.datetime.now())
        sel = q.Выполнить().Выбрать()
        while sel.Следующий():
            by_day_pko[s(sel.День)[:10]] = (sel.Кол, sel.Сумма)

    all_days = sorted(set(by_day_orp.keys()) | set(by_day_pko.keys()))
    print(f"  {'День':12} {'ОРП кол':>8} {'ОРП Σ':>12}  {'ПКО кол':>8} {'ПКО Σ':>12}")
    for d in all_days:
        oc, os_ = by_day_orp.get(d, (0, 0))
        pc, ps_ = by_day_pko.get(d, (0, 0))
        print(f"  {d:12} {oc:>8} {os_ or 0:>12.2f}  {pc:>8} {ps_ or 0:>12.2f}")

if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        import traceback
        traceback.print_exc()
        sys.exit(1)
