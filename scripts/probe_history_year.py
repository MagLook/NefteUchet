hr("5) Пример ручного ОРП за март — что в товарах и оплатах")
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 1 ОРП.Ссылка
ИЗ Документ.ОтчетОРозничныхПродажах КАК ОРП
ГДЕ ОРП.Дата МЕЖДУ &Н1 И &Н2
  И ОРП.Склад.Наименование = "АКЗС Витебский"
УПОРЯДОЧИТЬ ПО ОРП.Дата УБЫВ
"""
q.УстановитьПараметр("Н1", datetime.datetime(2026,3,1))
q.УстановитьПараметр("Н2", datetime.datetime(2026,4,1))
sel = q.Выполнить().Выбрать()
sample = None
while sel.Следующий(): sample = sel.Ссылка; break
if sample:
    obj = sample.ПолучитьОбъект()
    print(f"\n  Документ: {sample}")
    print(f"  Дата: {obj.Дата}  Σ: {float(obj.СуммаДокумента):.2f}  Склад: {obj.Склад}")
    print(f"  Комментарий: {obj.Комментарий!r}")
    print(f"  Товары ({obj.Товары.Количество()}):")
    for i in range(obj.Товары.Количество()):
        r = obj.Товары.Получить(i)
        print(f"    {i+1}. {str(r.Номенклатура):30}  л={float(r.Количество):>10.2f}  ц={float(r.Цена):>7.2f}  Σ={float(r.Сумма):>12.2f}")
    print(f"  Оплата ({obj.Оплата.Количество()}):")
    for i in range(obj.Оплата.Количество()):
        r = obj.Оплата.Получить(i)
        print(f"    {i+1}. вид={str(r.ВидОплаты):30}  Σ={float(r.СуммаОплаты):>12.2f}")
else:
    print("  (нет ОРП за март по АКЗС Витебский)")
