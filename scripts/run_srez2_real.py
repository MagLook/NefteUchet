    print(f"  СРЕЗ 2: kind=retail_sale_sidegoods на эталоне {args.номер}")
    print("=" * 76)

    # [1] Чтение ОРП из ЦБ
    print(f"\n[1/5] Чтение ОРП {args.номер} из ЦБ ЭЛСИ.АЗК...")
    шапка, товары, возвраты, оплаты = прочитать_орп_из_цб(args.номер)
