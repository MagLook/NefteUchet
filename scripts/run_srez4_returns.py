def main():
    парсер = argparse.ArgumentParser()
    парсер.add_argument("--only-json", action="store_true",
                        help="Только сформировать JSON-пакеты, не грузить")
    парсер.add_argument("--scenario", choices=["all", "return-sale", "return-purchase", "idempotency"],
                        default="all", help="Какой тест прогнать")
    args = парсер.parse_args()

    print("=" * 76)
    print(f"  СРЕЗ 4: returns + идемпотентность (--scenario={args.scenario})")
    print("=" * 76)

    результаты = []

    # === Сценарий 1: return_sale ===
    if args.scenario in ("all", "return-sale"):
        print("\n[1] Синтетический return_sale")
        print("-" * 76)
        пакет, pid = синтетический_return_sale()
        путь = сохранить_пакет(пакет, "return-sale")
        print(f"  Сохранён: {путь}")
        if not args.only_json:
            r = загрузить_в_бп_гиг(путь, "return_sale")
            результаты.append(("return_sale", r is not None and r.Ошибки.Количество() == 0))

    # === Сценарий 2: return_purchase ===
    if args.scenario in ("all", "return-purchase"):
        print("\n[2] Синтетический return_purchase")
        print("-" * 76)
        пакет, pid = синтетический_return_purchase()
        путь = сохранить_пакет(пакет, "return-purchase")
        print(f"  Сохранён: {путь}")
        if not args.only_json:
            r = загрузить_в_бп_гиг(путь, "return_purchase")
            результаты.append(("return_purchase", r is not None and r.Ошибки.Количество() == 0))

    # === Сценарий 3: Идемпотентность ===
    if args.scenario in ("all", "idempotency"):
        print("\n[3] Идемпотентность: T1 → T2 (повтор без изменений) → T3 (с изменением хеша)")
        print("-" * 76)
        пакет_1, пакет_2, пакет_3, источник_uuid = сценарий_идемпотентности()

        путь_1 = сохранить_пакет(пакет_1, "idemp-t1")
        путь_2 = сохранить_пакет(пакет_2, "idemp-t2-repeat")
        путь_3 = сохранить_пакет(пакет_3, "idemp-t3-modify")
        print(f"  Источник UUID документа: {источник_uuid}")
        print(f"  T1 (создание):     {путь_1.name}")
        print(f"  T2 (повтор):       {путь_2.name}")
        print(f"  T3 (модификация):  {путь_3.name}")

        if not args.only_json:
            # T1
            r1 = загрузить_в_бп_гиг(путь_1, "T1: создание")
            запись_1 = проверить_документ_в_бп(источник_uuid)
            if запись_1:
                print(f"  [T1] В TL_СоответствиеИсточников: {запись_1['тип']}, хеш={запись_1['хеш'][:16]}...")

            # T2 — повтор
            r2 = загрузить_в_бп_гиг(путь_2, "T2: повтор без изменений")
            запись_2 = проверить_документ_в_бп(источник_uuid)
            если_хеш_сохранился = запись_1 and запись_2 and запись_1["хеш"] == запись_2["хеш"]
            если_документов_не_прибавилось = r2 and r2.Документы.Количество() == 0  # пакет повторный — БП может не создавать
            результаты.append(("idempotency_t2_skip", если_хеш_сохранился))

            # T3 — модификация
            r3 = загрузить_в_бп_гиг(путь_3, "T3: модификация (новый хеш)")
            запись_3 = проверить_документ_в_бп(источник_uuid)
            если_хеш_обновился = запись_1 and запись_3 and запись_1["хеш"] != запись_3["хеш"]
            результаты.append(("idempotency_t3_update", если_хеш_обновился))

    # === Итог ===
    print("\n" + "=" * 76)
    if not результаты:
        print("  --only-json: пакеты сформированы, проверка в БП пропущена")
        return 0
    pass_count = sum(1 for _, ok in результаты if ok)
    fail_count = sum(1 for _, ok in результаты if not ok)
    for name, ok in результаты:
        print(f"  {'PASS' if ok else 'FAIL'}: {name}")
    print(f"\n  ИТОГ: {pass_count} PASS, {fail_count} FAIL")
    return 0 if fail_count == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
