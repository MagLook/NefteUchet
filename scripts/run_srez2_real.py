def сформировать_пакет(шапка, товары, возвраты, оплаты):
    """Сформировать JSON-пакет kind=retail_sale_sidegoods по контракту §7.9."""
    package_id = str(uuidlib.uuid4())
    док = {
        "Тип": "retail_sale_sidegoods",
        "ИсточникUUID": шапка["ИсточникUUID"],
        "Номер": шапка["Номер"],
        "Дата": шапка["Дата"],
        "Проведен": шапка["Проведен"],
        "ПометкаУдаления": шапка["ПометкаУдаления"],
        "Организация": шапка["Организация"],
        "Склад": шапка["Склад"],
        "Подразделение": None,  # для БП ГИГ — `АЗС 208 г. Выборг` (маппит приёмник)
        "Товары": товары,
        "ВозвращенныеТовары": возвраты,
        "Оплаты": оплаты,
    }
    # Канонизация для хеша
    docjson = json.dumps(док, ensure_ascii=False, sort_keys=True)
    док_хеш = hashlib.sha256(docjson.encode("utf-8")).hexdigest()
    док["Хеш"] = док_хеш

    нси = собрать_нси(шапка, товары, возвраты)

    пакет = {
        "ВерсияФормата": "1",
        "ИдентификаторПакета": package_id,
        "Источник": "ЭЛСИ.АЗК ЦБ (probe)",
        "ВремяВыгрузки": dt.datetime.now().isoformat(),
        "НСИ": нси,
        "Документы": [док],
    }
    return пакет, package_id, док_хеш


def собрать_нси(шапка, товары, возвраты):
    """Минимальный набор НСИ для приёмника: организация, склад, номенклатуры."""
    нси = []
    нси.append({
        "Тип": "Организация",
        "ИсточникUUID": шапка["Организация"],
        "Наименование": шапка["ОрганизацияИмя"],
    })
    нси.append({
        "Тип": "Склад",
        "ИсточникUUID": шапка["Склад"],
        "Наименование": шапка["СкладИмя"],
    })
    видимые = set()
    for стр in товары + возвраты:
        uuid = стр["Номенклатура"]
        if uuid in видимые:
            continue
        видимые.add(uuid)
        нси.append({
            "Тип": "Номенклатура",
            "ИсточникUUID": uuid,
            "Код": стр.get("НоменклатураКод", ""),
            "Наименование": стр.get("НоменклатураИмя", ""),
        })
    return нси


