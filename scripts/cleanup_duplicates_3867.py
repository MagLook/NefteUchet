# -*- coding: utf-8 -*-
"""Очистка дублей смены 209/3867 после повторной загрузки.

Найти и удалить:
  - Непроведённые документы с ключом TL|СМЕНА|15|209|3867 (старые, остались после сброса регистрации)
  - Дублирующее старое СписаниеТоваров (если есть пара)

По умолчанию DRY_RUN — только показывает что будет сделано.
Запуск с параметром --apply реально удалит.
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

DRY_RUN = "--apply" not in sys.argv

conn = connect()


def s(v):
    if v is None: return "—"
    try: return str(v)
    except Exception: return repr(v)


print("=" * 90)
print(f"Очистка дублей смены 209/3867  [{'DRY-RUN' if DRY_RUN else 'APPLY'}]")
print("=" * 90)

ТИПЫ = [
    ("Документ.ОтчетОРозничныхПродажах",     "ОРП"),
    ("Документ.ПеремещениеТоваров",          "Перемещ"),
    ("Документ.СписаниеТоваров",             "Списан"),
    ("Документ.ПриходныйКассовыйОрдер",      "ПКО"),
]

# Найти все документы смены 3867 и сгруппировать по «ключевой подпризнак»
все_документы = []
for менеджер, краткое in ТИПЫ:
    q = conn.NewObject("Запрос")
    q.Текст = f"""
    ВЫБРАТЬ Док.Ссылка КАК Ссылка, Док.Номер КАК Ном, Док.Дата КАК Дата,
           Док.Проведен КАК Пров, Док.Комментарий КАК Ком
    ИЗ {менеджер} КАК Док
    ГДЕ Док.Комментарий ПОДОБНО "%3867%"
    УПОРЯДОЧИТЬ ПО Док.Дата
    """
    в = q.Выполнить().Выбрать()
    while в.Следующий():
        ном = s(в.Ном).strip()
        ком = s(в.Ком)
        все_документы.append({
            "тип": краткое, "ссылка": в.Ссылка, "ном": ном,
            "пров": bool(в.Пров), "ком": ком,
            "ключ_подп": ком.split(" | ")[0] if " | " in ком else ком,
        })

# Группировка по подключу (TL|СМЕНА|...|voucher, TL|СМЕНА|...|cards и т.д.)
группы = {}
for д in все_документы:
    группы.setdefault(д["ключ_подп"], []).append(д)

print(f"\nНайдено {len(все_документы)} документов, {len(группы)} уникальных подключей:")
для_удаления = []
для_распроведения_и_удаления = []

for подкл, доки in группы.items():
    print(f"\n  [{подкл}] — {len(доки)} шт")
    if len(доки) == 1:
        д = доки[0]
        print(f"    ✓ оставить: №{д['ном']} (Проведён={д['пров']})  тип={д['тип']}")
        continue
    # >1 = дубли. Стратегия: оставить ПРОВЕДЁННЫЙ свежий, удалить остальные
    доки.sort(key=lambda x: (not x["пров"], x["ном"]))  # сначала проведённые, по номеру
    оставить = None
    for д in доки:
        if д["пров"]:
            if оставить is None:
                # самый свежий проведённый — оставить
                оставить = max([x for x in доки if x["пров"]], key=lambda x: x["ном"])
                break
    if оставить is None:
        # ни одного проведённого — оставить самый свежий по номеру
        оставить = max(доки, key=lambda x: x["ном"])

    print(f"    ✓ оставить: №{оставить['ном']} (Проведён={оставить['пров']})  тип={оставить['тип']}")
    for д in доки:
        if д["ссылка"] is оставить["ссылка"]:
            continue
        if д["пров"]:
            print(f"    ✗ распровести+удалить: №{д['ном']}  тип={д['тип']}")
            для_распроведения_и_удаления.append(д)
        else:
            print(f"    ✗ удалить (не проведён): №{д['ном']}  тип={д['тип']}")
            для_удаления.append(д)

print("\n" + "=" * 90)
print(f"К удалению: {len(для_удаления)} непроведённых + {len(для_распроведения_и_удаления)} проведённых (с распроведением)")
print("=" * 90)

if DRY_RUN:
    print("\n⚠ DRY-RUN. Реально ничего не удалено.")
    print("   Для удаления запустите: py -3-32 cleanup_duplicates_3867.py --apply")
    sys.exit(0)

# APPLY: реальное удаление
print("\nВыполняю реальные действия...")

# 1. Распровести проведённые дубли
for д in для_распроведения_и_удаления:
    try:
        обj = д["ссылка"].ПолучитьОбъект()
        обj.Записать(conn.РежимЗаписиДокумента.ОтменаПроведения)
        print(f"  ✓ распроведён: №{д['ном']}")
    except Exception as e:
        print(f"  ✗ ошибка распроведения №{д['ном']}: {e}")

# 2. Удалить все (пометить на удаление и физически)
все_к_удалению = для_удаления + для_распроведения_и_удаления
for д in все_к_удалению:
    try:
        обj = д["ссылка"].ПолучитьОбъект()
        обj.УстановитьПометкуУдаления(True)
        обj.Удалить()
        print(f"  ✓ удалён: {д['тип']} №{д['ном']}")
    except Exception as e:
        print(f"  ✗ ошибка удаления {д['тип']} №{д['ном']}: {e}")

print("\n" + "=" * 90)
print("Готово")
