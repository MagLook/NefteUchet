print()
print("=" * 100)
print("Записи в РегистрСведений.TL_СтатусыЗагрузки за 20-22.05.2026")
print("=" * 100)

try:
    q3 = conn.NewObject("Запрос")
    q3.Текст = """
    ВЫБРАТЬ
        Рег.КлючЗагрузки КАК Ключ,
        Рег.ВремяЗагрузки КАК Время,
        Рег.Статус КАК Статус,
        Рег.СообщениеОшибки КАК Сообщ
    ИЗ РегистрСведений.TL_СтатусыЗагрузки КАК Рег
    ГДЕ Рег.ВремяЗагрузки >= ДАТАВРЕМЯ(2026,5,20,0,0,0)
      И Рег.ВремяЗагрузки <= ДАТАВРЕМЯ(2026,5,22,23,59,59)
    УПОРЯДОЧИТЬ ПО Рег.ВремяЗагрузки УБЫВ
    """
    в3 = q3.Выполнить().Выбрать()
    н = 0
    while в3.Следующий():
        н += 1
        ключ = str(в3.Ключ or "")
        вр = в3.Время
        стат = str(в3.Статус or "")
        соб = str(в3.Сообщ or "")[:200]
        try:
            врс = вр.strftime("%d.%m %H:%M:%S")
        except Exception:
            врс = str(вр)
        print(f"\n  [{н}] {врс}  Статус={стат}")
        print(f"      Ключ: {ключ}")
        if соб:
            print(f"      Сообщ: {соб}")
    if н == 0:
        print("  (записей нет — TradeLedger в этот период не запускался)")
except Exception as ex:
    print(f"  ОШИБКА: {ex}")

