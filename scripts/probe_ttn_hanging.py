# -*- coding: utf-8 -*-
"""Для каждой 'висящей' ТТН-смены (статус Загружен) проверить есть ли
реальные Перемещение/Комплектация в БД, и каков их статус.
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return ""
    try: return str(v)
    except Exception: return ""


# Возьмём 5 первых ТТН-ключей со статусом Загружен
q = conn.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ ПЕРВЫЕ 5
    Рег.КлючЗагрузки, Рег.ДатаЗагрузки
ИЗ РегистрСведений.TL_СтатусыЗагрузки КАК Рег
ГДЕ Рег.КлючЗагрузки ПОДОБНО "TL|ТТН|%"
  И Рег.Статус = "Загружен"
  И НЕ Рег.КлючЗагрузки ПОДОБНО "TL|ТТН|%|ПЕРЕМ"
  И НЕ Рег.КлючЗагрузки ПОДОБНО "TL|ТТН|%|КОМПЛ"
УПОРЯДОЧИТЬ ПО Рег.ДатаЗагрузки УБЫВ
"""
в = q.Выполнить().Выбрать()
базовые = []
while в.Следующий():
    базовые.append(s(в.КлючЗагрузки))

print(f"Возьмём 5 ТТН-ключей (без подключей):")
for к in базовые:
    print(f"  {к}")

print()
# Для каждого — посмотреть подключи в регистре и документы в БД
for базК in базовые:
    print(f"\n{'='*100}")
    print(f"ТТН-ключ: {базК}")
    print('-' * 100)

    # 1. Все ключи в регистре с этим базовым
    q1 = conn.NewObject("Запрос")
    q1.УстановитьПараметр("К", базК)
    q1.УстановитьПараметр("М", базК + "|%")
    q1.Текст = """
    ВЫБРАТЬ КлючЗагрузки, Статус, ТипДокумента
    ИЗ РегистрСведений.TL_СтатусыЗагрузки
    ГДЕ КлючЗагрузки = &К ИЛИ КлючЗагрузки ПОДОБНО &М
    УПОРЯДОЧИТЬ ПО КлючЗагрузки
    """
    в1 = q1.Выполнить().Выбрать()
    print(f"\n  Записи в регистре:")
    while в1.Следующий():
        print(f"    {s(в1.КлючЗагрузки):<45} {s(в1.Статус):<12} {s(в1.ТипДокумента)}")

    # 2. Реальные документы по этим ключам
    print(f"\n  Документы в БД по комментарию:")
    нашли = False
    for менеджер, краткое in [
        ("Документ.ПеремещениеТоваров", "Перемещ"),
        ("Документ.КомплектацияНоменклатуры", "Компл"),
        ("Документ.ПоступлениеТоваровУслуг", "ПТУ"),
    ]:
        q2 = conn.NewObject("Запрос")
        q2.УстановитьПараметр("М", базК + "%")
        q2.Текст = f"""
        ВЫБРАТЬ Док.Номер, Док.Дата, Док.Проведен, Док.ПометкаУдаления, Док.Комментарий
        ИЗ {менеджер} КАК Док
        ГДЕ ВЫРАЗИТЬ(Док.Комментарий КАК СТРОКА(300)) ПОДОБНО &М
        """
        в2 = q2.Выполнить().Выбрать()
        while в2.Следующий():
            нашли = True
            try: дт = в2.Дата.strftime("%d.%m")
            except: дт = s(в2.Дата)
            пр = "✓" if в2.Проведен else "○"
            пу = " ✗ПОМ" if в2.ПометкаУдаления else ""
            print(f"    [{краткое:<8}] {пр} №{s(в2.Номер).strip():<14} {дт}{пу}  ком: {s(в2.Комментарий)[:60]}")
    if not нашли:
        print(f"    ⚠ Ни одного документа не найдено по комментарию начинающемуся с {базК}")
