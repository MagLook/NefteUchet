def сохранить_пакет(пакет, метка):
    """Сохранить пакет с меткой в имени для отладки."""
    package_id = пакет["ИдентификаторПакета"]
    ts = int(dt.datetime.now().timestamp())
    путь = OWNCLOUD_DIR / f"tl_{метка}_{package_id}_{ts}.json"
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(пакет, f, ensure_ascii=False, indent=2)
    return путь


def загрузить_в_бп_гиг(путь_пакета, comment):
    print(f"\n  [{comment}] Подключение к БП ГИГ: {BP_BASE}")
    connector = win32com.client.Dispatch("V83.COMConnector")
    cs = f'File="{BP_BASE}";Usr="{BP_USER}";Pwd="{BP_PWD}";'
    conn = connector.Connect(cs)
    try:
        пакет_объект = conn.TL_HTTPКлиентЦБ.ПрочитатьПакетИзФайла(str(путь_пакета))
        результат = conn.TL_СопуткаСервис.ОбработатьПакет(пакет_объект, True)
        print(f"  Документов: {результат.Документы.Количество()} | Ошибок: {результат.Ошибки.Количество()}")
        if результат.Ошибки.Количество() > 0:
            for i in range(результат.Ошибки.Количество()):
                print(f"    [{i+1}] {результат.Ошибки.Получить(i)}")
        return результат
    except Exception as e:
        print(f"  [EXPECTED FAIL] {e}")
        return None


def проверить_документ_в_бп(источник_uuid):
    """После загрузки — проверить, что в БП ГИГ создан/обновлён ровно один документ."""
    connector = win32com.client.Dispatch("V83.COMConnector")
    cs = f'File="{BP_BASE}";Usr="{BP_USER}";Pwd="{BP_PWD}";'
    conn = connector.Connect(cs)

    # Поиск через TL_СоответствиеИсточников
    q = conn.NewObject("Запрос")
    q.Текст = (
        "ВЫБРАТЬ Тип, ИсточникUUID, СсылкаОбъект, ХешПоследнегоПакета, ДатаПоследнейЗагрузки "
        "ИЗ РегистрСведений.TL_СоответствиеИсточников "
        "ГДЕ ИсточникUUID = &UUID"
    )
    q.УстановитьПараметр("UUID", источник_uuid)
    v = q.Выполнить().Выбрать()
    if v.Следующий():
        return {
            "тип": str(v.Тип),
            "ссылка": str(v.СсылкаОбъект),
            "хеш": str(v.ХешПоследнегоПакета),
            "дата": str(v.ДатаПоследнейЗагрузки),
        }
    return None


