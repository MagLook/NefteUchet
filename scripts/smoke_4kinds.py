# -*- coding: utf-8 -*-
"""
Smoke 4 новых kind на стороне БП ГИГ.

Берёт самый свежий пакет смены 09.04 АЗС 208 из C:\\TL_BP_Export\\ (там полный
набор 7 kind — 2 purchase + 1 retail + 1 production + 1 inventory + 1 gain +
1 writeoff + 4 transfer), вызывает TL_СопуткаСервис.ОбработатьПакет.

Цель: проверить, что новые обработчики (Inventory/Gain/Writeoff/Transfer)
создают документы в БП ГИГ без падений.
"""
import sys
import os
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

КАТАЛОГ = r"C:\TL_BP_Export"

# Найти самый свежий файл смены 09.04
кандидаты = [
    f for f in os.listdir(КАТАЛОГ)
    if "2082080904202601" in f and f.endswith(".json")
]
if not кандидаты:
    print("Нет файла смены 09.04")
    sys.exit(1)

# Берём свежайший по mtime
кандидаты.sort(key=lambda f: os.path.getmtime(os.path.join(КАТАЛОГ, f)))
файл = os.path.join(КАТАЛОГ, кандидаты[-1])
print(f"Файл: {файл}")
print(f"Размер: {os.path.getsize(файл)} байт\n")

conn = connect()

# Прямой вызов TL_СопуткаСервис.ОбработатьПакетИзФайла (обёртка)
print("--- ОбработатьПакетИзФайла (Проводить=Истина) ---")
Результат = conn.TL_СопуткаСервис.ОбработатьПакетИзФайла(файл, True)

# 3. Распечатать результат
print(f"  Статус:               {Результат.Статус}")
print(f"  ИдентификаторПакета:  {Результат.ИдентификаторПакета}")
print(f"  ВсегоДокументов:      {Результат.ВсегоДокументов}")
print(f"  ВсегоНСИ:             {Результат.ВсегоНСИ}")
print(f"  Создано документов:   {Результат.Документы.Количество()}")

print(f"\n  Документы (созданные/обновлённые):")
for i in range(Результат.Документы.Количество()):
    ссылка = Результат.Документы.Получить(i)
    try:
        мд = ссылка.Метаданные()
        print(f"    {i+1}. {мд.Имя}: {ссылка}")
    except Exception:
        print(f"    {i+1}. {ссылка}")

print(f"\n  Ошибки ({Результат.Ошибки.Количество()}):")
for i in range(Результат.Ошибки.Количество()):
    print(f"    · {Результат.Ошибки.Получить(i)}")
