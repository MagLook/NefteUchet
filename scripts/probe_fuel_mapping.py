# -*- coding: utf-8 -*-
"""Как у нас сейчас в БД ГИГ настроен маппинг service_code → Номенклатура.
Источники: справочник TL_ВидыТоплива + key-value в TL_Настройки."""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tl_config import connect

conn = connect()


def s(v):
    if v is None: return "—"
    try: return str(v)
    except Exception: return "?"


# 1. Справочник TL_ВидыТоплива
print("=" * 90)
print("1. Справочник TL_ВидыТоплива")
print("=" * 90)
try:
    q = conn.NewObject("Запрос")
    q.Текст = """
    ВЫБРАТЬ Ссылка, КодВнешний, Наименование, НоменклатураТонны
    ИЗ Справочник.TL_ВидыТоплива
    ГДЕ НЕ ПометкаУдаления
    УПОРЯДОЧИТЬ ПО КодВнешний
    """
    в = q.Выполнить().Выбрать()
    нашли = False
    while в.Следующий():
        нашли = True
        print(f"\n  Код={s(в.КодВнешний):<5} {s(в.Наименование):<20}")
        print(f"    НоменклатураТонны = {s(в.НоменклатураТонны)}")
        # ТЧ МаппингПоСтанциям
        q2 = conn.NewObject("Запрос")
        q2.УстановитьПараметр("С", в.Ссылка)
        q2.Текст = """
        ВЫБРАТЬ ТЧ.АЗС.Наименование КАК АЗС, ТЧ.НоменклатураЛитры
        ИЗ Справочник.TL_ВидыТоплива.МаппингПоСтанциям КАК ТЧ
        ГДЕ ТЧ.Ссылка = &С
        УПОРЯДОЧИТЬ ПО ТЧ.АЗС.Наименование
        """
        в2 = q2.Выполнить().Выбрать()
        кол = 0
        while в2.Следующий():
            кол += 1
            print(f"      [{кол}] АЗС {s(в2.АЗС):<35} → {s(в2.НоменклатураЛитры)}")
        if кол == 0:
            print(f"      (нет АЗС в маппинге)")
    if not нашли:
        print("\n  Справочник пуст — нет ни одного вида топлива")
except Exception as e:
    print(f"  ОШИБКА: {e}")

# 2. Key-value регистр TL_Настройки
print("\n\n" + "=" * 90)
print("2. Key-value в TL_Настройки (Топливо_*)")
print("=" * 90)
q3 = conn.NewObject("Запрос")
q3.Текст = """
ВЫБРАТЬ Ключ, Значение
ИЗ РегистрСведений.TL_Настройки
ГДЕ Ключ ПОДОБНО "Топливо_%"
УПОРЯДОЧИТЬ ПО Ключ
"""
в3 = q3.Выполнить().Выбрать()
нашли = False
while в3.Следующий():
    нашли = True
    print(f"  {s(в3.Ключ):<30} = {s(в3.Значение)}")
if not нашли:
    print("  Записей нет")

# 3. Какие service_code реально приходили из STS за май 2026 (по проводкам в БД)
print("\n\n" + "=" * 90)
print("3. Номенклатура из проводок ОРП за май 2026 (что реально загружено)")
print("=" * 90)
q4 = conn.NewObject("Запрос")
q4.Текст = """
ВЫБРАТЬ
    ТЧ.Номенклатура.Наименование КАК Ном,
    КОЛИЧЕСТВО(*) КАК Стр,
    СУММА(ТЧ.Количество) КАК Литры
ИЗ Документ.ОтчетОРозничныхПродажах.Товары КАК ТЧ
ГДЕ ТЧ.Ссылка.Дата >= ДАТАВРЕМЯ(2026,5,1,0,0,0)
  И ТЧ.Ссылка.Дата <= ДАТАВРЕМЯ(2026,5,15,23,59,59)
  И ТЧ.Ссылка.Проведен
  И НЕ ТЧ.Ссылка.ПометкаУдаления
  И ВЫРАЗИТЬ(ТЧ.Ссылка.Комментарий КАК СТРОКА(300)) ПОДОБНО "TL|%"
СГРУППИРОВАТЬ ПО ТЧ.Номенклатура.Наименование
УПОРЯДОЧИТЬ ПО Литры УБЫВ
"""
в4 = q4.Выполнить().Выбрать()
print(f"\n  {'Номенклатура':<35} {'Строк':>6} {'Литры':>14}")
print("  " + "-" * 60)
while в4.Следующий():
    print(f"  {s(в4.Ном):<35} {int(в4.Стр):>6} {float(в4.Литры or 0):>14,.2f}".replace(",", " "))
