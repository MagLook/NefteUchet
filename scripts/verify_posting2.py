"""Verify posting results. Run: py -3.13-32 scripts/verify_posting2.py"""
import pythoncom, io
pythoncom.CoInitialize()
import win32com.client

conn = win32com.client.Dispatch("V83.COMConnector")
ib = conn.Connect(r'File="D:\Users\magsp\GIG Base2";Usr="Гайворонская Татьяна";Pwd="12345"')

out = io.open(r"D:\Users\magsp\ELSYPLUS\NefteUchet\build\verify_posting2.txt", "w", encoding="utf-8")

# 1. ОтчётОРозничныхПродажах
out.write("=== ОтчётОРозничныхПродажах ===\n")
q = ib.NewObject("Query")
q.Text = """ВЫБРАТЬ Ссылка, Номер, Дата, Проведен, Комментарий
ИЗ Документ.ОтчетОРозничныхПродажах
ГДЕ Комментарий ПОДОБНО &М И НЕ ПометкаУдаления УПОРЯДОЧИТЬ ПО Дата УБЫВ"""
q.УстановитьПараметр("М", "%TL|СМЕНА%")
r = q.Выполнить().Выбрать()
while r.Следующий():
    out.write(f"\n  {r.Номер} {r.Дата} Проведён:{r.Проведен}\n  {r.Комментарий}\n")
    doc = r.Ссылка.ПолучитьОбъект()
    out.write(f"  Склад: {doc.Склад.Наименование}\n")
    for i in range(doc.Товары.Количество()):
        row = doc.Товары.Получить(i)
        out.write(f"    {row.Номенклатура.Наименование}: {row.Количество} x {row.Цена} = {row.Сумма}\n")
    if r.Проведен:
        q2 = ib.NewObject("Query")
        q2.Text = """ВЫБРАТЬ НомерСтроки, СчетДт.Код КАК Дт, СчетКт.Код КАК Кт, Сумма, КоличествоКт, Содержание
        ИЗ РегистрБухгалтерии.Хозрасчетный ГДЕ Регистратор = &Д УПОРЯДОЧИТЬ ПО НомерСтроки"""
        q2.УстановитьПараметр("Д", r.Ссылка)
        r2 = q2.Выполнить().Выбрать()
        out.write("  Проводки:\n")
        while r2.Следующий():
            out.write(f"    [{r2.НомерСтроки}] Дт:{r2.Дт} Кт:{r2.Кт} {r2.Сумма} [{r2.Содержание}]\n")

# 2. Перемещения
out.write("\n\n=== Перемещения ===\n")
